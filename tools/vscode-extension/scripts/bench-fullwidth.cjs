/** 生成模拟方言代码：每行一条语句，含字符串/注释/关键字，末尾可拼接 */
function 生成文档(行数) {
    const 行们 = [];
    for (let i = 0; i < 行数; i++) {
        if (i % 7 === 0) {
            行们.push(`    // 注释行：计算第 ${i} 个中间结果`);
        } else if (i % 7 === 3) {
            行们.push(`    让 文本${i} = "字符串内容 ${i}";`);
        } else {
            行们.push(`    让 结果${i} = 值${i} + 偏移${i} * 2;`);
        }
    }
    return 行们.join('\n');
}

