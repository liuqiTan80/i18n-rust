function 场景_单字符输入() {
    console.log('\n====================================================');
    console.log('场景 1/2：单字符按键（ASCII 95% + 全角 5%，光标在文档末尾）');
    console.log('====================================================');

    for (const [名称, 行数, 按键数] of [
        ['文档 A（500 行 ≈ 15KB，典型教学文件）', 500, 1000],
        ['文档 B（5000 行 ≈ 150KB，大文档压力）', 5000, 200]
    ]) {
        const 文档 = 构建文档(生成文档(行数));
        const 末尾行 = 文档.行起始们.length - 1;
        const 末尾列 = 文档.文本.length - 文档.行起始们[末尾行];

        // 按键序列：5% 全角（中文输入法上屏场景），95% 普通输入
        const 按键们 = [];
        for (let i = 0; i < 按键数; i++) {
            按键们.push(i % 20 === 0 ? '，' : i % 20 === 10 ? 'a' : '字');
        }

        const 旧耗时 = 测中位数(() => {
            for (const 键 of 按键们) {
                旧流程输入(文档, 键, 末尾行, 末尾列);
            }
        }, 1);
        const 新耗时 = 测中位数(() => {
            for (const 键 of 按键们) {
                新流程输入(文档, 键, 末尾行, 末尾列);
            }
        }, 1);

        报告(名称, [
            ['旧流程总耗时', `${旧耗时.toFixed(1)} ms`],
            ['新流程总耗时', `${新耗时.toFixed(1)} ms`],
            ['单次按键均值', `${(旧耗时 / 按键数 * 1000).toFixed(2)} µs → ${(新耗时 / 按键数 * 1000).toFixed(2)} µs`],
            ['加速比', `${(旧耗时 / 新耗时).toFixed(1)}×`]
        ]);
    }
}

function 场景_多全角输入() {
    console.log('\n====================================================');
    console.log('场景 3：一次输入 5 个全角符号（粘贴/输入法上屏 k=5，光标在文档末尾）');
    console.log('====================================================');
    const 文档 = 构建文档(生成文档(5000));
    const 末尾行 = 文档.行起始们.length - 1;
    const 末尾列 = 文档.文本.length - 文档.行起始们[末尾行];
    const 文本 = '，。；：？'; // 5 个全角符号
    const 次数 = 50;

    const 旧耗时 = 测中位数(() => 旧流程输入(文档, 文本, 末尾行, 末尾列), 次数);
    const 新耗时 = 测中位数(() => 新流程输入(文档, 文本, 末尾行, 末尾列), 次数);

    报告('文档 B（5000 行）+ k=5 全角符号', [
        ['旧流程总耗时', `${旧耗时.toFixed(1)} ms`],
        ['新流程总耗时', `${新耗时.toFixed(1)} ms`],
        ['单次均值', `${格式(旧耗时, 次数)} → ${格式(新耗时, 次数)}`],
        ['加速比', `${(旧耗时 / 新耗时).toFixed(1)}×`]
    ]);
}

function 场景_扫描起点对比() {
    console.log('\n====================================================');
    console.log('场景 4：词法扫描起点对比（被否方案量化：行首起点 vs 文档开头）');
    console.log('  注意：行首起点在块注释/原始字符串跨行时结果错误，此处仅量化时间收益');
    console.log('====================================================');
    const 文档 = 构建文档(生成文档(5000));
    const 末尾行 = 文档.行起始们.length - 1;
    const 末尾列 = 文档.文本.length - 文档.行起始们[末尾行];
    const 前缀 = 文档.文本.slice(0, 偏移(文档, 末尾行, 末尾列));
    const 行首 = 文档.文本.slice(文档.行起始们[末尾行], 偏移(文档, 末尾行, 末尾列));
    const 次数 = 30;

    const 全文耗时 = 测中位数(() => 扫描词法状态(前缀), 次数);
    const 行首耗时 = 测中位数(() => 扫描词法状态(行首), 次数);

    报告('文档 B（5000 行）末尾输入', [
        ['全文前缀长度', `${前缀.length} 字符`],
        ['行首前缀长度', `${行首.length} 字符`],
        ['全文起点扫描', `${格式(全文耗时, 次数)}`],
        ['行首起点扫描', `${格式(行首耗时, 次数)}`],
        ['时间比', `${(全文耗时 / 行首耗时).toFixed(1)}×（行首收益量级）`]
    ]);
}

function 场景_单遍多位置() {
    console.log('\n====================================================');
    console.log('场景 5：单遍多位置扫描 vs k 次单位置扫描（k=5）');
    console.log('====================================================');
    const 文档 = 构建文档(生成文档(5000));
    const 末尾行 = 文档.行起始们.length - 1;
    const 末尾列 = 文档.文本.length - 文档.行起始们[末尾行];
    const 前缀 = 文档.文本.slice(0, 偏移(文档, 末尾行, 末尾列));
    // 模拟 5 个全角符号的偏移（间距 1，模拟连续输入）
    const 偏移们 = [];
    for (let i = 0; i < 5; i++) {
        偏移们.push(前缀.length - 5 + i);
    }
    const 次数 = 30;

    const 单遍耗时 = 测中位数(() => 扫描词法状态们(前缀, 偏移们), 次数);
    const 多次耗时 = 测中位数(() => {
        for (const o of 偏移们) {
            扫描词法状态(前缀.slice(0, o));
        }
    }, 次数);

    报告('文档 B（5000 行）末尾，k=5', [
        ['单遍扫描', `${格式(单遍耗时, 次数)}`],
        ['5 次单位置扫描', `${格式(多次耗时, 次数)}`],
        ['加速比', `${(多次耗时 / 单遍耗时).toFixed(1)}×`]
    ]);
}

function 场景_正则过滤() {
    console.log('\n====================================================');
    console.log('场景 6：ASCII/母语输入的正则先行过滤（无全角提前返回）');
    console.log('====================================================');
    const 文档 = 构建文档(生成文档(5000));
    const 末尾行 = 文档.行起始们.length - 1;
    const 末尾列 = 文档.文本.length - 文档.行起始们[末尾行];
    const 次数 = 5000;

    // 仅对比"完整事件处理"中新增的部分：正则 test vs 位置数组分配
    const 正则耗时 = 测中位数(() => 全角符号检测正则.test('a'), 次数);
    const 分配耗时 = 测中位数(() => 计算插入字符位置们(末尾行, 末尾列, 'a'), 次数);
    const 正则长文本 = 测中位数(() => 全角符号检测正则.test('让 x = 1; // 普通中文输入行'.repeat(10)), 次数);
    const 分配长文本 = 测中位数(() => 计算插入字符位置们(末尾行, 末尾列, '让 x = 1; // 普通中文输入行'.repeat(10)), 次数);

    报告('文档 B（5000 行）末尾', [
        ['单字符：正则 test', `${格式(正则耗时, 次数)}`],
        ['单字符：位置数组分配', `${格式(分配耗时, 次数)}`],
        ['120 字符：正则 test', `${格式(正则长文本, 次数)}`],
        ['120 字符：位置数组分配', `${格式(分配长文本, 次数)}`]
    ]);
}

