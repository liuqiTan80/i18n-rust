/**
 * 前端热路径基准测量（开发工具，非发布产物）
 *
 * 量化全角转换优化前后的实际收益，并为被否方案（行首起点扫描、
 * 单遍多位置扫描）提供决策数据。
 *
 * 用法：先 npm run compile（生成 out/），再执行：
 *   node scripts/bench-fullwidth.cjs
 *
 * 模拟假设：
 * - 文档为字符串（模拟 vscode.TextDocument.getText/offsetAt，getText 成本
 *   近似为 slice 成本，真实 VS Code 的 Buffer 切片略快于此近似）
 * - 每次按键触发一次 onDidChangeTextDocument 事件（单 contentChange）
 */

const { performance } = require('node:perf_hooks');
const {
    全角符号映射,
    全角符号检测正则,
    扫描词法状态,
    扫描词法状态们,
    计算插入字符位置们,
    应转换全角
} = require('../out/fullwidth-convert.js');

// ============================================================
// 工具：模拟 TextDocument（行起始索引实现 offsetAt）
// ============================================================

function 构建文档(文本) {
    const 行起始们 = [0];
    for (let i = 0; i < 文本.length; i++) {
        if (文本[i] === '\n') {
            行起始们.push(i + 1);
        }
    }
    return { 文本, 行起始们 };
}

/** 行列 → 字符偏移（模拟 document.offsetAt，O(1)） */
function 偏移(文档, 行, 列) {
    return 文档.行起始们[行] + 列;
}

// ============================================================
// 新旧流程（旧流程为优化前实现的内联复现，含 k 次全文扫描）
// ============================================================

/** 旧流程：每次按键，对每个全角字符各取一次前缀并各扫一遍 */
function 旧流程输入(文档, 变更文本, 起始行, 起始列) {
    const 位置们 = 计算插入字符位置们(起始行, 起始列, 变更文本);
    for (const { 索引, 行, 列 } of 位置们) {
        const 字符 = 变更文本[索引];
        const 半角 = 全角符号映射[字符];
        if (!半角) {
            continue;
        }
        // 旧实现：getText(文档开头 → 插入位置) + 全文词法扫描
        const 前缀 = 文档.文本.slice(0, 偏移(文档, 行, 列));
        if (!应转换全角(扫描词法状态(前缀), 字符)) {
            continue;
        }
    }
}

/** 新流程：正则先行过滤 + k=1 快速路径 / 单遍扫描（当前实现） */
function 新流程输入(文档, 变更文本, 起始行, 起始列) {
    if (!全角符号检测正则.test(变更文本)) {
        return;
    }
    const 位置们 = 计算插入字符位置们(起始行, 起始列, 变更文本);
    const 候选们 = [];
    for (const { 索引, 行, 列 } of 位置们) {
        const 字符 = 变更文本[索引];
        const 半角 = 全角符号映射[字符];
        if (半角) {
            候选们.push({ 字符, 半角, 行, 列 });
        }
    }
    if (候选们.length === 0) {
        return;
    }
    const 最后 = 候选们[候选们.length - 1];
    const 前缀 = 文档.文本.slice(0, 偏移(文档, 最后.行, 最后.列));
    if (候选们.length === 1) {
        const 候选 = 候选们[0];
        if (应转换全角(扫描词法状态(前缀), 候选.字符)) {
            return;
        }
    } else {
        const 偏移们 = 候选们.map(({ 行, 列 }) => 偏移(文档, 行, 列));
        const 状态们 = 扫描词法状态们(前缀, 偏移们);
        for (let k = 0; k < 候选们.length; k++) {
            if (!应转换全角(状态们[k], 候选们[k].字符)) {
                return;
            }
        }
    }
}

