/** 运行 fn 共 次数 次，返回总耗时（ms），预热后测量 */
function 测总耗时(fn, 次数) {
    for (let i = 0; i < Math.min(次数, 20); i++) {
        fn();
    }
    const 开始 = performance.now();
    for (let i = 0; i < 次数; i++) {
        fn();
    }
    return performance.now() - 开始;
}

/** 取 轮次 轮的中位数（ms） */
function 测中位数(fn, 次数, 轮次 = 5) {
    const 样本们 = [];
    for (let 轮 = 0; 轮 < 轮次; 轮++) {
        样本们.push(测总耗时(fn, 次数));
    }
    样本们.sort((a, b) => a - b);
    return 样本们[Math.floor(样本们.length / 2)];
}

function 格式(ms, 次数) {
    return `${(ms / 次数 * 1000).toFixed(2)} µs/次`;
}

function 报告(标题, 行们) {
    console.log(`\n== ${标题} ==`);
    for (const [标签, 值] of 行们) {
        console.log(`  ${标签.padEnd(28)} ${值}`);
    }
}

