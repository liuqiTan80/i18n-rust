/**
 * LSP 自动重启的时间窗口判定（纯逻辑，不依赖 VS Code API，便于单测）
 *
 * 采用时间窗口统计：仅累计最近「重启窗口毫秒」内的异常退出，
 * 窗口外的旧崩溃自动过期，避免偶发崩溃跨周月累计导致永久停止自动重启；
 * 窗口内达「重启窗口内上限」次仍可防止死循环刷屏。
 */

/** 统计窗口时长（毫秒） */
export const 重启窗口毫秒 = 10 * 60 * 1000;
/** 窗口内允许的自动重启次数上限 */
export const 重启窗口内上限 = 20;

/**
 * 记录本次异常退出并修剪窗口外旧记录。
 * 返回修剪后的时间戳序列与窗口内累计次数（含本次）。
 */
export function 更新退出时间戳(
    时间戳们: readonly number[],
    现在: number
): { 修剪后: number[]; 次数: number } {
    const 修剪后 = 时间戳们.filter(时间戳 => 现在 - 时间戳 < 重启窗口毫秒);
    修剪后.push(现在);
    return { 修剪后, 次数: 修剪后.length };
}