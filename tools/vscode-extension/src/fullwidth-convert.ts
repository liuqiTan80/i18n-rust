/**
 * 全角符号自动转换（纯逻辑，不依赖 VS Code API）
 *
 * 在代码区（非字符串、非注释）输入的全角符号自动转换为半角，
 * 字符串与注释内的全角符号保持原样（内容可能是有意义的中文标点）。
 */

/**
 * 全角符号 → 半角符号映射表
 * 覆盖 U+FF01~U+FF5E 全角 ASCII 区域及中文引号等常见符号
 */
export const 全角符号映射: Readonly<Record<string, string>> = {
    '，': ',', '。': '.', '；': ';', '：': ':', '？': '?', '！': '!',
    '（': '(', '）': ')', '【': '[', '】': ']', '｛': '{', '｝': '}',
    '［': '[', '］': ']', '、': ',', '＝': '=', '＋': '+', '－': '-',
    '＊': '*', '／': '/', '％': '%', '＃': '#', '＄': '$', '＠': '@',
    '＆': '&', '＿': '_', '｜': '|', '＜': '<', '＞': '>', '～': '~',
    '＾': '^', '＼': '\\', '　': ' ', '‘': "'", '’': "'",
    '“': '"', '”': '"'
};

/**
 * 词法状态：Rust 源码中插入位置所处的区域
 */
export enum 词法状态 {
    代码 = 0,
    双引号字符串 = 1,
    单引号字符 = 2,
    行注释 = 3,
    块注释 = 4,
    原始字符串 = 5
}

/**
 * 扫描指定文本前缀，返回扫描结束时的词法状态
 *
 * 支持：双引号字符串（含转义）、单引号字符（区分生命周期 'a）、
 * 行注释 //、嵌套块注释 /* *\/、原始字符串 r"..." 与 r#"..."#。
 */
export function 扫描词法状态(前缀: string): 词法状态 {
    let 状态 = 词法状态.代码;
    let 块注释深度 = 0;
    let 原始字符串井号数 = 0;

    for (let i = 0; i < 前缀.length; i++) {
        const 字符 = 前缀[i];
        const 下一字符 = 前缀[i + 1];
        switch (状态) {
            case 词法状态.代码:
                if (字符 === '"') {
                    状态 = 词法状态.双引号字符串;
                } else if (字符 === "'") {
                    // 生命周期标注 'a（后跟字母且再后非 '）不是字符字面量
                    const 后 = 前缀[i + 1];
                    const 再后 = 前缀[i + 2];
                    const 是生命周期 = /[A-Za-z_]/.test(后 ?? '') && 再后 !== "'";
                    if (!是生命周期) {
                        状态 = 词法状态.单引号字符;
                    }
                } else if (字符 === '/' && 下一字符 === '/') {
                    状态 = 词法状态.行注释;
                    i++;
                } else if (字符 === '/' && 下一字符 === '*') {
                    状态 = 词法状态.块注释;
                    块注释深度 = 1;
                    i++;
                } else if (字符 === 'r' && (下一字符 === '"' || 下一字符 === '#')) {
                    // 原始字符串：r"..." 或 r#"..."#（支持多井号）
                    let 井号 = 0;
                    let j = i + 1;
                    while (前缀[j] === '#') {
                        井号++;
                        j++;
                    }
                    if (前缀[j] === '"') {
                        状态 = 词法状态.原始字符串;
                        原始字符串井号数 = 井号;
                        i = j;
                    }
                }
                break;
            case 词法状态.双引号字符串:
                if (字符 === '\\') {
                    i++; // 跳过转义字符（\" \\ 等）
                } else if (字符 === '"') {
                    状态 = 词法状态.代码;
                }
                break;
            case 词法状态.单引号字符:
                if (字符 === '\\') {
                    i++;
                } else if (字符 === "'") {
                    状态 = 词法状态.代码;
                }
                break;
            case 词法状态.行注释:
                if (字符 === '\n') {
                    状态 = 词法状态.代码;
                }
                break;
            case 词法状态.块注释:
                // Rust 块注释支持嵌套：/* /* */ */
                if (字符 === '/' && 下一字符 === '*') {
                    块注释深度++;
                    i++;
                } else if (字符 === '*' && 下一字符 === '/') {
                    块注释深度--;
                    i++;
                    if (块注释深度 === 0) {
                        状态 = 词法状态.代码;
                    }
                }
                break;
            case 词法状态.原始字符串:
                // r#"..."#：遇到 " 后必须跟够数量 # 才算结束
                if (字符 === '"') {
                    let 井号数 = 0;
                    let j = i + 1;
                    while (井号数 < 原始字符串井号数 && 前缀[j] === '#') {
                        井号数++;
                        j++;
                    }
                    if (井号数 === 原始字符串井号数) {
                        状态 = 词法状态.代码;
                        i = j - 1;
                    }
                }
                break;
        }
    }
    return 状态;
}
