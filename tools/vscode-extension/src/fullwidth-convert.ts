/**
 * 全角符号自动转换（纯逻辑，不依赖 VS Code API）
 *
 * 在代码区（非字符串、非注释）输入的全角符号自动转换为半角，
 * 字符串与注释内的全角符号保持原样（内容可能是有意义的中文标点）。
 */

/**
 * 全角符号 → 半角符号映射表
 * 覆盖 U+FF01~U+FF5E 全角 ASCII 区域及中文引号等常见符号
 */
export const 全角符号映射: Readonly<Record<string, string>> = {
    '，': ',', '。': '.', '；': ';', '：': ':', '？': '?', '！': '!',
    '（': '(', '）': ')', '【': '[', '】': ']', '｛': '{', '｝': '}',
    '［': '[', '］': ']', '、': ',', '＝': '=', '＋': '+', '－': '-',
    '＊': '*', '／': '/', '％': '%', '＃': '#', '＄': '$', '＠': '@',
    '＆': '&', '＿': '_', '｜': '|', '＜': '<', '＞': '>', '～': '~',
    '＾': '^', '＼': '\\', '　': ' ', '‘': "'", '’': "'",
    '“': '"', '”': '"'
};

/**
 * 全角符号检测正则（由映射表键构建）
 *
 * 输入热路径先行过滤：绝大多数按键/粘贴内容不含全角符号，
 * 命中才继续计算插入位置与词法扫描（避免每次输入分配位置数组）。
 */
export const 全角符号检测正则: RegExp = new RegExp(`[${Object.keys(全角符号映射).join('')}]`);

/**
 * 判断指定词法状态与字符组合是否应执行全角→半角转换
 *
 * 代码区一律转换；字符串/注释内保持原样（内容可能是有意义的母语标点）；
 * 例外：普通双引号字符串内的中文引号（“ ”）仍转换——中文输入法配对输入时
 * 右引号落在已打开的字符串内，不转换会导致字符串定界符不匹配。
 */
export function 应转换全角(状态: 词法状态, 字符: string): boolean {
    if (状态 === 词法状态.代码) {
        return true;
    }
    return 状态 === 词法状态.双引号字符串 && (字符 === '“' || 字符 === '”');
}

/**
 * 词法状态：Rust 源码中插入位置所处的区域
 */
export enum 词法状态 {
    代码 = 0,
    双引号字符串 = 1,
    单引号字符 = 2,
    行注释 = 3,
    块注释 = 4,
    原始字符串 = 5
}

/**
 * 计算一段插入文本中每个非换行字符在文档中的位置（纯函数，可单测）
 *
 * contentChange 的 range.start 是插入起点；插入文本可能包含换行
 * （粘贴多行内容），后续字符的行/列必须逐字符推进：
 * 遇 \n（或 \r\n / \r）行号 +1、列归零。
 *
 * 返回项含原文本索引（索引），用于回查对应字符。
 */
export function 计算插入字符位置们(
    起始行: number,
    起始列: number,
    文本: string
): { 索引: number; 行: number; 列: number }[] {
    const 位置们: { 索引: number; 行: number; 列: number }[] = [];
    let 行 = 起始行;
    let 段首列 = 起始列;
    let 段内偏移 = 0;
    for (let i = 0; i < 文本.length; i++) {
        const 字符 = 文本[i];
        if (字符 === '\n' || 字符 === '\r') {
            // \r\n 视为一个换行：\n 轮不再重复换行
            if (字符 === '\r' && 文本[i + 1] === '\n') {
                i++;
            }
            行++;
            段首列 = 0;
            段内偏移 = 0;
            continue;
        }
        位置们.push({ 索引: i, 行, 列: 段首列 + 段内偏移 });
        段内偏移++;
    }
    return 位置们;
}

/**
 * 词法状态机：逐字符推进，返回任意位置处的词法状态
 *
 * 支持：双引号字符串（含转义）、单引号字符（区分生命周期 'a）、
 * 行注释 //、嵌套块注释 /* *\/、原始字符串 r"..." 与 r#"..."#。
 *
 * 推进一个字符返回内部额外跳过的后续字符数（注释标记 / 转义序列 / 原始字符串头部），
 * 调用方据此跳过，避免被跳过的字符被重复解释（例如 // 的第二个 /）。
 */
class 词法状态机 {
    private 状态 = 词法状态.代码;
    private 块注释深度 = 0;
    private 原始字符串井号数 = 0;

    /** 处理前缀中索引 i 处的字符；返回本次额外跳过的后续字符数 */
    推进(前缀: string, i: number): number {
        const 字符 = 前缀[i];
        const 下一字符 = 前缀[i + 1];
        switch (this.状态) {
            case 词法状态.代码:
                if (字符 === '"') {
                    this.状态 = 词法状态.双引号字符串;
                } else if (字符 === "'") {
                    // 生命周期标注 'a（后跟字母且再后非 '）不是字符字面量
                    const 后 = 前缀[i + 1];
                    const 再后 = 前缀[i + 2];
                    const 是生命周期 = /[A-Za-z_]/.test(后 ?? '') && 再后 !== "'";
                    if (!是生命周期) {
                        this.状态 = 词法状态.单引号字符;
                    }
                } else if (字符 === '/' && 下一字符 === '/') {
                    this.状态 = 词法状态.行注释;
                    return 1;
                } else if (字符 === '/' && 下一字符 === '*') {
                    this.状态 = 词法状态.块注释;
                    this.块注释深度 = 1;
                    return 1;
                } else if (字符 === 'r' && (下一字符 === '"' || 下一字符 === '#')) {
                    // 原始字符串：r"..." 或 r#"..."#（支持多井号）
                    let 井号 = 0;
                    let j = i + 1;
                    while (前缀[j] === '#') {
                        井号++;
                        j++;
                    }
                    if (前缀[j] === '"') {
                        this.状态 = 词法状态.原始字符串;
                        this.原始字符串井号数 = 井号;
                        return j - i;
                    }
                }
                break;
            case 词法状态.双引号字符串:
                if (字符 === '\\') {
                    return 1; // 跳过转义字符（\" \\ 等）
                } else if (字符 === '"') {
                    this.状态 = 词法状态.代码;
                }
                break;
            case 词法状态.单引号字符:
                if (字符 === '\\') {
                    return 1;
                } else if (字符 === "'") {
                    this.状态 = 词法状态.代码;
                }
                break;
            case 词法状态.行注释:
                if (字符 === '\n') {
                    this.状态 = 词法状态.代码;
                }
                break;
            case 词法状态.块注释:
                // Rust 块注释支持嵌套：/* /* */ */
                if (字符 === '/' && 下一字符 === '*') {
                    this.块注释深度++;
                    return 1;
                } else if (字符 === '*' && 下一字符 === '/') {
                    this.块注释深度--;
                    if (this.块注释深度 === 0) {
                        this.状态 = 词法状态.代码;
                    }
                    return 1;
                }
                break;
            case 词法状态.原始字符串:
                // r#"..."#：遇到 " 后必须跟够数量 # 才算结束
                if (字符 === '"') {
                    let 井号数 = 0;
                    let j = i + 1;
                    while (井号数 < this.原始字符串井号数 && 前缀[j] === '#') {
                        井号数++;
                        j++;
                    }
                    if (井号数 === this.原始字符串井号数) {
                        this.状态 = 词法状态.代码;
                        return j - 1 - i;
                    }
                }
                break;
        }
        return 0;
    }

    /** 当前词法状态 */
    当前(): 词法状态 {
        return this.状态;
    }
}

/**
 * 扫描指定文本前缀，返回扫描结束时的词法状态
 *
 * 与 扫描词法状态们 共用状态机实现；单位置查询用本函数。
 */
export function 扫描词法状态(前缀: string): 词法状态 {
    const 机 = new 词法状态机();
    for (let i = 0; i < 前缀.length; i++) {
        i += 机.推进(前缀, i);
    }
    return 机.当前();
}

/**
 * 扫描指定文本前缀，一次遍历记录多个偏移处的词法状态
 *
 * 偏移 o 表示前缀前 o 个字符处理完后的状态（o ∈ [0, 前缀.length]）。
 * 全角转换热路径使用：k 个插入位置共享同一前缀时，避免每个位置
 * 各取一次全文并各扫一遍（O(k×n) → O(n)），大文档末尾输入中文
 * 标点时每次按键的全文扫描只发生一次。
 */
export function 扫描词法状态们(前缀: string, 偏移们: readonly number[]): 词法状态[] {
    const 机 = new 词法状态机();
    const 目标们 = [...new Set(偏移们)].sort((a, b) => a - b);
    const 状态们: 词法状态[] = [];
    let 目标索引 = 0;

    // 偏移 0：插入点在文档开头，未处理任何字符，状态恒为代码
    while (目标索引 < 目标们.length && 目标们[目标索引] === 0) {
        状态们.push(词法状态.代码);
        目标索引++;
    }

    for (let i = 0; i < 前缀.length && 目标索引 < 目标们.length; i++) {
        const 跳过 = 机.推进(前缀, i);
        // 跳过本次内部消费的后续字符（注释标记 / 转义序列 / 原始字符串头部）
        i += 跳过;
        // 处理完本次消费（含跳过的后续字符）后，若目标偏移恰好位于
        // 消费末尾（i + 1），记录当前状态。目标偏移落在被跳过字符
        // 内部（如 // 的第二个 /）在真实插入场景中不会出现。
        if (目标们[目标索引] === i + 1) {
            状态们.push(机.当前());
            目标索引++;
        }
    }
    // 剩余目标超出前缀长度（防御）：统一记录当前状态
    while (目标索引 < 目标们.length) {
        状态们.push(机.当前());
        目标索引++;
    }
    return 状态们;
}
