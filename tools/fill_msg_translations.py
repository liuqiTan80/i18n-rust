def main() -> int:
    failed = 0
    for lang in LANGS:
        path = os.path.join(PACKS, lang, "errors.toml")
        with open(path, encoding="utf-8") as f:
            content = f.read()
        try:
            data = tomllib.loads(content)
        except tomllib.TOMLDecodeError as e:
            print(f"❌ {lang}: 解析失败: {e}")
            failed += 1
            continue
        # 收集缺失键（幂等：已有键不覆盖）
        existing = set((data.get("消息翻译") or {}).keys())
        missing = [k for k in MSG if k not in existing]
        if not missing:
            print(f"✅ {lang}: 消息翻译已完整（{len(existing)} 条），跳过")
            continue
        # 追加新键（按 MSG 顺序）
        additions = []
        for key in missing:
            values = MSG[key]
            idx = LANGS.index(lang)
            additions.append(f'["消息翻译"."{key}"]\n')
            additions.append(f'"消息模板" = "{values[idx]}"\n\n')
        new_content = content.rstrip("\n") + "\n\n" + "".join(additions)
        try:
            tomllib.loads(new_content)
        except tomllib.TOMLDecodeError as e:
            print(f"❌ {lang}: 写后验证失败: {e}")
            failed += 1
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(new_content)
        print(f"✅ {lang}: 补齐 {len(missing)} 条消息翻译（共 {len(existing) + len(missing)} 条）")
    return failed


if __name__ == "__main__":
    sys.exit(main())

