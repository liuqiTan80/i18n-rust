    /// 将母语（原始文件）列号转换为英文（虚拟文件）列号
    ///
    /// 由调用方先经按虚拟资源标识查询/查询原始预取项后，
    /// 调用无锁纯函数母语列转英文列（请求方向位置转换热路径）。
    /// 将英文（虚拟文件）内容反向翻译为母语内容
    ///
    /// 供代码格式化（文本编辑格式化请求）与补全/代码操作文本还原使用：
    /// 英文代码经 rustfmt 格式化后，据此还原为母语代码。
    /// 反向表为构造时预构建的合并表（关键字优先），
    /// 保证与正向翻译互逆。
    ///
    /// `资源标识` 为文档原始统一资源标识：传入时按该文档的编辑地图精确删除代理添加的
    /// `crate::` 前缀（用户手写的前缀保留）；为 `无`（补全片段等无文档
    /// 上下文场景）时不删除任何前缀，宁可保留代理前缀也不误删用户手写。
    pub fn 反向转译(&self, 资源标识: Option<&str>, 英文内容: &str) -> String {
        // 无文档上下文或项无代理前缀时，模块名集完全不被使用
        //（词法器仅在新增包前缀词汇命中后才查模块名集合）——
        // 跳过全表扫描：补全/代码操作响应的每个片段都走这里，
        // 每次省一次随文档数增长的读锁遍历
        let 新增包前缀词汇 = 资源标识
            .and_then(|标识值| self.查询原始(标识值))
            .map(|项值| 项值.新增包前缀词汇.clone())
            .unwrap_or_default();
        let 模块名集 = if 新增包前缀词汇.is_empty() {
            HashSet::new()
        } else {
            self.当前模块名集合(None)
        };
        词法器::反译(英文内容, &self.反向映射, &模块名集, &新增包前缀词汇)
    }

