//! 别名替换模块
//! 将源代码中的中文标识符别名（如第三方库的中文名称）替换为英文标识符。
//! 仅替换标识符类型的 token，不触碰字符串字面量和注释等内容。
//! 声明位保护：紧跟在声明关键字（fn/struct/let 等）后的标识符是用户自己的定义，
//! 不是库 API 引用，不参与别名替换；且用户声明的名字在整个文件内的
//! 裸使用处都豁免（两遍扫描：先收集声明名，再逐 token 替换），
//! 避免 `let 新建 = 5` 声明位受保护而后续使用处被误替换成 新建。
//! 三条精细规则：
//! 1. `::` 限定后的路径段按「链根」分级处理：根是项目符号
//!    （包/self/super/项目模块名/项目项名）时链内**与项目声明名
//!    同名**的段豁免——`平台Linux::新建` 的定义侧与调用侧一致
//!    （避免 E0599）；链内非项目名与根非项目符号的段都照常替换
//!    （`源码映射项::新建` 的 `新建` 未定义于项目、`盒子::新建`
//!    的 `新建` 是库 API）；无项目上下文时退化为「本文件项名豁免」
//!    （`接口错误::错误请求`）；
//! 2. 库特征实现块（`实现 <映射词特征> 对于 类型 {}`）内的方法名是库 API
//!    规定的名称（用户从映射表抄写而来），不是用户自定义名字，不受声明位
//!    保护——`实现 抄写器 对于 类型 { 函数 渲染（...） }` 中的 `渲染`
//!    必须转译为 `render`，否则无法匹配 `Scribe::render`（E0407/E0046）；
//! 3. 函数参数与闭包参数是「值绑定」（用户命名）：`fn 完整网址(路径: &str)`
//!    的 `路径` 在声明与使用处都豁免替换（参数「类型」位置的字照常替换），
//!    与格式化串中的 `{路径}` 保持一致，避免 E0425（找不到名称 `路径`）；
//! 4. 结构体字段名与枚举变体名同样是用户命名，纳入声明收集：
//!    字段 `struct 容器 { 值: i32 }` 的 `值`（撞 `值`=values 映射键）
//!    在定义/构造/访问处（`实例.值`）全豁免；枚举变体
//!    `enum 判定结果 { 保留, 丢弃 }` 的 `保留`/`丢弃`（撞
//!    保留/drop 映射键）同理；变体可经 `::` 访问
//!    （`判定结果::保留`）故收集为项，字段收集为值绑定。
//!    方法调用位（`实例.方法()`）不查字段名：`编辑表.长度()` 的
//!    `长度` 是 `新建向量::元素数` 调用，只查「项目方法名集合」（项）；
//! 5. 模式绑定（match 臂、let 解构、对于 模式）同样是值绑定：
//!    `匹配 有值(入参) { 有值(连接) => … }` 的 `连接`（撞
//!    `连接`=连接 映射键）全文件豁免（见 collect_pattern_bindings）。

use rustc_lexer::{TokenKind, tokenize};
use std::collections::{HashMap, HashSet};

use crate::缓存::源映射条目;

/// 单阶段替换结果：输出与编辑表
///
/// 编辑表以**本阶段输入文本**的字节偏移记录（input_offset 升序、互不重叠），
/// replacement 为本阶段输出文本。
#[derive(Debug, Clone)]
pub struct 替换结果 {
    /// 替换后的文本
    pub 产出: String,
    /// 编辑表
    pub 编辑表: Vec<源映射条目>,
}

/// 声明位关键字（转译后的英文形式）：其后紧跟的标识符为用户定义
///
/// 不含 `mut`：仅 `让 mut 名称` 场景下透明传递声明状态（见替换循环），
/// `&mut 类型` 等非声明位的 mut 不传递，避免误保护库类型引用。
/// 不含 `实现`：`实现 特征 对于 类型` 中的特征/类型多为库 API，仍需替换。
/// LSP 列映射模拟别名替换时复用同一张表，保证两侧行为一致。
pub const 声明关键字表: &[&str] = &[
    "fn", "struct", "enum", "trait", "type", "mod", "let", "const", "static",
];

/// 变量声明关键字：其后名字是「变量」（不可经 `::` 访问）；
/// [`声明关键字表`] 的其余关键字（fn/struct/enum/trait/type/mod）声明的
/// 是「项」，项可经 `::` 访问（见模块文档第 1 条规则）
const 变量声明关键字: &[&str] = &["let", "const", "static"];

/// 用户声明名与库特征方法名的收集结果（第一遍扫描）
#[derive(Debug, Default)]
pub struct 声明收集 {
    /// 项声明名（fn/struct/enum/trait/type/mod）+ 枚举变体名：
    /// `::` 后的同名标识符仍豁免
    pub 项名集: HashSet<String>,
    /// 变量声明名（let/const/静态）+ 函数/闭包参数：
    /// `::` 后的同名标识符照常替换
    pub 变量名集: HashSet<String>,
    /// 结构体命名字段：裸使用处豁免（`实例.字段`/结构体字面量）；
    /// `::` 后照常替换（字段不能经 `::` 访问）。
    /// 与 variables 分开收集，供项目级合并（绑定名是文件局部的）
    pub 成员名集: HashSet<String>,
    /// 库特征实现块内的方法名：声明位保护对这些名字失效（库 API 名称）
    pub 库方法名集: HashSet<String>,
}

/// 项目级声明上下文（跨文件声明豁免）
///
/// 单文件的声明豁免无法覆盖跨文件调用：A 文件声明 `公开 函数 新建()`，
/// B 文件调用 `包::A::新建()` 时 B 的转译单元看不到 A 的声明，
/// `新建` 被当作库别名替换出 `新建`（E0599）。转译前扫描同 包
/// 全部方言源文件汇总本结构，把使用处豁免升级到项目级。
///
/// 保守近似与单文件声明豁免一致：不做作用域/可见性分析，同名即豁免。
#[derive(Debug, Default, Clone)]
pub struct 项目上下文 {
    /// 项目模块名（方言文件名词干）：`::` 路径链根
    pub 模块名集: HashSet<String>,
    /// 项目声明名（项 + 结构体字段）：裸使用处豁免
    ///（let/参数等文件内绑定不参与合并——绑定名是文件局部的）
    pub 声明名: HashSet<String>,
    /// 项目项名（fn/struct/enum/trait/type/mod + 枚举变体）：
    /// `::` 路径段豁免与路径链根判定（字段不参与：不可经 `::` 访问）
    pub 项名集: HashSet<String>,
}

impl 项目上下文 {
    /// 从项目源文件集合构建：`modules` 为项目模块名词干，
    /// `sources` 为全部方言源文件内容（母语原文）
    ///
    /// 声明收集工作在关键字转译后的文本上进行（声明关键字需英文形式），
    /// 内部对每个源文件先跑词法转译阶段再收集。
    pub fn 自源文件新建<'a>(
        模块名集: HashSet<String>,
        源文件集: impl IntoIterator<Item = &'a str>,
        映射管理器: &crate::映射管理::映射管理器,
    ) -> Self {
        let 声明们: Vec<声明收集> = 源文件集
            .into_iter()
            .map(|源码| 收集源声明(源码, 映射管理器))
            .collect();
        Self::自声明新建(模块名集, 声明们.iter())
    }

    /// 同 [`Self::自源文件新建`]，但单文件声明收集结果由调用方提供
    ///
    /// 汇总规则唯一来源（[`Self::自源文件新建`] 亦委托本函数）：调用方可按
    /// 文件粒度缓存 [`收集源声明`] 的结果（如 LSP 按内容哈希
    /// 缓存），避免同一内容被重复跑词法转译，同时无需复刻合并规则。
    pub fn 自声明新建<'a>(
        模块名集: HashSet<String>,
        声明集: impl IntoIterator<Item = &'a 声明收集>,
    ) -> Self {
        let mut 声明名 = HashSet::new();
        let mut 项名集 = HashSet::new();
        for 声明 in 声明集 {
            for 名字 in &声明.项名集 {
                声明名.insert(名字.clone());
                项名集.insert(名字.clone());
            }
            声明名.extend(声明.成员名集.iter().cloned());
        }
        Self {
            模块名集,
            声明名,
            项名集,
        }
    }

    /// 上下文为空（无模块且无声明名）：空上下文不产生任何豁免
    pub fn 上下文为空(&self) -> bool {
        self.模块名集.is_empty() && self.声明名.is_empty()
    }

    /// 项目上下文指纹（排序后哈希，跨进程确定）：并入转译缓存指纹，
    /// 项目声明集合变化时相关缓存自动失效
    pub fn 计算指纹(&self) -> u64 {
        use std::hash::{Hash, Hasher};
        let mut 模块列表: Vec<&String> = self.模块名集.iter().collect();
        模块列表.sort_unstable();
        let mut 名字列表: Vec<&String> = self.声明名.iter().collect();
        名字列表.sort_unstable();
        let mut 项名列表: Vec<&String> = self.项名集.iter().collect();
        项名列表.sort_unstable();
        let mut 哈希器 = std::collections::hash_map::DefaultHasher::new();
        ("i18n-rust-project", 模块列表, 名字列表, 项名列表).hash(&mut 哈希器);
        哈希器.finish()
    }

    /// 裸使用处豁免：项目声明名（项 + 结构体字段，含其他文件声明）
    fn 裸用豁免(&self, 文本段: &str) -> bool {
        self.声明名.contains(文本段)
    }

    /// 路径链根判定：包/super/self/项目模块名/项目项名。
    /// 根段后跟 `::` 时整条路径视为项目路径（链内全部段豁免）
    fn 是路径根(&self, 文本段: &str) -> bool {
        matches!(文本段, "crate" | "super" | "self")
            || self.模块名集.contains(文本段)
            || self.项名集.contains(文本段)
    }
}

/// 类型体（结构体/枚举）扫描状态：收集命名字段与枚举变体
#[derive(Debug)]
struct 类型体扫描 {
    /// 是否为枚举体（枚举顶层成员是变体，收集为项）
    是否枚举: bool,
    /// 花括号深度（1 = 类型体顶层）
    深度: u32,
    /// 处于成员开始位置（`{`/`,` 之后）：下一个标识符是字段名/变体名
    成员开始: bool,
    /// 已见的名字（等 `:` 确认后收集为字段）
    待确认成员: Option<String>,
}

/// 收集单个方言源文件的声明名（词法转译 + 声明扫描）
///
/// 与 [`项目上下文::自源文件新建`] 内部的单文件收集步骤完全一致
/// （后者亦委托本函数，规则唯一来源），供需要按文件粒度缓存结果的调用方
/// 使用——例如 LSP 每按键都要汇总全部打开文件的声明名，若每次重算
/// 等于 O(项目规模) 次词法转译；按内容哈希缓存本函数的返回值后，
/// 每次按键只有内容真正变化的那个文件需要重算。
pub fn 收集源声明(
    源码: &str, 映射管理器: &crate::映射管理::映射管理器
) -> 声明收集 {
    let 词法 = crate::词法::词法转译并映射(
        源码,
        映射管理器.取关键词映射表(),
        映射管理器.取宏映射表(),
        映射管理器.取派生映射表(),
        映射管理器.取使用延迟词(),
        映射管理器.取方法延迟词(),
        映射管理器.取别名映射表(),
    );
    收集声明名(&词法.产出, 映射管理器.取别名映射表())
}

/// 收集用户在声明位定义的标识符名（第一遍扫描）
///
/// 状态机与替换主循环一致：声明关键字后紧跟的标识符计入集合；
/// `mut` 在声明态内透明传递；空白/注释不打断声明态；符号终结声明位。
/// 另收集「值绑定」：函数参数名（`fn 名(参数: 类型)` 中的参数开始位
/// 且后跟 `:`）与闭包参数名（`|甲, 乙|`，可无类型标注直接收集）——
/// 绑定名是用户命名，不是库 API 引用。
/// 结构体/枚举体扫描（[`类型体扫描`]）：命名字段（`字段: 类型`）
/// 收集为值绑定，枚举顶层变体名收集为项（变体可经 `::` 访问）。
/// 集合内的名字在文件内的使用处豁免别名替换（保守近似：不做作用域
/// 分析，同名遮蔽场景同样豁免，与声明位保护的设计意图一致）。
/// 库特征实现块内的方法名（见 [`收集库特征方法名`]）从保护集合剔除。
pub fn 收集声明名(源码: &str, 别名映射表: &HashMap<String, String>) -> 声明收集 {
    let mut 产出 = 声明收集::default();
    let mut 前声明态: Option<&'static str> = None;
    // —— 类型体（struct/enum）扫描状态 ——
    // 待定类型：已见 `struct`/`enum` 关键字，值为（是否枚举，是否已见名字）；
    // 名字后遇 `{` 进入体扫描，遇 `;` 放弃（unit/tuple 结构体无可收集成员）
    let mut 待定类型: Option<(bool, bool)> = None;
    let mut 类型体: Option<类型体扫描> = None;
    // 类型体内的括号/方括号深度：>0 时内部标识符不参与成员收集
    //（`公开(包) 字段` 可见性、`[T; N]` 数组类型、`#[属性]` 属性）
    let mut 体圆数 = 0u32;
    let mut 体尖数 = 0u32;
    let mut 体方数 = 0u32;
    // —— 函数参数绑定跟踪 ——
    // 函头态：0=不在 fn 头部；1=已见 fn 等待参数括号；2=在参数括号内。
    // 括号内处于参数开始位置（`(` 或 `,` 之后）且后跟 `:` 的标识符是
    // 用户声明的参数名（`mut 名: 类型` 中 mut 透明传递）
    let mut 函头态 = 0u32;
    // fn 名后的 `<...>` 泛型深度：`fn 名<T>(...)` 中的 `(` 不是参数括号
    let mut 函尖数 = 0u32;
    let mut 圆深 = 0u32;
    let mut 参起始 = false;
    let mut 待参: Option<String> = None;
    // —— 闭包参数绑定跟踪（`|甲, 乙| 体`，无类型标注直接收集）——
    let mut 闭包中 = false;
    // 闭包参数内的括号深度：解构/类型（`|(甲, 乙): (T, T)|`）内的名字不收集
    let mut 闭圆数 = 0u32;
    let mut 闭起始 = false;
    // 上一个有效 token 是否可作表达式结尾（区分位或 `a | b` 与闭包 `|甲|`）
    let mut 前值尾 = false;
    // 上一个 `|`（或号）token 的结束偏移：词法解析器 不合并 `||`，它是连续
    // 两个 `|` token，紧邻的第二个不得判定为闭包起始（`a || b` 是逻辑或）
    let mut 或尾位 = usize::MAX;
    // token 序列预收集：本函数内三遍扫描（声明名/库特征方法/模式绑定）
    // 共享同一份 token 序列，避免重复词法化
    let 令牌序列: Vec<rustc_lexer::Token> = tokenize(源码).collect();
    let mut 偏移 = 0;
    for 令牌 in &令牌序列 {
        let 文本段 = &源码[偏移..偏移 + 令牌.len];
        match 令牌.kind {
            TokenKind::Ident => {
                // —— 类型头推进（struct/enum 后第一个标识符是类型名）——
                // 名字已由下方声明关键字逻辑收集为项；此处仅推进状态，
                // `公开` 修饰不消耗「等名字」态
                if 文本段 == "struct" {
                    待定类型 = Some((false, false));
                } else if 文本段 == "enum" {
                    待定类型 = Some((true, false));
                } else if let Some((_, 已见名)) = &mut 待定类型
                    && !*已见名
                    && 文本段 != "pub"
                {
                    *已见名 = true;
                }
                // —— 类型体成员收集 ——
                // 成员开始位置的标识符：枚举顶层是变体名（收集为项，变体可经
                // `::` 访问）；struct 字段与变体携带的结构体字段先入候选，
                // 等 `:` 确认后收集（`公开(包)` 可见性、`#[属性]`、数组类型
                // `[T; N]` 与泛型 `<...>` 内部的标识符不参与）
                if let Some(扫描体) = &mut 类型体
                    && 体圆数 == 0
                    && 体尖数 == 0
                    && 体方数 == 0
                    && 扫描体.成员开始
                    && 文本段 != "pub"
                {
                    if 扫描体.是否枚举 && 扫描体.深度 == 1 {
                        产出.项名集.insert(文本段.to_string());
                    } else {
                        扫描体.待确认成员 = Some(文本段.to_string());
                    }
                    扫描体.成员开始 = false;
                }
                if let Some(关键字) = 前声明态 {
                    if 变量声明关键字.contains(&关键字) {
                        产出.变量名集.insert(文本段.to_string());
                    } else {
                        产出.项名集.insert(文本段.to_string());
                    }
                }
                前声明态 = 推进声明关键字(前声明态, 文本段);
                // 函数参数名：参数开始位置的标识符（`mut` 后继续等待名字）
                if 函头态 == 2 && 圆深 == 1 && 参起始 && 文本段 != "mut" {
                    待参 = Some(文本段.to_string());
                    参起始 = false;
                }
                if 函头态 == 0 && 文本段 == "fn" {
                    函头态 = 1;
                    函尖数 = 0;
                }
                // 闭包参数名：`|` 或 `,` 之后的名字（`mut 名` 同样透明）
                if 闭包中 && 闭圆数 == 0 && 闭起始 && 文本段 != "mut" {
                    产出.变量名集.insert(文本段.to_string());
                    闭起始 = false;
                }
                // `move |甲|`：move 是闭包前缀，其后 `|` 仍是闭包起始
                前值尾 = 文本段 != "move";
            }
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            TokenKind::OpenParen => {
                前声明态 = None;
                if 类型体.is_some() {
                    体圆数 += 1;
                }
                if 函头态 == 1 && 函尖数 == 0 {
                    函头态 = 2;
                    圆深 = 1;
                    参起始 = true;
                } else if 函头态 == 2 {
                    圆深 += 1;
                    参起始 = false;
                }
                if 闭包中 {
                    闭圆数 += 1;
                    闭起始 = false;
                }
                待参 = None;
                前值尾 = false;
            }
            TokenKind::CloseParen => {
                前声明态 = None;
                if 类型体.is_some() {
                    体圆数 = 体圆数.saturating_sub(1);
                }
                if 函头态 == 2 {
                    圆深 = 圆深.saturating_sub(1);
                    if 圆深 == 0 {
                        函头态 = 0;
                    }
                    参起始 = false;
                }
                if 闭包中 {
                    闭圆数 = 闭圆数.saturating_sub(1);
                    闭起始 = false;
                }
                待参 = None;
                前值尾 = true;
            }
            TokenKind::Comma => {
                前声明态 = None;
                if 函头态 == 2 && 圆深 == 1 {
                    参起始 = true;
                }
                if 闭包中 && 闭圆数 == 0 {
                    闭起始 = true;
                }
                // 类型体成员分隔：重置成员开始位（括号/尖括号/方括号内的
                // 逗号是类型参数分隔，不是成员分隔）
                if 体圆数 == 0
                    && 体尖数 == 0
                    && 体方数 == 0
                    && let Some(扫描体) = &mut 类型体
                {
                    扫描体.成员开始 = true;
                    扫描体.待确认成员 = None;
                }
                // 名字后遇 `,`（无类型标注模式）：丢弃待确认候选
                待参 = None;
                前值尾 = false;
            }
            TokenKind::Colon => {
                前声明态 = None;
                // `名:` → 确认函数参数绑定（其他位置不会有待确认候选）
                if let Some(名字) = 待参.take() {
                    产出.变量名集.insert(名字);
                }
                // `字段:` → 确认结构体字段名（收作成员名；`::` 的第二冒号
                // 无候选，无副作用）
                if let Some(扫描体) = &mut 类型体
                    && let Some(名字) = 扫描体.待确认成员.take()
                {
                    产出.成员名集.insert(名字);
                }
                前值尾 = false;
            }
            TokenKind::Or => {
                前声明态 = None;
                if 闭包中 {
                    if 闭圆数 == 0 {
                        闭包中 = false;
                    }
                } else if !前值尾 && 或尾位 != 偏移 {
                    // 前一个有效 token 不是表达式结尾，且不与上一个 `|`
                    // 相邻（`a || b` 是连续两个 `|` token）→ 闭包起始
                    //（位或 `a | b` 的 `|` 前是表达式，不进入闭包态）
                    闭包中 = true;
                    闭圆数 = 0;
                    闭起始 = true;
                }
                或尾位 = 偏移 + 令牌.len;
                待参 = None;
                前值尾 = false;
            }
            TokenKind::Lt => {
                前声明态 = None;
                if 函头态 == 1 {
                    函尖数 += 1;
                }
                if 类型体.is_some() {
                    体尖数 += 1;
                }
                待参 = None;
                前值尾 = false;
            }
            TokenKind::Gt => {
                前声明态 = None;
                if 函头态 == 1 {
                    函尖数 = 函尖数.saturating_sub(1);
                }
                if 类型体.is_some() {
                    体尖数 = 体尖数.saturating_sub(1);
                }
                待参 = None;
                前值尾 = false;
            }
            TokenKind::OpenBrace => {
                // `struct/enum 名 {` → 进入类型体成员扫描；体内嵌套花括号
                //（变体携带的结构体体、常量表达式块）加深一层
                if let Some((是否枚举, 已见名)) = 待定类型.take() {
                    if 已见名 {
                        类型体 = Some(类型体扫描 {
                            是否枚举,
                            深度: 1,
                            成员开始: true,
                            待确认成员: None,
                        });
                        体圆数 = 0;
                        体尖数 = 0;
                        体方数 = 0;
                    }
                } else if 类型体.is_some()
                    && 体圆数 == 0
                    && 体尖数 == 0
                    && 体方数 == 0
                    && let Some(扫描体) = &mut 类型体
                {
                    扫描体.深度 += 1;
                    扫描体.成员开始 = true;
                    扫描体.待确认成员 = None;
                }
                前声明态 = None;
                待参 = None;
                前值尾 = false;
            }
            TokenKind::CloseBrace => {
                // 类型体闭合：深度 归零退出扫描（括号/尖括号/方括号内的
                // 花括号不是类型体边界）
                if 体圆数 == 0 && 体尖数 == 0 && 体方数 == 0 {
                    let 已退出 = if let Some(扫描体) = &mut 类型体 {
                        扫描体.深度 = 扫描体.深度.saturating_sub(1);
                        if 扫描体.深度 == 0 {
                            true
                        } else {
                            扫描体.成员开始 = true;
                            扫描体.待确认成员 = None;
                            false
                        }
                    } else {
                        false
                    };
                    if 已退出 {
                        类型体 = None;
                    }
                }
                前声明态 = None;
                待参 = None;
                前值尾 = true;
            }
            TokenKind::OpenBracket => {
                // 方括号内的标识符不参与成员收集（属性、数组类型 `[T; N]`）
                if 类型体.is_some() {
                    体方数 += 1;
                }
                前声明态 = None;
                待参 = None;
                前值尾 = false;
            }
            TokenKind::CloseBracket => {
                if 类型体.is_some() {
                    体方数 = 体方数.saturating_sub(1);
                }
                前声明态 = None;
                待参 = None;
                前值尾 = true;
            }
            _ => {
                前声明态 = None;
                待参 = None;
                // `struct/enum 名;`（单元结构体）：放弃类型体等待
                if matches!(令牌.kind, TokenKind::Semi) {
                    待定类型 = None;
                }
                前值尾 = matches!(
                    令牌.kind,
                    TokenKind::Literal { .. }
                        | TokenKind::CloseBracket
                        | TokenKind::CloseBrace
                        | TokenKind::Question
                );
            }
        }
        偏移 += 令牌.len;
    }
    // 库特征实现块内的方法名从保护集合剔除：它们是库 API 规定的名称，
    // 应照常参与别名替换（如 `实现 抄写器 对于 类型 { 函数 渲染（...） }`）
    产出.库方法名集 = 收集库特征方法名(&令牌序列, 源码, &产出.项名集, 别名映射表);
    for 名字 in &产出.库方法名集 {
        产出.项名集.remove(名字);
        产出.变量名集.remove(名字);
    }
    // 模式绑定收集（match 臂 / let 解构 / 对于 模式）：独立扫描
    收集模式绑定(&令牌序列, 源码, &mut 产出);
    产出
}

/// 推进声明关键字状态：`mut` 透明传递，其余按是否声明关键字更新
fn 推进声明关键字(前一: Option<&'static str>, 文本段: &str) -> Option<&'static str> {
    if 文本段 == "mut" {
        return 前一;
    }
    声明关键字表
        .iter()
        .find(|&&次索引| 次索引 == 文本段)
        .copied()
}

/// `实现` 块扫描状态（第二遍扫描用）
#[derive(Debug)]
enum 实现扫描 {
    /// 不在 实现 上下文中
    不在,
    /// 已见 `实现`，等待特征名/类型名（`<...>` 泛型参数内的名字忽略）
    等特征,
    /// 已见 实现 目标名，等待块开始 `{`
    有名(String),
    /// 在 实现 块内；`是库` 表示这是「库特征实现块」
    体内 { 是库: bool },
}

/// 识别「库特征实现块」内的方法名（第二遍扫描）
///
/// 实现外部（库）特征时，`实现` 块内的方法名是库 API 规定的方法名
/// （用户从映射表抄写而来），必须照常参与别名替换；而实现用户自定义
/// 特征（`trait 可显示`）时方法名是用户取的名字，保持声明位保护。
/// 判定「库特征」的两个条件同时满足：特征名不在用户项集合中（排除
/// 同文件自定义特征），且在别名映射表中（无映射词时替换循环本就无事
/// 可做，保持保护无害，也避免跨文件自定义特征被误判）。
fn 收集库特征方法名(
    令牌序列: &[rustc_lexer::Token],
    源码: &str,
    项集: &HashSet<String>,
    别名映射表: &HashMap<String, String>,
) -> HashSet<String> {
    let mut 库方法名 = HashSet::new();
    let mut 扫描态 = 实现扫描::不在;
    // 等特征 中 `<...>` 泛型参数深度：`实现<T> 特征 对于 类型` 里 `T` 不是特征名
    let mut 尖括深度 = 0u32;
    // 体内 内大括号深度：归零时退出 实现 块
    let mut 花括深度 = 0u32;
    // 上一个有意义 token 是否为 `fn`（空白/注释不打断，与主循环一致）
    let mut 前是函数 = false;
    let mut 偏移 = 0;
    for 令牌 in 令牌序列 {
        let 文本段 = &源码[偏移..偏移 + 令牌.len];
        match 令牌.kind {
            TokenKind::Ident => {
                match &扫描态 {
                    实现扫描::不在 => {
                        if 文本段 == "impl" {
                            扫描态 = 实现扫描::等特征;
                            尖括深度 = 0;
                        }
                    }
                    实现扫描::等特征 => {
                        if 尖括深度 == 0 {
                            扫描态 = 实现扫描::有名(文本段.to_string());
                        }
                    }
                    // `实现 特征 对于 类型`：特征名之后的 对于/类型名均忽略，等待 `{`
                    实现扫描::有名(_) => {}
                    实现扫描::体内 { 是库 } => {
                        if *是库 && 前是函数 {
                            库方法名.insert(文本段.to_string());
                        }
                    }
                }
                前是函数 = 文本段 == "fn";
            }
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            TokenKind::OpenBrace => {
                if let 实现扫描::有名(名字) = &扫描态 {
                    let 是库 = !项集.contains(名字) && 别名映射表.contains_key(名字);
                    扫描态 = 实现扫描::体内 { 是库 };
                    花括深度 = 0;
                } else if matches!(扫描态, 实现扫描::体内 { .. }) {
                    花括深度 += 1;
                } else if matches!(扫描态, 实现扫描::等特征) {
                    // `实现 {`：非法写法，放弃跟踪
                    扫描态 = 实现扫描::不在;
                }
                前是函数 = false;
            }
            TokenKind::CloseBrace => {
                if matches!(扫描态, 实现扫描::体内 { .. }) {
                    if 花括深度 == 0 {
                        扫描态 = 实现扫描::不在;
                    } else {
                        花括深度 -= 1;
                    }
                }
                前是函数 = false;
            }
            TokenKind::Lt => {
                if matches!(扫描态, 实现扫描::等特征) {
                    尖括深度 += 1;
                }
                前是函数 = false;
            }
            TokenKind::Gt => {
                if matches!(扫描态, 实现扫描::等特征) {
                    尖括深度 = 尖括深度.saturating_sub(1);
                }
                前是函数 = false;
            }
            _ => 前是函数 = false,
        }
        偏移 += 令牌.len;
    }
    库方法名
}

/// 对于 模式挂起中出现的「非模式词」：声明/语句关键字
///
/// 真模式里不可能出现这些词，出现即说明挂起跨越了语句边界
/// （残留/剥离代码），须丢弃挂起，避免把后续代码里的名字误收为绑定。
const 语句边界关键字: &[&str] = &[
    "fn", "struct", "enum", "impl", "trait", "mod", "type", "const", "static", "let", "use", "pub",
    "return", "if", "else", "while", "loop", "match", "break", "continue", "unsafe", "async",
    "await", "move", "where",
];

/// 模式绑定收集（第三遍扫描）：match 臂 / let 解构 / 对于 模式
///
/// 模式中出现的标识符是「值绑定」（用户命名），须与函数/闭包参数一样
/// 全文件豁免替换——否则 `成功(连接) =>` 的 `连接`（撞 `连接`=连接
/// 映射键）会被误替换为 `连接`（实测确认的缺陷）。识别规则：
/// - match 臂：`=>`（`等号码`+`大于号` 相邻两 token）向左回溯到臂起点
///   （深度 0 的 `,`/`{`/`;`），区间内标识符按模式语法过滤后收集；
///   守卫表达式中的名字同为值使用，一并收集无害（方法调用位与
///   `::` 路径位不查值绑定集合，不会过度豁免库 API）；
/// - let 解构：`let` 后解构括号（`let (甲, 乙) = …`、
///   `let 点 { x, y } = …`）内的名字；`=` 结束（类型标注在括号外，
///   不受影响），if-let/while-let 同形覆盖；
/// - 对于 模式：`对于` 到 `在` 之间的名字（`对于 &长度 在 …`、
///   `对于 (键, 值) 在 …`）；挂起期间遇声明/语句关键字即丢弃。
///   `实现 … 对于 类型 {` 的 对于 由 实现 头部状态排除。
///
/// 过滤见 [`是模式绑定`]：`::` 路径段（`错误::连接` 的
/// `连接` 是库变体）、后跟 `(`/`{`/`[` 的构造路径（`有值(…)`、
/// `点 { … }`）、后跟 `:` 的字段名（`x: 甲` 的 `x`）、`mut`/`ref`
/// 修饰符都不是绑定。
fn 收集模式绑定(
    令牌序列: &[rustc_lexer::Token], 源码: &str, 产出: &mut 声明收集
) {
    // —— let 解构态 / 对于 模式态 / 实现 头部区间 ——
    let mut 模式态 = false;
    let mut 模式深 = 0u32;
    let mut 循环态 = false;
    let mut 循环深 = 0u32;
    let mut 循环挂起: Vec<String> = Vec::new();
    // `实现 … 对于 类型 {` 的头部区间：其间出现的 `对于` 是 实现 语法
    let mut 实现头中 = false;

    let mut 偏移 = 0usize;
    for 下标 in 0..令牌序列.len() {
        let 形态 = 令牌序列[下标].kind;
        let 文本段 = &源码[偏移..偏移 + 令牌序列[下标].len];
        match 形态 {
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            TokenKind::Ident => {
                if 文本段 == "impl" {
                    实现头中 = true;
                }
                // —— 对于 模式态 ——
                if 循环态 {
                    if 文本段 == "in" && 循环深 == 0 {
                        // 模式结束：提交挂起绑定
                        产出.变量名集.extend(循环挂起.drain(..));
                        循环态 = false;
                    } else if 循环深 == 0 && (文本段 == "for" || 语句边界关键字.contains(&文本段))
                    {
                        // 遇嵌套 对于 重启挂起；遇声明/语句关键字丢弃挂起
                        循环挂起.clear();
                        循环态 = 文本段 == "for";
                        循环深 = 0;
                    } else if 是模式绑定(令牌序列, 下标, 文本段) {
                        循环挂起.push(文本段.to_string());
                    }
                } else if 文本段 == "for" && !实现头中 {
                    循环态 = true;
                    循环深 = 0;
                    循环挂起.clear();
                }
                // —— let 解构态（`=` 之前括号内的名字是绑定）——
                if 模式态 && 模式深 > 0 && 是模式绑定(令牌序列, 下标, 文本段) {
                    产出.变量名集.insert(文本段.to_string());
                }
                if 文本段 == "let" {
                    模式态 = true;
                    模式深 = 0;
                }
            }
            TokenKind::OpenParen | TokenKind::OpenBracket => {
                if 模式态 {
                    模式深 += 1;
                }
                if 循环态 {
                    循环深 += 1;
                }
            }
            TokenKind::OpenBrace => {
                // 实现 头部结束（进入块体）
                实现头中 = false;
                if 模式态 {
                    模式深 += 1;
                }
                if 循环态 {
                    循环深 += 1;
                }
            }
            TokenKind::CloseParen | TokenKind::CloseBracket | TokenKind::CloseBrace => {
                模式深 = 模式深.saturating_sub(1);
                循环深 = 循环深.saturating_sub(1);
            }
            TokenKind::Semi => {
                实现头中 = false;
                模式态 = false;
                模式深 = 0;
                循环挂起.clear();
                循环态 = false;
                循环深 = 0;
            }
            TokenKind::Eq => {
                // `let 模式 =`：模式结束（`=` 之后是表达式，名字照常替换）；
                // 对于 模式里 `=` 不合法（防御）
                if 模式态 && 模式深 == 0 {
                    模式态 = false;
                }
                if 循环态 && 循环深 == 0 {
                    循环挂起.clear();
                    循环态 = false;
                }
            }
            TokenKind::Colon => {
                // `let 名: 类型` 的 `:` 是类型标注分隔——其后是类型（可能含
                // `[`/`<`/`(`），不再是模式绑定。须立即结束 let 态，否则类型
                // 中的 `[` 会把 let 深度抬回非零、`=` 无法结束 let 态，导致类型
                // 内的别名被误收为值绑定而全文件豁免替换（weix-1 #15）。
                // `::` 是路径分隔（两个相邻 冒号 token），不代表类型标注，不能结束。
                if 模式态
                    && 模式深 == 0
                    && !前一有意义索引(令牌序列, 下标)
                        .is_some_and(|前索引| 令牌序列[前索引].kind == TokenKind::Colon)
                    && !后继有意义索引(令牌序列, 下标)
                        .is_some_and(|数量| 令牌序列[数量].kind == TokenKind::Colon)
                {
                    模式态 = false;
                    模式深 = 0;
                }
                // 对于 模式里 `:` 不合法（类型标注等非循环场景，防御）
                if 循环态 && 循环深 == 0 {
                    循环挂起.clear();
                    循环态 = false;
                }
            }
            TokenKind::Lt if 循环态 && 循环深 == 0 => {
                // 对于 模式里 `<` 不合法（泛型等非循环场景，防御）
                循环挂起.clear();
                循环态 = false;
            }
            TokenKind::Gt => {
                // `=>`（`等号码`+`大于号` 相邻两 token）：match 臂箭头 → 回溯收集
                //（索引相邻即两 token 间无其他 token，`=>` 无空白）
                if let Some(前索引) = 前一有意义索引(令牌序列, 下标)
                    && 令牌序列[前索引].kind == TokenKind::Eq
                    && 前索引 == 下标 - 1
                {
                    收集匹配臂绑定(令牌序列, 偏移, 下标, 源码, 产出);
                }
            }
            _ => {}
        }
        偏移 += 令牌序列[下标].len;
    }
}

/// `=>` 回溯：收集 match 臂模式中的绑定名
///
/// 从箭头（索引 `箭索引`，起点偏移 `箭偏移`）向左回溯到臂起点
/// （深度 0 的 `,`/`{`/`;`），区间内标识符经 [`是模式绑定`]
/// 过滤后收为值绑定。`{}`/`()`/`[]` 深度配对处理结构体模式
/// （`点 { x, y }`）与嵌套模式。
///
/// 越界防护（weix-1 #27）：带块臂体（`=> { … }`）的**下一臂**回溯时
/// 会先遇到上一臂的块闭合 `}`；若不识别，深度失衡后 `,`/`;` 不再
/// 终止，回溯将穿透上一臂语句，把类型标注（`让 x: T = …` 的 `T`）
/// 等裸标识符误收为值绑定 → 其全文件豁免替换（`无符号机器整数`
/// = 无符号机器整数 实测不被翻译，产物 E0425）。块体臂的逗号可省略，其闭合
/// `}` 即当前臂模式的左边界：识别后立即截止
/// （见 [`闭花括号终结臂体`]）。
fn 收集匹配臂绑定(
    令牌序列: &[rustc_lexer::Token],
    箭偏移: usize,
    箭索引: usize,
    源码: &str,
    产出: &mut 声明收集,
) {
    // 箭索引 前一个有意义 token 是 `=`（调用方已确认 `=>` 相邻）
    let Some(等索引) = 前一有意义索引(令牌序列, 箭索引) else {
        return;
    };
    let mut 深度 = 0u32;
    // 反向累计各 token 的起点偏移（切分令牌 连续覆盖全源）
    let mut 起点 = 箭偏移.saturating_sub(令牌序列[等索引].len);
    for 内索引 in (0..等索引).rev() {
        起点 = 起点.saturating_sub(令牌序列[内索引].len);
        let 形态 = 令牌序列[内索引].kind;
        match 形态 {
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            TokenKind::CloseParen | TokenKind::CloseBracket => 深度 += 1,
            TokenKind::CloseBrace => {
                // 上一臂块体闭合即当前臂模式左边界：就此截止，
                // 不得穿入上一臂体（见函数文档「越界防护」）
                if 深度 == 0 && 闭花括号终结臂体(令牌序列, 内索引) {
                    break;
                }
                深度 += 1;
            }
            TokenKind::OpenParen | TokenKind::OpenBracket => {
                if 深度 == 0 {
                    break; // 模式区间外的括号（异常输入）：保守停止
                }
                深度 -= 1;
            }
            TokenKind::OpenBrace => {
                if 深度 == 0 {
                    break; // match 体（或宏体）的起点
                }
                深度 -= 1;
            }
            TokenKind::Comma | TokenKind::Semi => {
                if 深度 == 0 {
                    break; // 上一臂的分隔或语句边界
                }
            }
            TokenKind::Ident => {
                let 文本段 = &源码[起点..起点 + 令牌序列[内索引].len];
                if 是模式绑定(令牌序列, 内索引, 文本段) {
                    产出.变量名集.insert(文本段.to_string());
                }
            }
            _ => {}
        }
    }
}

/// `}`（索引 `闭索引`）是否为「臂块体闭合」（`=> { … }` 的收尾）
///
/// 判定：向左找配对的 `{`，其前一个有意义 token 是 `=>` 的 `>`
/// （`等号码`+`大于号` 相邻）则为臂体闭合。结构体模式的 `}`（配对 `{` 前
/// 是路径名，如 `点 { x }`、`点<T> { x }`）返回 false，照常参与
/// 深度配对。
fn 闭花括号终结臂体(令牌序列: &[rustc_lexer::Token], 闭索引: usize) -> bool {
    let mut 深度 = 0u32;
    let mut 次索引 = 闭索引;
    while 次索引 > 0 {
        次索引 -= 1;
        match 令牌序列[次索引].kind {
            TokenKind::CloseBrace => 深度 += 1,
            TokenKind::OpenBrace => {
                if 深度 == 0 {
                    // 配对 `{`：前一个有意义 token 是 `=>` 的 `>`？
                    return 前一有意义索引(令牌序列, 次索引).is_some_and(|前索引| {
                        令牌序列[前索引].kind == TokenKind::Gt
                            && 前一有意义索引(令牌序列, 前索引).is_some_and(|前一位置| {
                                令牌序列[前一位置].kind == TokenKind::Eq && 前一位置 == 前索引 - 1
                            })
                    });
                }
                深度 -= 1;
            }
            _ => {}
        }
    }
    false
}

/// 模式内标识符的「值绑定」判定
///
/// `mut`/`ref` 修饰符不是名字；`::` 路径段（变体/常量路径）、后跟
/// `(`/`{`/`[` 的构造路径（`有值(…)`、`点 { … }`）、后跟 `:` 的
/// 字段名（`x: 甲` 的 `x`，兼作 `::` 前段判定）都不是绑定。
fn 是模式绑定(令牌序列: &[rustc_lexer::Token], 下标: usize, 文本段: &str) -> bool {
    if 文本段 == "mut" || 文本段 == "ref" {
        return false;
    }
    if let Some(数量) = 后继有意义索引(令牌序列, 下标) {
        match 令牌序列[数量].kind {
            TokenKind::Colon
            | TokenKind::OpenParen
            | TokenKind::OpenBrace
            | TokenKind::OpenBracket => return false,
            _ => {}
        }
    }
    // 前是 `::` 后段（前两个有意义 token 都是 冒号）→ 路径段，不是绑定
    if let Some(前索引) = 前一有意义索引(令牌序列, 下标)
        && 令牌序列[前索引].kind == TokenKind::Colon
        && let Some(前一位置) = 前一有意义索引(令牌序列, 前索引)
        && 令牌序列[前一位置].kind == TokenKind::Colon
    {
        return false;
    }
    true
}

/// 下标 之前（不含 下标）第一个有意义 token 的索引（跳过空白/注释）
fn 前一有意义索引(令牌序列: &[rustc_lexer::Token], 下标: usize) -> Option<usize> {
    令牌序列[..下标]
        .iter()
        .rposition(|令牌项| !是琐碎词(令牌项.kind))
}

/// 下标 之后（不含 下标）第一个有意义 token 的索引（跳过空白/注释）
fn 后继有意义索引(令牌序列: &[rustc_lexer::Token], 下标: usize) -> Option<usize> {
    令牌序列[下标 + 1..]
        .iter()
        .position(|令牌项| !是琐碎词(令牌项.kind))
        .map(|前索引| 前索引 + 下标 + 1)
}

/// 空白/注释（trivia）：不参与相邻性判断
fn 是琐碎词(形态: TokenKind) -> bool {
    matches!(
        形态,
        TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
    )
}

/// 将源码中的中文别名替换为英文标识符（仅替换标识符 token）
///
/// 输入应为已完成关键字转译的代码（声明关键字已是英文形式）。
/// 声明位的标识符（如 `fn 绝对值()`、`让 字符串 = 1`）保留原样，
/// 且这些用户声明名在文件内的使用处也不替换；`::` 限定后的路径段
/// 仅对「变量名」不豁免（如 `字符串::新建` 里的 `新建` 是库 API，
/// 照常替换），用户声明的项可经 `::` 访问（`接口错误::错误请求`），
/// 仍豁免。库特征实现块内的方法名是库 API 名称，照常替换（见模块文档）。
///
/// # 参数
/// - `source`: 待替换的源代码字符串
/// - `别名映射表`: 中文别名 → 英文原名 的映射表
///
/// # 返回
/// 替换后的源代码字符串
pub fn 替换别名(源码: &str, 别名映射表: &HashMap<String, String>) -> String {
    替换别名并映射(源码, 别名映射表).产出
}

/// 同 [`替换别名`]，同时产出编辑表（本阶段输入坐标）
pub fn 替换别名并映射(
    源码: &str, 别名映射表: &HashMap<String, String>
) -> 替换结果 {
    替换别名并上下文(源码, 别名映射表, None)
}

/// 同 [`替换别名并映射`]，附项目级声明上下文（跨文件声明豁免）
///
/// `project` 为 无 时行为与 [`替换别名并映射`] 完全一致。
/// 提供上下文时在逐文件豁免之上额外豁免：
/// - 项目声明名（含其他文件声明的项/结构体字段）的裸使用处；
/// - 项目模块名的裸使用处；
/// - 以 `包`/`super`/`self`/项目模块名/项目项名为根的 `::` 路径链：
///   链内**与项目声明名同名**的段豁免（`包::平台Linux::Linux内存源::新建`
///   ——跨文件引用成员与声明侧一致，避免 E0599）；链内非项目名
///   （`源码映射项::新建` 的 `新建` 未定义于项目）照常替换。
///   `::` 后非项目根的段（`盒子::新建`）同样照常替换：`新建` 是库 API。
pub fn 替换别名并上下文(
    源码: &str,
    别名映射表: &HashMap<String, String>,
    项目上下文: Option<&项目上下文>,
) -> 替换结果 {
    替换别名并上下文并模块路径(源码, 别名映射表, &HashMap::new(), 项目上下文)
}

/// 同 [`替换别名并上下文`]，附模块路径表（use 之外的模块前缀转译）
///
/// 管线的「模块路径替换」阶段只处理 use 语句；表达式与属性位置的
/// `模块词::项`（`异步运行时::睡眠`、`#[异步运行时::主函数]`）在本函数内
/// 回退模块路径表完成（office-zb #10/#18：此前「模块词」保留、「项」被
/// 别名替换，产物 `异步运行时::main` 报 E0433）。回退规则：
/// - 仅**路径根位置**（后跟 `::`、且前不是 `::` 的段）触发；
/// - 别名表命中优先——标识符语义覆盖模块语义（`路径::新建` 的 `路径`
///   是 `路径类型` 而非 `路径模块` 模块）；
/// - 路径根位上的字段/变量名豁免不适用（见 `使用豁免` 的根位分支）；
/// - 替换值做 包 名连字符规范化（`-` → `_`）。
pub fn 替换别名并上下文并模块路径(
    源码: &str,
    别名映射表: &HashMap<String, String>,
    模块路径表: &HashMap<String, String>,
    项目上下文: Option<&项目上下文>,
) -> 替换结果 {
    // 映射表为空时直接返回，避免不必要的词法分析开销
    if 别名映射表.is_empty() && 模块路径表.is_empty() {
        return 替换结果 {
            产出: 源码.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 第一遍：收集用户声明名与库特征方法名（使用处豁免见 声明收集）
    let 声明结果 = 收集声明名(源码, 别名映射表);
    // 单个 冒号 跟踪：词法解析器 把 `::` 拆成两个 冒号 token
    let mut 上次冒号 = false;
    // token 序列化收集：`.方法()` 判定需向后看一位（下一个有意义 token
    // 是否为 `(`），字段访问 `实例.字段` 与方法调用 `实例.方法()` 的
    // 豁免集合不同
    let 令牌序列: Vec<rustc_lexer::Token> = tokenize(源码).collect();
    let mut 产出 = String::new();
    let mut 编辑表 = Vec::new();
    let mut 当前偏移 = 0;
    // 上一个有意义 token 若是声明关键字，记录其文本（`mut` 透明传递）；
    // 空白/注释不重置该状态
    let mut 前声明态: Option<&'static str> = None;
    // 上一个有意义 token 是否为 `::`（两个连续 冒号 token 的第二个）
    let mut 前路径分隔 = false;
    // 上一个有意义 token 是否为 `.`（成员访问/方法链）
    let mut 前点号 = false;
    // —— 项目路径链跟踪（仅 项目上下文 为 有值 时生效）——
    // 待项目根：上一标识符是项目根候选（包/模块名/项名），
    // 等待 `::` 确认；项目路径中：根段已确认，链内段按项目声明名豁免
    let mut 待项目根 = false;
    let mut 项目路径中 = false;

    for (索引, 令牌) in 令牌序列.iter().enumerate() {
        let 长度 = 令牌.len;
        let 文本段 = &源码[当前偏移..当前偏移 + 长度];
        match 令牌.kind {
            TokenKind::Ident => {
                // `.方法()` 位：`.` 后的标识符且下一个有意义 token 是 `(`
                //（字段名不是方法名，豁免集合见下方 使用豁免）
                let 方法位 = 前点号 && 后继有意义是开括号(&令牌序列, 索引);
                // 路径根位置（首段）：后跟 `::` 且前不是 `::` 的标识符——
                // `模块词::项` 的首段。字段/变量不可经 `::` 访问，根位豁免
                // 不适用（office-zb #27）；模块词回退替换亦仅限根位
                let 路径头位 = !前路径分隔 && 后继有意义是路径分隔(&令牌序列, 索引);
                // 项目路径链：根段后跟 `::` 时链内段按项目声明名豁免。
                // 根段确认依赖上一标识符留存的候选标记与当前 `::` 状态
                let 项目链中 =
                    项目上下文.is_some() && (项目路径中 || (待项目根 && 前路径分隔));
                if 项目链中 {
                    项目路径中 = true;
                }
                // 声明位保护：紧随声明关键字的名字是用户自己的定义；
                // 例外——库特征实现块内 `fn` 后的方法名是库 API 名称
                //（见 收集库特征方法名），照常参与替换
                let 声明保护 = 前声明态.is_some()
                    && !(前声明态 == Some("fn") && 声明结果.库方法名集.contains(文本段));
                // 各位置豁免集合：
                // - 链内：仅项目声明名（项/模块）——`平台Linux::新建` 豁免，
                //   未定义于项目的 `源码映射项::新建` 照常替换（与教程
                //   `fn 新建` 定义侧一致）；
                // - `::` 后非链（根非项目根）：无项目上下文时保留旧行为
                //   （本文件项名豁免，`接口错误::错误请求`）；有上下文时
                //   一律按库 API 替换（`盒子::新建` 的同名项目项不得误伤）；
                // - `.方法()` 位：仅项目方法名（项集合）——`编辑表.长度()`
                //   的 `长度` 是 `新建向量::元素数` 调用，字段名豁免不适用于方法位；
                // - 其他：本文件声明名 + 项目裸使用处豁免（含结构体字段）
                let 使用豁免 = if 项目链中 {
                    声明结果.项名集.contains(文本段)
                        || 项目上下文.is_some_and(|前索引| {
                            前索引.项名集.contains(文本段) || 前索引.模块名集.contains(文本段)
                        })
                } else if 前路径分隔 {
                    项目上下文.is_none() && 声明结果.项名集.contains(文本段)
                } else if 方法位 {
                    声明结果.项名集.contains(文本段)
                        || 项目上下文.is_some_and(|前索引| 前索引.项名集.contains(文本段))
                } else if 路径头位 {
                    // 路径根位（后跟 `::`）：字段/变量/裸名豁免不适用——它们
                    // 不可经 `::` 访问。缺陷回归（office-zb #27 字段场景）：
                    // 字段名与词表词撞名（如「天数」=Days）时，`天数::新建`
                    // 曾因字段豁免保留「天数」、只替换段位 → `天数::新建`
                    // 报 E0433；字面量/字段访问位等非根位仍按字段豁免。
                    // 仅本文件项名与项目项名/模块名（路径链根）在根位豁免
                    声明结果.项名集.contains(文本段)
                        || 项目上下文.is_some_and(|前索引| 前索引.是路径根(文本段))
                } else {
                    声明结果.项名集.contains(文本段)
                        || 声明结果.变量名集.contains(文本段)
                        || 声明结果.成员名集.contains(文本段)
                        // 项目声明名（项+字段，含其他文件声明）与项目根词
                        //（模块名；包/super/self 为英文，替换表不会命中，
                        // 在此仅作为路径链起点）
                        || 项目上下文.is_some_and(|前索引| {
                            前索引.裸用豁免(文本段) || 前索引.是路径根(文本段)
                        })
                };
                if 声明保护 || 使用豁免 {
                    // 声明位标识符或用户声明名的使用处：保留原样
                    产出.push_str(文本段);
                } else if let Some(英文值) = 别名映射表.get(文本段) {
                    编辑表.push(源映射条目::新建条目(
                        当前偏移,
                        长度,
                        文本段,
                        英文值,
                    ));
                    产出.push_str(英文值);
                } else if 路径头位 && let Some(英文值) = 模块路径表.get(文本段) {
                    // 路径根位回退模块路径表：`异步运行时::睡眠` → `tokio::sleep`、
                    // `#[异步运行时::主函数]` → `#[tokio::main]`（office-zb #10/#18）。
                    // use 语句内已在管线模块路径阶段替换，此处覆盖表达式/属性位置
                    let 归一化 = crate::模块路径::规范化包名连字符(英文值);
                    let 替换值 = 归一化.as_deref().unwrap_or(英文值);
                    编辑表.push(源映射条目::新建条目(
                        当前偏移,
                        长度,
                        文本段,
                        替换值,
                    ));
                    产出.push_str(替换值);
                } else {
                    产出.push_str(文本段);
                }
                // 根段候选判定（基于母语原文；`包`等已在词法阶段转为英文）
                待项目根 = 项目上下文.is_some_and(|前索引| 前索引.是路径根(文本段));
                // `让 mut 名称`：声明位内的 mut 透明传递声明状态；
                // `&mut 类型` 等非声明位的 mut 不传递，库类型引用仍被替换
                前声明态 = 推进声明关键字(前声明态, 文本段);
                前路径分隔 = false;
                前点号 = false;
            }
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {
                产出.push_str(文本段);
                // 空白与注释不打断声明状态、路径限定状态与成员访问状态
            }
            _ => {
                产出.push_str(文本段);
                // 符号终结声明位；连续两个 冒号 构成 `::` 路径限定
                前声明态 = None;
                let 是冒号 = matches!(令牌.kind, TokenKind::Colon);
                // 非 冒号 符号终结项目路径链（`::` 的冒号保持链状态）
                if !是冒号 {
                    项目路径中 = false;
                    待项目根 = false;
                }
                前路径分隔 = if 是冒号 {
                    前路径分隔 || 上次冒号
                } else {
                    false
                };
                上次冒号 = 是冒号;
                前点号 = matches!(令牌.kind, TokenKind::Dot);
            }
        }
        当前偏移 += 长度;
    }
    替换结果 { 产出, 编辑表 }
}

/// 下一个有意义 token（跳过空白/注释）是否为 `(`
///
/// 判定标识符处于「方法调用位」（`实例.方法()`）而非「字段访问位」
///（`实例.字段`）——两者豁免集合不同（字段名不是方法名）。
/// 行选择上限：词法解析器 的 `词法令牌` 仅含 令牌类别/元素数，`令牌序列` 与源码
/// 对齐，索引索引即偏移序位。
fn 后继有意义是开括号(令牌序列: &[rustc_lexer::Token], 索引: usize) -> bool {
    令牌序列
        .get(索引 + 1..)
        .unwrap_or_default()
        .iter()
        .find(|令牌项| {
            !matches!(
                令牌项.kind,
                TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
            )
        })
        .is_some_and(|令牌项| matches!(令牌项.kind, TokenKind::OpenParen))
}

/// 下一个有意义 token（跳过空白/注释）是否为 `::`
///
/// 判定标识符处于「路径根位置」（`模块词::项` 的首段）。词法解析器 将
/// `::` 拆分为两个连续 冒号 token；空白/注释不打断（与主循环
/// `上次冒号` 状态对空白的处理一致）。
fn 后继有意义是路径分隔(令牌序列: &[rustc_lexer::Token], 索引: usize) -> bool {
    let mut 冒号数 = 0;
    for 令牌项 in 令牌序列.get(索引 + 1..).unwrap_or_default() {
        if matches!(
            令牌项.kind,
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
        ) {
            continue;
        }
        if matches!(令牌项.kind, TokenKind::Colon) {
            冒号数 += 1;
            if 冒号数 >= 2 {
                return true;
            }
            continue;
        }
        return false;
    }
    false
}

