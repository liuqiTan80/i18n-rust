//! 界面消息表：ui.toml 解析、`{}` 代入与缺键回退的唯一定义
//!
//! CLI（`rzc`）与 LSP 各有自己的**加载链**——磁盘目录位置、环境变量优先级
//! 不同，这部分留在各自包里；但「TOML 怎么解析」「`{}` 怎么代入」「缺键
//! 回退到哪」必须只有一份实现，否则同一句提示会因入口不同而变语言。
//!
//! 引擎自身走编译期嵌入的静态表（[`包::语言::内置消息表`]），
//! 零解析直取；[`消息表`] 承载运行期从磁盘或显式目录读到的自定义表。
//!
//! 本模块自己是上面那条纪律的适用对象，因此有两条写得出来的规矩：
//!
//! - TOML 取节只有一处实现（[`取文本节`]）。构建整张表与 build.rs 生成的静态
//!   表初始化都走它，「`["界面消息"]` 怎么读」不可能在两处漂移。
//! - `{}` 代入选单趟扫描（[`代入参数`]），游标只在原文上前进；边界语义（参数
//!   多余忽略、参数不足保留 `{}`）由一条与旧实现逐例对跑的差分测试钉住，
//!   见 `母语测试::新旧代入逐例一致`。

use std::collections::HashMap;

/// 一张界面消息表
///
/// 界面消息来自 ui.toml 的 `["界面消息"]` 节；`["解释"]` 节是 LSP 悬停提示
/// 用的大白话说明（键为符号路径，如 `Option::unwrap`），缺省时为空表。
pub struct 消息表 {
    界面消息: HashMap<String, String>,
    解释文档: HashMap<String, String>,
    /// TOML 解析失败的原因文本；`无` 表示解析成功
    ///
    /// 失败不当错误抛出：调用方继续沿加载链回退即可。但**为什么**退得要留个
    /// 可查的线索——用户手写 ui.toml 写坏了，原先只会看到界面默默变回内置
    /// 文案，完全无从下手。见 [`自身::失败原因`]。
    解析失败原因: Option<String>,
}

impl 消息表 {
    /// 解析 ui.toml 内容
    ///
    /// 解析失败视为空表（两节都空），由调用方继续沿加载链回退；失败原因记在
    /// [`自身::失败原因`] 供各入口自行提示。
    pub fn 成表(内容: &str) -> Self {
        let 解析产出 = toml::from_str::<toml::Value>(内容);
        match 解析产出 {
            Ok(文档) => Self {
                界面消息: 取文本节(&文档, "界面消息"),
                解释文档: 取文本节(&文档, "解释"),
                解析失败原因: None,
            },
            Err(详情) => Self {
                界面消息: HashMap::new(),
                解释文档: HashMap::new(),
                解析失败原因: Some(详情.to_string()),
            },
        }
    }

    /// 是否没有任何界面消息
    ///
    /// 显式目录里的 ui.toml 可能只写了 `["解释"]` 节，此时界面消息应继续
    /// 沿加载链回退，而不是拿一张空表把整个界面变成裸键名。
    pub fn 没有消息(&self) -> bool {
        self.界面消息.is_empty()
    }

    /// 取消息模板：本表 → 内置中文表 → 键名本身
    pub fn 取消息(&self, 键名: &str) -> String {
        取模板(&self.界面消息, 键名)
    }

    /// 取消息模板并按出现顺序代入 `{}` 占位符
    pub fn 取带参消息(&self, 键名: &str, 消息参数: &[&str]) -> String {
        代入参数(&self.取消息(键名), 消息参数)
    }

    /// 取大白话解释（缺失返回 `无`，调用方保持原样回退）
    pub fn 解释(&self, 键名: &str) -> Option<&str> {
        self.解释文档.get(键名).map(|文档值| 文档值.as_str())
    }

    /// TOML 解析失败的原因（`无` = 解析成功）
    pub fn 失败原因(&self) -> Option<&String> {
        self.解析失败原因.as_ref()
    }
}

/// 从消息表取模板：本表 → 内置中文表 → 键名本身
///
/// 自定义语言包（用户手写 ui.toml）通常只覆盖自己关心的键，缺失键回退中文
/// 而不是显示裸键名；只有连中文表都没有该键时才回退键名，让漏译一眼可见。
pub fn 取模板(界面消息: &HashMap<String, String>, 键名: &str) -> String {
    if let Some(文案) = 界面消息.get(键名) {
        return 文案.clone();
    }
    let 内置表 = crate::语言::内置消息表("zh");
    if let Some(文案) = 内置表.get(键名) {
        return 文案.clone();
    }
    键名.to_string()
}

/// 按出现顺序把 `{}` 替换为参数；参数多于占位符时忽略多余参数，
/// 参数不足时保留未替换的 `{}`（模板兜底，避免恐慌）。
///
/// 单趟分割：`分割("{}")` 把模板切成 n+1 段，段与段之间恰好是占位符，
/// 于是一遍走完即可决定「代参数」还是「留字面 `{}`」，不必自己维护字节游标
/// ——多字节文案下按字节开窗会切在字符中间（本函数的第一版重写就栽在这里，
/// 由 `母语测试::新旧代入逐例一致` 当场抓出）。
pub fn 代入参数(文本模板: &str, 消息参数: &[&str]) -> String {
    // 预留：模板原长 + 参数实际总长，常见长度下不再扩容
    let 参数总长: usize = 消息参数.iter().map(|单个| 单个.len()).sum();
    let mut 结果串 = String::with_capacity(文本模板.len() + 参数总长);
    let mut 参数号 = 0;
    // 单趟分割：`分割("{}")` 把模板切成 n+1 段，第 0 段之前没有占位符，之后
    // 每段之前恰好一个。段边界由分割器给出，本函数不碰字节游标。
    let mut 段们 = 文本模板.split("{}");
    if let Some(首段) = 段们.next() {
        结果串.push_str(首段);
    }
    for 段 in 段们 {
        // 还有参数就代参数，参数用尽就把 `{}` 原样留在译文里
        if 参数号 < 消息参数.len() {
            结果串.push_str(消息参数[参数号]);
            参数号 += 1;
        } else {
            结果串.push_str("{}");
        }
        结果串.push_str(段);
    }
    结果串
}

/// 把 TOML 文档的某一节按「键 → 字符串值」取出（非字符串值忽略）
///
/// [`消息表::成表`] 与 [`解析界面消息`] 共用本函数，解析语义只有一处。
fn 取文本节(文档: &toml::Value, 节名: &str) -> HashMap<String, String> {
    let mut 出表: HashMap<String, String> = HashMap::new();
    if let Some(表项) = 文档.get(节名).and_then(|节值| 节值.as_table()) {
        for (键名, 值项) in 表项.iter() {
            if let Some(消息文本) = 值项.as_str() {
                出表.insert(键名.clone(), 消息文本.to_string());
            }
        }
    }
    出表
}

/// 解析 ui.toml 的 `["界面消息"]` 节
///
/// 供 build.rs 生成的静态表初始化调用（生成代码在 `语言` 模块内展开），
/// 与其他入口共用同一份解析语义。使用自有字符串存储而非「常驻生命周期的文本切片」：
/// 每语言表仅解析一次，把盒子强转成常驻引用会永久占用全部消息文本，无必要。
pub(crate) fn 解析界面消息(内容: &str) -> HashMap<String, String> {
    let 解析产出 = toml::from_str::<toml::Value>(内容);
    match 解析产出 {
        Ok(文档) => 取文本节(&文档, "界面消息"),
        Err(详情) => {
            let _ = 详情;
            HashMap::new()
        }
    }
}

#[cfg(test)]
mod 母语测试 {
    use super::*;

    /// 旧实现（逐参数从头 `find("{}")`）原样留作差分基准
    ///
    /// 只活在测试里，用来证明 [`代入参数`] 的单趟重写与它逐例一致：重写一旦
    /// 改动边界语义，这条用例必然先红。
    fn 旧代入(文本模板: &str, 消息参数: &[&str]) -> String {
        let mut 拼串 = String::new();
        let mut 剩余 = 文本模板;
        for 单个 in 消息参数 {
            match 剩余.find("{}") {
                Some(位置) => {
                    拼串.push_str(&剩余[..位置]);
                    拼串.push_str(单个);
                    剩余 = &剩余[位置 + 2..];
                }
                None => {
                    拼串.push_str(剩余);
                    return 拼串;
                }
            }
        }
        拼串.push_str(剩余);
        拼串
    }

    fn 边界用例<'甲>() -> Vec<(&'甲 str, &'甲 [&'甲 str])> {
        vec![
            // 常规：一个、多个
            ("已导出到 {}", &["a.rs"]),
            ("项目根: {}，错误: {}", &["/p", "boom"]),
            // 无占位符、空模板、无参数
            ("无占位符", &[]),
            ("", &["x"]),
            ("无占位符", &["多余"]),
            // 参数多余 / 参数不足
            ("只有 {}", &["a", "b"]),
            ("{} 和 {}", &["a"]),
            ("{} {} {}", &["1", "2"]),
            // 连续占位符、首尾占位符
            ("{}{}{}", &["1", "2", "3"]),
            ("{}x", &[]),
            ("x{}", &[]),
            // 单个花括号不构成占位符
            ("{ 单花括号 } 和 {}", &["值"]),
            ("{x} {}", &["值"]),
            // 参数本身含 `{}`：代进去后不再二次代入
            ("套娃 {}", &["{}"]),
            ("{} {}", &["{}", "{}"]),
            // 多字节文本：字节游标须按 `{}` 的 ASCII 长度前进
            ("第 {} 行第 {} 列", &["3", "7"]),
            ("中文{}中文{}尾", &["夹"]),
            ("{}", &["多字节参数内容"]),
        ]
    }

    #[test]
    fn 新旧代入逐例一致() {
        for (文本模板, 消息参数) in 边界用例() {
            assert!(
                代入参数(文本模板, 消息参数) == 旧代入(文本模板, 消息参数),
                "单趟重写与旧实现在「{}」上不一致",
                文本模板
            );
        }
    }

    #[test]
    fn 穷举模板与旧实现逐一对齐() {
        // 三字符表覆盖 `{}` 的错位、连续、首尾形态；长度固定为 5 → 243 个模板，
        // 每个再配 0..2 个参数，共 729 例。穷举比手写用例更能证明「重写没改语义」。
        let 字母表 = ['a', '{', '}'];
        let 参数池 = ["p0", "p1", "p2"];
        let mut 例数 = 0;
        for 序号 in 0..243 {
            let mut 串 = String::new();
            let mut 余 = 序号;
            for _ in 0..5 {
                串.push(字母表[余 % 3]);
                余 /= 3;
            }
            for 个数 in 0..3 {
                例数 += 1;
                let 消息参数 = &参数池[..个数];
                assert!(
                    代入参数(&串, 消息参数) == 旧代入(&串, 消息参数),
                    "模板「{}」配 {} 个参数时不一致",
                    串,
                    个数
                );
            }
        }
        assert!(例数 == 729);
    }

    #[test]
    fn 按顺序代入占位符() {
        assert!(代入参数("已导出到 {}", &["a.rs"]) == "已导出到 a.rs");
        assert!(代入参数("项目根: {}，错误: {}", &["/p", "boom"]) == "项目根: /p，错误: boom");
    }

    #[test]
    fn 参数多余时忽略不足时保留() {
        assert!(代入参数("只有 {}", &["a", "b"]) == "只有 a");
        assert!(代入参数("{} 和 {}", &["a"]) == "a 和 {}");
        assert!(代入参数("无占位符", &[]) == "无占位符");
    }

    #[test]
    fn 两个节都能解析() {
        let 表 = 消息表::成表(
            "[\"界面消息\"]\n\"a\" = \"b\"\n[\"解释\"]\n\"Option::unwrap\" = \"直接取出值，出错就崩溃\"\n",
        );
        assert!(表.取消息("a") == "b");
        assert!(表.解释("Option::unwrap") == Some("直接取出值，出错就崩溃"));
        assert!(表.解释("不存在的键").is_none());
        assert!(表.失败原因().is_none());
    }

    #[test]
    fn 只有解释节时按空表回退() {
        // 只有 ["解释"] 节：界面消息为空，调用方应继续沿加载链回退
        let 表 = 消息表::成表("[\"解释\"]\n\"Vec::push\" = \"末尾追加\"\n");
        assert!(表.没有消息());
        assert!(表.解释("Vec::push") == Some("末尾追加"));
        // 界面消息缺键回退中文内置表，再缺失才回退键名
        assert!(表.取消息("err_line_col") == "第 {} 行第 {} 列");
        assert!(表.取消息("no_such_key") == "no_such_key");
    }

    #[test]
    fn 非法文本不抛错但留下原因() {
        // 旧实现把解析错误整个丢掉：界面静默退回内置表，用户无从知道手写
        // 的 ui.toml 哪里坏了。重构后原因可读，取模板行为不变。
        let 表 = 消息表::成表("这不是 TOML [[[");
        assert!(表.没有消息());
        assert!(表.取消息("err_line_col") == "第 {} 行第 {} 列");
        let 说明 = 表.失败原因().expect("解析失败应留下可读原因");
        assert!(!说明.is_empty());
        // 解析成功的表不带原因
        assert!(
            消息表::成表("[\"界面消息\"]\n\"a\" = \"b\"\n")
                .失败原因()
                .is_none()
        );
    }

    #[test]
    fn 自定义表缺键回退内置中文() {
        // 自定义语言包只写了一个键：其余键回退中文内置表而非裸键名
        let 表 = 消息表::成表("[\"界面消息\"]\n\"cli_about\" = \"Custom\"\n");
        assert!(表.取消息("cli_about") == "Custom");
        assert!(表.取消息("err_line_col") == "第 {} 行第 {} 列");
    }

    #[test]
    fn 取先模板再代入() {
        let 表 = 消息表::成表("[\"界面消息\"]\n\"k\" = \"{} 与 {}\"\n");
        assert!(表.取带参消息("k", &["甲", "乙"]) == "甲 与 乙");
        // 缺键走中文表后再代入：占位符数量随回退模板而定
        assert!(表.取带参消息("err_line_col", &["3", "7"]) == "第 3 行第 7 列");
    }

    #[test]
    fn 静态表入口只取界面消息一节() {
        // build.rs 走的入口：解释节不参与，非法内容按空表处理
        let 消息 =
            解析界面消息("[\"界面消息\"]\n\"k\" = \"v\"\n[\"解释\"]\n\"k\" = \"不该收到\"\n");
        assert!(消息.len() == 1);
        assert!(消息.get("k").map(|文档值| 文档值.as_str()) == Some("v"));
        assert!(解析界面消息(" [[[ ").is_empty());
    }
}
