//! 转译产物坐标 → 母语源码坐标的列映射【zh 自举·批次1】
//! 本文件是源真相：由引导 rzc 转译为 列映射.rs 后交 cargo 编译。
//! 再生成方式见 tools/zh-selfhost/regen.sh；请勿手改同目录下的 列映射.rs。
//!
//! 转译是逐 token 的原地替换，不增删换行，因此**行号恒等**；但中英文 token
//! 长度不同（如 `让` → `let`、`可变` → `mut`），同一行内的列号会发生偏移，
//! 必须回放替换过程才能还原到母语源码的列。
//!
//! 本模块供命令行使用。**不可与 LSP 侧的列映射混用**：LSP 协议要求 UTF-16
//! 代码单元列（`lsp/src/translation_cache.rs`），而命令行输出面向终端，
//! 采用**字符数**列——与 rustc JSON 诊断的 `column_start` 口径一致。
//! 算法同源，但列口径不同，混用会在非 BMP 字符（emoji 等）上产生偏移。
//!
//! 注：`词元.令牌类别/.元素数`、`条目.源偏移/.替换文本`、`令牌种类`、
//! `切分令牌`、`模式匹配!` 是 词法解析器 与未中文化模块（cache）的接口名，
//! 属跨模块契约，待相应模块 zh 化批次联动更新。

use crate::缓存::源映射条目;
use rustc_lexer::{TokenKind, tokenize};
use std::collections::HashMap;

/// 行内列映射分段点：一次长度变化的替换发生后记录的 (英文列, 中文列)
///
/// 两个分段点之间英文与中文同步增长（未替换文本原样输出），
/// 故段内可直接用 `英文列 - 中文列` 的恒定差值换算。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 列分段点 {
    /// 转译产物的行内列（0-based，字符数）
    pub 英文列: u32,
    /// 母语源码的行内列（0-based，字符数）
    pub 中文列: u32,
}

/// 逐行列映射表：回放转译过程得到，供诊断列号回译使用
#[derive(Debug, Clone)]
pub struct 列映射表 {
    /// `逐行分段[i]` 为第 i 行（0-based）的分段点，按 `英文列` 升序且以行首 (0,0) 起始
    逐行分段: Vec<Vec<列分段点>>,
}

impl 列映射表 {
    /// 回放转译过程，构建逐行的列映射
    ///
    /// `母语源码` 为母语源码，`管线映射表` 为转译管线的全量编辑表
    /// （`转译产出::管线映射`，条目按母语源偏移升序）。
    /// 未命中编辑表的词元视为原样输出，长度不变。
    pub fn 构建(母语源码: &str, 管线映射表: &[源映射条目]) -> Self {
        // 索引：母语源字节偏移 → 编辑条目（token 级替换，一个 token 至多一条）
        let 按偏移索引: HashMap<usize, &源映射条目> =
            管线映射表.iter().map(|条目| (条目.源偏移, 条目)).collect();

        let mut 逐行分段: Vec<Vec<列分段点>> = vec![vec![列分段点 {
            英文列: 0,
            中文列: 0,
        }]];
        let mut 中文列 = 0u32;
        let mut 英文列 = 0u32;
        let mut 偏移 = 0usize;

        for 词元 in tokenize(母语源码) {
            let 起点 = 偏移;
            let 词元文本 = &母语源码[偏移..][..词元.len];
            偏移 += 词元.len;

            // 空白与注释不被替换，原样输出；但可能跨行（块注释/连续换行），
            // 需逐字符处理以在新行重置行内列并记录行首分段点
            if matches!(
                词元.kind,
                TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
            ) {
                for char in 词元文本.chars() {
                    if char == '\n' {
                        中文列 = 0;
                        英文列 = 0;
                        逐行分段.push(vec![列分段点 {
                            英文列: 0,
                            中文列: 0,
                        }]);
                    } else {
                        中文列 += 1;
                        英文列 += 1;
                    }
                }
                continue;
            }

            let 中文长度 = 词元文本.chars().count() as u32;
            let 英文长度 = match 按偏移索引.get(&起点) {
                Some(条目) => 条目.替换文本.chars().count() as u32,
                None => 中文长度,
            };

            中文列 += 中文长度;
            英文列 += 英文长度;

            // 仅长度变化时记录分段点：长度未变则该词元前后列关系不变
            if 英文长度 != 中文长度 {
                // 初始化即有一行且只追加，行数恒 ≥ 1，直接按下标改最后一行
                let 最后行 = 逐行分段.len() - 1;
                逐行分段[最后行].push(列分段点 {
                    英文列, 中文列
                });
            }
        }

        Self { 逐行分段 }
    }

    /// 把转译产物的 1-based (行, 列) 映射回母语源码的 1-based (行, 列)
    ///
    /// 转译不增删换行，行号恒等返回。
    /// 落在替换区间内的位置按差值近似到最近的中文词元起点——
    /// 这与 LSP 侧一致，诊断只需指向正确的词元，无需精确到字符内部。
    ///
    /// 行号越界（映射表行数不足）时原样返回，不臆造坐标。
    pub fn 映射位置(&self, 行号: u32, 列号: u32) -> (u32, u32) {
        let 行索引 = if 行号 == 0 { 0 } else { 行号 - 1 };
        let 行内表 = match self.逐行分段.get(行索引 as usize) {
            Some(表) => 表,
            None => return (行号, 列号),
        };
        let 目标列 = (if 列号 == 0 { 0 } else { 列号 - 1 }) as i32; // 1-based → 0-based

        // 取最后一个 英文列 <= 目标列 的分段点（行首点保证存在，索引安全）
        let mut 当前点 = 列分段点 {
            英文列: 0,
            中文列: 0,
        };
        for 分段点 in 行内表 {
            if 分段点.英文列 as i32 <= 目标列 {
                当前点 = *分段点;
            } else {
                break;
            }
        }

        let 差值 = 当前点.英文列 as i32 - 当前点.中文列 as i32;
        let 还原列 = 目标列 - 差值;
        let 中文列号 = if 还原列 < 0 { 0 } else { 还原列 };
        (行号, 中文列号 as u32 + 1) // 回到 1-based
    }

    /// 映射表覆盖的行数（供测试与诊断用）
    pub fn 行数(&self) -> usize {
        self.逐行分段.len()
    }
}

#[cfg(test)]
mod 单元测试 {
    use super::*;

    /// 中文 `    让 可变 数量 = 10;`
    /// 英文 `    let mut 数量 = 10;`
    ///
    /// 字节偏移：4 个前导空格后「让」占 3 字节（偏移 4），
    /// 再 1 空格后「可变」占 6 字节（偏移 8）。
    fn 样本() -> (&'static str, Vec<源映射条目>) {
        let 源码 = "    让 可变 数量 = 10;";
        let 编辑表 = vec![
            源映射条目::新建条目(4, 3, "让", "let"),
            源映射条目::新建条目(8, 6, "可变", "mut"),
        ];
        (源码, 编辑表)
    }

    #[test]
    fn 映射关键字列号() {
        let (源码, 编辑表) = 样本();
        let 映射表 = 列映射表::构建(源码, &编辑表);

        // 英文列 5（1-based）= `let` 的首字符 → 中文列 5 = 「让」
        assert_eq!(映射表.映射位置(1, 5), (1, 5));
        // 英文列 9 = `mut` 的首字符 → 中文列 7 = 「可」
        assert_eq!(映射表.映射位置(1, 9), (1, 7));
        // 英文列 13 = 「数」 → 中文列 10 = 「数」（未被替换，但受前面两个替换影响）
        assert_eq!(映射表.映射位置(1, 13), (1, 10));
        // 英文列 16 = `=` → 中文列 13 = `=`
        assert_eq!(映射表.映射位置(1, 16), (1, 13));
    }

    /// 前导空格未被替换，列号应恒等
    #[test]
    fn 替换前恒等() {
        let (源码, 编辑表) = 样本();
        let 映射表 = 列映射表::构建(源码, &编辑表);
        assert_eq!(映射表.映射位置(1, 1), (1, 1));
        assert_eq!(映射表.映射位置(1, 4), (1, 4));
    }

    /// 空编辑表 → 恒等映射（转译未改动任何词元时不应漂移）
    #[test]
    fn 无编辑则恒等() {
        let 映射表 = 列映射表::构建("    让 数量 = 1;", &[]);
        for 列号 in 1..=15 {
            assert_eq!(映射表.映射位置(1, 列号), (1, 列号));
        }
    }

    /// 多行：行号恒等，且每行的列差独立累积（不跨行污染）
    #[test]
    fn 多行互相独立() {
        let 源码 = "让 x = 1;\n让 可变 y = 2;";
        // 字节偏移：第 1 行「让 x = 1;」占 0..9（「让」3 字节 + 7 个 ASCII），
        // `\n` 在偏移 10，故第 2 行「让」在 11、「可变」在 15
        let 编辑表 = vec![
            源映射条目::新建条目(0, 3, "让", "let"),
            源映射条目::新建条目(11, 3, "让", "let"),
            源映射条目::新建条目(15, 6, "可变", "mut"),
        ];
        let 映射表 = 列映射表::构建(源码, &编辑表);
        assert_eq!(映射表.行数(), 2);

        // 第 1 行：`let x = 1;` 列 5 = `x` → 中文列 3 = `x`
        assert_eq!(映射表.映射位置(1, 5), (1, 3));
        // 第 2 行：`let mut y = 2;` 列 9 = `y` → 中文列 6 = `y`
        assert_eq!(映射表.映射位置(2, 9), (2, 6));
    }

    /// 行号越界时原样返回，不臆造坐标
    #[test]
    fn 行号越界直返() {
        let (源码, 编辑表) = 样本();
        let 映射表 = 列映射表::构建(源码, &编辑表);
        assert_eq!(映射表.映射位置(99, 7), (99, 7));
    }

    /// 列号为 0（防御：上游给出非法坐标）不应下溢 崩溃
    #[test]
    fn 零列号不下溢() {
        let (源码, 编辑表) = 样本();
        let 映射表 = 列映射表::构建(源码, &编辑表);
        assert_eq!(映射表.映射位置(1, 0), (1, 1));
    }
}
