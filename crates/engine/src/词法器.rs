    /// 方法位判定跨空白与注释：圆点与名字之间夹什么都是方法位
    ///
    /// 方法位改用「上一个有意义词元是否为圆点」的状态变量（早先对每个
    /// 标识符回扫词元流），空白与注释不重置该状态正是两条实现等价的关键
    /// 边界；同时确认非方法位照常替换，状态没有被粘住。
    #[test]
    fn 词法方法位跨杂项让位() {
        let 关键字表 = HashMap::from([("枚举".to_string(), "enum".to_string())]);
        let 方法让位集 = HashSet::from(["枚举".to_string()]);
        for 样本文本 in [
            "列.枚举();",
            "列 . 枚举();",
            "列.\n    枚举();",
            "列. /* c */ 枚举();",
            "列. // c\n    枚举();",
        ] {
            let 输出文本 = 分词转译(
                样本文本,
                &关键字表,
                &HashMap::new(),
                &HashMap::new(),
                &HashSet::new(),
                &方法让位集,
                &HashMap::new(),
            )
            .输出;
            assert_eq!(输出文本, 样本文本, "方法位让位失效：{样本文本:?}");
        }
        // 对照：不在圆点之后的同名标识符照常替换
        let 输出文本 = 分词转译(
            "枚举();",
            &关键字表,
            &HashMap::new(),
            &HashMap::new(),
            &HashSet::new(),
            &方法让位集,
            &HashMap::new(),
        )
        .输出;
        assert_eq!(输出文本, "enum();");
    }

