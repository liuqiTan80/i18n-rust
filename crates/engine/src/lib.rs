///（内部含完整词法转译）取本文件声明，随后管线里的词法阶段再跑一遍。
///
/// 本入口把词法阶段提到回调之前执行，本文件声明从词法产物顺带收集，回调
/// 只需合并其他文件的缓存声明。输出与「预扫声明 → 建上下文 → 完整管线」
/// 逐字节一致（项目上下文按构造相同），另返回本文件声明与所用上下文，
