//! 名字缓存：把逐标识符的映射表查找折算成一次槽位探测
//!
//! 转译管线的词法、别名、教学校验 三个阶段都要对源码里的每个标识符查
//! 一两张 `哈希映射`，而同一份源码里名字高度重复（局部变量、字段名、库接口
//! 被反复引用）。映射表查找实测约 22 ns/次且受随机访存限制，2000 行样例
//! 近 4000 个标识符合计就是上百微秒。这里按名字直映解析结果：重复名字只
//! 付一次「散列 + 字符串比较」的探测，首次出现才查表。
//!
//! 设计（中文原生重构，非英文版的逐句对译）：
//! - **逐字节**乘-异或散列，取代原版的「每 8 字节成一个字」：后者要靠
//!   `from_le_bytes` / `rotate_left` / `copy_from_slice` 三个方法位，而中文
//!   语言包对它们**没有词条**（本分支实测登记），于是那套定长缓冲 + 越界
//!   钳位的写法只能整体保留英文。改成逐字节折叠后，一个 `对于` 循环加一次
//!   `溢出乘` 就写完，会恐慌的分支直接归零——多付的是短名字上几次乘法，
//!   而本表只分桶、比错了最多重解析一次，分布质量够用。
//! - 槽存**定长数组**而非堆上向量：槽位数是编译期常量（256），整表随结构
//!   一次落位，省掉一次堆分配；`选项<(&文本, 事实)>` 在 `事实` 可复制时可整体
//!   复制，正好满足数组重复初始化的要求。
//! - 取值接口写成「命中即返回、未命中则解析后回填」两条直路，取代三分支
//!   模式匹配（词形「匹配」在中文语言包里同时是分支匹配关键字与布尔谓词宏，
//!   属一词多译，本分支禁用）。
//! - 开地址单槽、后来者直接覆盖：命中与否只影响速度、不影响正确性——槽内
//!   保存名字全文，取用时逐字节比较，散列碰撞不会把 A 的事实给到 B。

/// 槽位指数的位宽（2 的幂，256 槽）：探测只碰一次内存，冲突时覆盖即可
const 槽位指数: usize = 8;

/// 槽位总数
pub(crate) const 槽位总数: usize = 1 << 槽位指数;

/// 名字到槽位的散列：逐字节的异或-乘法折叠（FNV 与 FxHash 之间的极简形态）
///
/// 初值取名字长度，使「一个是另一个前缀」的两个名字落到不同桶；随后每字节
/// 一次「异或 + 溢出乘」，把全部字节搅进高位。不引哈希器依赖、也不调
/// `默认哈希器`（它走 SipHash，短名字上每字节约 1 纳秒）。
pub(crate) fn 名字槽位(名字: &str) -> usize {
    const 散列质数: u64 = 0x517c_c1b7_2722_0a95;
    let mut 散列: u64 = 名字.len() as u64;
    for 字节值 in 名字.as_bytes() {
        散列 = (散列 ^ (*字节值 as u64)).wrapping_mul(散列质数);
    }
    // 取高位：乘法低位扩散差（只差一个末字节的名字低位几乎相同），
    // 标准库的哈希映射同理用高位定桶
    (散列 >> (64 - 槽位指数)) as usize
}

/// 名字级直映缓存：槽内存「名字全文 + 事实」，未命中的事实由调用方解析
///
/// `事实` 须可复制（通常是若干 `选项<(&'甲 文本)>` 与 `布尔` 组成的小结构），
/// 这样命中时零分配、零引用计数；`'甲` 是名字与事实里借用的映射表值的共同
/// 生命周期（都来自同一次转译调用的输入）。名字与寿命都用中文原生写法，
/// 类型参数位与寿命位对 rzc 与 rustc 均合法（本分支实测）。
pub(crate) struct 名字缓存<'甲, 事实: Copy> {
    槽位: [Option<(&'甲 str, 事实)>; 槽位总数],
}

impl<'甲, 事实: Copy> 名字缓存<'甲, 事实> {
    /// 新建缓存：全部槽位置空（编译期定形，无堆分配）
    pub(crate) fn 新建() -> Self {
        Self {
            槽位: [None; 槽位总数],
        }
    }

    /// 取名字对应的事实：命中直接返回；未命中时调用 `解析` 并回填。
    ///
    /// `解析` 是无参闭包。特征约束位只认英文写法（本分支实测的已知限制，见台账）：
    /// 中文词形「函数」既是闭包特征又是定义关键字，属一词多译，此处不启用豁免。
    pub(crate) fn 取或解析<解析闭包: FnOnce() -> 事实>(
        &mut self,
        名字: &'甲 str,
        解析: 解析闭包,
    ) -> 事实 {
        let 槽 = 名字槽位(名字);
        // 槽内是可复制值，解构即复制，不与后续写槽冲突
        if let Some((已存, 事实)) = self.槽位[槽]
            && 已存 == 名字
        {
            return 事实;
        }
        let 事实 = 解析();
        self.槽位[槽] = Some((名字, 事实));
        事实
    }
}

#[cfg(test)]
mod 母语测试 {
    use super::*;

    #[test]
    fn 每名字只解析一次() {
        // 同一名字第二次取值不再调用解析（用计数变量验证）
        let mut 调用数: usize = 0;
        let mut 缓存: 名字缓存<'_, u32> = 名字缓存::新建();
        let 一 = 缓存.取或解析("甲", || {
            调用数 += 1;
            1
        });
        let 二 = 缓存.取或解析("甲", || {
            调用数 += 1;
            2
        });
        assert_eq!((一, 二, 调用数), (1, 1, 1));
    }

    #[test]
    fn 同槽覆盖不串味() {
        // 「甲q」与「甲」实测同为 238 号槽（逐字节散列，256 槽）；其余候选
        // 不撞。先把这个事实钉在断言里，再验证同槽名字的解析结果互不污染
        let 目标槽 = 名字槽位("甲");
        let mut 撞名: Option<&str> = None;
        for 候选 in ["甲乙", "甲丙", "甲丁", "甲q"] {
            if 名字槽位(候选) == 目标槽 {
                撞名 = Some(候选);
            }
        }
        let 撞名 = 撞名.expect("候选组中应有且仅有一个与甲同槽的名字");
        let mut 缓存: 名字缓存<'_, &str> = 名字缓存::新建();
        assert_eq!(缓存.取或解析("甲", || "一"), "一");
        assert_eq!(缓存.取或解析(撞名, || "二"), "二");
        // 被覆盖后回到「甲」会重新解析，但取到的必须仍是「甲」的事实
        assert_eq!(缓存.取或解析("甲", || "一"), "一");
    }

    #[test]
    fn 前缀名字不落同槽() {
        // 散列初值含名字长度，故前缀关系不撞槽（这是本版散列的立足点）
        assert!(名字槽位("名字") != 名字槽位("名字缓存"));
    }

    #[test]
    fn 槽位恒在范围内() {
        for 名字 in ["", "a", "变量", "很长的标识符名字_1234567890"] {
            assert!(名字槽位(名字) < 槽位总数);
        }
    }
}
