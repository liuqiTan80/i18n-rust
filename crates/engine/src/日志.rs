//! 轻量结构化日志系统，支持 `RZ_LOG=debug` 等环境变量控制等级（调试/信息/警告/错误）。
//! 输出格式：`[时间戳] [等级] [模块名] 消息`（时间戳为世界时，无第三方依赖）。
//! 提供 `调试日志!`、`信息日志!`、`警告日志!`、`错误日志!` 四个宏供其他模块使用。

#[cfg(test)]
use std::sync::{Mutex, MutexGuard};
use std::sync::{
    Once,
    atomic::{AtomicBool, AtomicU8, Ordering},
};
use std::time::{SystemTime, UNIX_EPOCH};

/// 日志等级（按严重程度递增，序数值用于比较过滤）
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 日志等级 {
    /// 调试等级：开发阶段详细信息
    调试级 = 0,
    /// 信息等级：正常流程关键节点
    信息级 = 1,
    /// 警告等级：潜在问题但不影响运行
    警告级 = 2,
    /// 错误等级：需要关注的异常情况
    错误级 = 3,
}

impl 日志等级 {
    /// 从环境变量取值解析等级（大小写不敏感，警告另接受 `warn | warning` 全称拼写）
    pub fn 解析环境(输入文本: &str) -> Option<日志等级> {
        match 输入文本.trim().to_ascii_lowercase().as_str() {
            "debug" => Some(Self::调试级),
            "info" => Some(Self::信息级),
            "warn" | "warning" => Some(Self::警告级),
            "error" => Some(Self::错误级),
            _ => None,
        }
    }

    /// 返回当前语言下的显示文字
    pub fn 显示文字(&self) -> String {
        let 映射键 = match self {
            Self::调试级 => "log_level_debug",
            Self::信息级 => "log_level_info",
            Self::警告级 => "log_level_warn",
            Self::错误级 => "log_level_error",
        };
        crate::语言::取消息(映射键)
    }

    /// 从序数还原日志等级（用于从原子u8 读取）
    fn 从序号还原(序数: u8) -> 日志等级 {
        match 序数 {
            0 => Self::调试级,
            1 => Self::信息级,
            3 => Self::错误级,
            _ => Self::警告级,
        }
    }
}

/// 默认等级的序数（警告）：`等级存储` 静态量的初值，无环境变量时生效。
///
/// 写成字面量而不是 `自身::警告级 作为 字节` 是有意的——这样「初值 ↔ 枚举序数」的一致性
/// 才需要被测试钉住：枚举变体一旦重排（调试级/信息级/警告级/错误级 的序数值变了），
/// 默认等级会静默漂移成「调试」或「错误」，而 `默认等级为警告测试` 会红。
const 默认等级序数: u8 = 2;
/// 当前生效的日志等级（默认警告：静默但保留关键输出）
static 等级存储: AtomicU8 = AtomicU8::new(默认等级序数);
/// 是否已从环境变量初始化（幂等标记）
static 已初始化: Once = Once::new();
/// 是否已被程序化设置（置位后环境变量不再覆盖，保证程序化优先级更高）
static 等级已程序化: AtomicBool = AtomicBool::new(false);

/// 从环境变量初始化日志等级（幂等，仅首次生效）
///
/// 示例：`RZ_LOG=debug rzc run 文件.zh` 启用全部日志；`RZ_LOG=error` 仅输出错误。
/// 若等级已被 `设置等级` 程序化设置，则环境变量不覆盖。
/// `初始化()` 的取舍：程序化设置优先于环境变量
///
/// 判定本体单独拆出来是为了能直接断言——`初始化()` 本体的一次性全进程只生效一次，
/// 用例若不是第一个调它的，断言就只是在验证「已经没人能改了」，而不是这条规则。
fn 环境应覆盖(程序化已设置: bool) -> bool {
    !程序化已设置
}

pub fn 初始化() {
    已初始化.call_once(|| {
        if !环境应覆盖(等级已程序化.load(Ordering::Relaxed)) {
            return;
        }
        if let Ok(读取值) = std::env::var("RZ_LOG")
            && let Some(等级) = 日志等级::解析环境(&读取值)
        {
            等级存储.store(等级 as u8, Ordering::Relaxed);
        }
    });
}

/// 程序化设置日志等级（优先级高于环境变量，测试与嵌入场景使用）
pub fn 设置等级(等级: 日志等级) {
    等级已程序化.store(true, Ordering::Relaxed);
    等级存储.store(等级 as u8, Ordering::Relaxed);
}

/// 返回当前生效的日志等级
pub fn 当前等级() -> 日志等级 {
    日志等级::从序号还原(等级存储.load(Ordering::Relaxed))
}

/// 判断指定等级是否应输出（等级 >= 当前等级时才输出）
pub fn 启用判定(等级: 日志等级) -> bool {
    等级 >= 当前等级()
}

/// 测试专用的日志等级守卫（纪律与 `语言::钉住语言` 一致）
///
/// 等级是进程全局（`等级存储`），而标准测试框架用多线程并发跑用例：任何
/// 「改等级」或「断言等级」的用例都必须持 `测试等级` 返回的守卫，
/// 否则两侧互相翻转全局值，随机红（实测：把断言用例的窗口撑开 150 毫秒，
/// 与逐个建缓存就写一次等级的旧做法并发跑，12/12 轮全红）。
/// 离开作用域时恢复进入前的等级，避免把状态留给后续用例。
#[cfg(test)]
pub(crate) struct 级别测试守卫<'甲> {
    先前: 日志等级,
    _锁: MutexGuard<'甲, ()>,
}

#[cfg(test)]
impl<'甲> Drop for 级别测试守卫<'甲> {
    fn drop(&mut self) {
        设置等级(self.先前);
    }
}

/// 串行化「改等级 / 断言等级」的用例；毒化由持锁方恐慌造成，状态仍可继续用
#[cfg(test)]
static 等级测试锁: Mutex<()> = Mutex::new(());

#[cfg(test)]
fn 等级锁<'甲>() -> MutexGuard<'甲, ()> {
    等级测试锁
        .lock()
        .unwrap_or_else(|中毒守卫| 中毒守卫.into_inner())
}

/// 把等级钉到 `等级` 并持锁到返回的守卫离开作用域，之后恢复原值
#[cfg(test)]
pub(crate) fn 测试等级<'甲>(等级: 日志等级) -> 级别测试守卫<'甲> {
    测试静音();
    let 锁 = 等级锁();
    let 先前 = 当前等级();
    设置等级(等级);
    级别测试守卫 { 先前, _锁: 锁 }
}

/// 需要安静日志的用例（构造缓存等）走这里：全进程只把等级压到错误一次
///
/// 旧做法是在共享辅助函数里每次调用都 `设置等级(错误级)`——那是个不持锁的
/// 环境写侧，任何断言等级的用例都在与它赛跑（实测撑开窗口后 12/12 轮红）。
/// 收敛成一次性写入，且这一次写入必须在持锁下进行，才与 `测试等级` 互斥。
///
/// 用 `尝试加锁` 而不是阻塞式抢锁：拿不到锁说明有「断言等级」的用例正处在窗口
/// 里，那就跳过（本函数每个建缓存的用例都会再走一遍，下一次照样能落地）。这样
/// 既不会与它互翻全局值，也不可能自锁——持守卫的用例里再调建缓存只是
/// 这次不静音，不会像阻塞式抢锁那样把标准库的非可重入互斥锁变成死锁。
#[cfg(test)]
pub(crate) fn 测试静音() {
    static 已静音: AtomicBool = AtomicBool::new(false);
    if 已静音.load(Ordering::Relaxed) {
        return; // 已静音：热路径上只是读一个原子量
    }
    let 尝试结果 = 等级测试锁.try_lock();
    if let Ok(_守卫) = 尝试结果 {
        已静音.store(true, Ordering::Relaxed);
        设置等级(日志等级::错误级);
    }
}

/// 生成一条日志行文本（不包含等级判断，供测试与复用）
pub fn 格式化日志行(等级: 日志等级, 模块名: &str, 日志消息: &str) -> String {
    format!(
        "[{}] [{}] [{}] {}",
        当前时间戳(),
        等级.显示文字(),
        模块名,
        日志消息
    )
}

/// 写入一条日志到标准错误（等级不足时直接返回）
pub fn 写日志(等级: 日志等级, 模块名: &str, 日志消息: &str) {
    if !启用判定(等级) {
        return;
    }
    eprintln!("{}", 格式化日志行(等级, 模块名, 日志消息));
}

// ============================================================
// 时间戳（世界时，手写日历转换，避免引入第三方日历库依赖）
// ============================================================

/// 返回当前世界时间戳，格式「年-月-日 时:分:秒」
fn 当前时间戳() -> String {
    let 秒数 = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|秒差| 秒差.as_secs())
        .unwrap_or(0);
    let (年, 月, 日, 时, 分钟, 秒) = 分解时间(秒数);
    format!("{年:04}-{月:02}-{日:02} {时:02}:{分钟:02}:{秒:02}")
}

/// 将纪元秒数分解为 (年, 月, 日, 时, 分, 秒)（世界时）
/// 使用公历日数分解算法，无第三方依赖
fn 分解时间(总秒: u64) -> (i64, u32, u32, u32, u32, u32) {
    let 天数 = (总秒 / 86_400) as i64;
    let 日内秒 = 总秒 % 86_400;

    let 基准日 = 天数 + 719_468;
    let 纪元号 = 基准日.div_euclid(146_097);
    let 年内日 = 基准日 - 纪元号 * 146_097;
    let 年偏移 = (年内日 - 年内日 / 1_460 + 年内日 / 36_524 - 年内日 / 146_096) / 365;
    let 年 = 年偏移 + 纪元号 * 400;
    let 年内天 = 年内日 - (365 * 年偏移 + 年偏移 / 4 - 年偏移 / 100);
    let 月偏移 = (5 * 年内天 + 2) / 153;
    let 日 = (年内天 - (153 * 月偏移 + 2) / 5 + 1) as u32;
    let 月 = (月偏移 + if 月偏移 < 10 { 3 } else { -9 }) as u32;
    let 年 = if 月 <= 2 { 年 + 1 } else { 年 };

    (
        年,
        月,
        日,
        (日内秒 / 3600) as u32,
        ((日内秒 % 3600) / 60) as u32,
        (日内秒 % 60) as u32,
    )
}

