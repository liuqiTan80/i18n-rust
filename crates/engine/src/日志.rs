#[cfg(test)]
mod 母语测试 {
    use super::*;

    #[test]
    fn 等级解析测试() {
        assert_eq!(日志等级::解析环境("debug"), Some(日志等级::调试级));
        assert_eq!(日志等级::解析环境("INFO"), Some(日志等级::信息级));
        assert_eq!(日志等级::解析环境("warn"), Some(日志等级::警告级));
        assert_eq!(日志等级::解析环境("warning"), Some(日志等级::警告级));
        assert_eq!(日志等级::解析环境("error"), Some(日志等级::错误级));
        assert_eq!(日志等级::解析环境("verbose"), None);
        assert_eq!(日志等级::解析环境(""), None);
    }

    #[test]
    fn 默认等级为警告测试() {
        // 约定：无环境变量时默认「警告」——教学级(信息)静默、警告与错误保留。
        // 旧实现只有一句取当前等级、没有任何断言，把初值改成别的
        // 数也照样全绿（变异实测），所以这里钉的是三方一致：初值常量 ↔ 枚举序数 ↔
        // 从序号还原。
        assert_eq!(
            默认等级序数,
            日志等级::警告级 as u8,
            "默认等级初值与警告的序数脱钩了"
        );
        for 等级 in [
            日志等级::调试级,
            日志等级::信息级,
            日志等级::警告级,
            日志等级::错误级,
        ] {
            assert_eq!(日志等级::从序号还原(等级 as u8), 等级, "{等级:?} 序数往返");
        }
        assert_eq!(
            日志等级::从序号还原(7),
            日志等级::警告级,
            "未知序数须兜底为警告（保守：不放大也不静默）"
        );
    }

    #[test]
    fn 启用判定按等级过滤测试() {
        // 等级是进程全局：改 + 断言必须持守卫，否则与并发用例互翻（见 级别测试守卫）
        let _等级 = 测试等级(日志等级::警告级);
        assert!(!启用判定(日志等级::调试级));
        assert!(!启用判定(日志等级::信息级));
        assert!(启用判定(日志等级::警告级));
        assert!(启用判定(日志等级::错误级));
    }

    #[test]
    fn 分解时间纪元测试() {
        assert_eq!(分解时间(0), (1970, 1, 1, 0, 0, 0));
    }

    #[test]
    fn 分解时间已知日期测试() {
        // 2026-01-01 与 2026-08-13 零时的纪元秒
        assert_eq!(分解时间(1_767_225_600), (2026, 1, 1, 0, 0, 0));
        assert_eq!(分解时间(1_786_579_200), (2026, 8, 13, 0, 0, 0));
    }

    #[test]
    fn 分解时间时分秒测试() {
        // 1970-01-01 十二时三十四分五十六秒 = 45296 秒
        assert_eq!(分解时间(45_296), (1970, 1, 1, 12, 34, 56));
        // 闰年 2024-02-29（2024-01-01 = 1704067200，加 59 天）
        assert_eq!(
            分解时间(1_704_067_200 + 59 * 86_400),
            (2024, 2, 29, 0, 0, 0)
        );
    }

    #[test]
    fn 格式化日志行结构测试() {
        // 等级文字走全局语言（`显示文字` → `语言::取消息`）：断言中文
        // 「信息」就得持语言守卫，否则会与切语言的用例竞争——它把等级换成
        // 别的语言文字，本用例随机红（实测：工作区并行跑发行版全量时会咬）。
        let _语言 = crate::语言::钉住语言("zh");
        let 文本行 = 格式化日志行(日志等级::信息级, "test_module", "test message 42");
        // 形如「[时间戳] [信息] [模块名] 消息」，本例的消息段为固定文本
        assert!(文本行.starts_with('['));
        assert!(文本行.contains("] [信息] [test_module] test message 42"));
        // 时间戳年份段
        let 年份段 = &文本行[1..5];
        assert!(年份段.chars().all(|每字符| 每字符.is_ascii_digit()));
        assert!(文本行.contains("-"));
    }

    #[test]
    fn 低等级不输出测试() {
        // 等级设为错误时，信息级写入不应恐慌（被过滤，无输出）
        let _等级 = 测试等级(日志等级::错误级);
        写日志(日志等级::信息级, "test_module", "不应输出");
        log_info!("test_module", "宏调用不应恐慌 {}", 1);
        log_debug!("test_module", "调试消息");
        assert!(启用判定(日志等级::错误级));
    }

    #[test]
    fn 宏在启用等级工作测试() {
        // 调试级下四个宏都应放行；宏本身不恐慌只是下限，等级判定才是可断言的行为
        let _等级 = 测试等级(日志等级::调试级);
        assert!(启用判定(日志等级::调试级));
        assert!(启用判定(日志等级::信息级));
        assert!(启用判定(日志等级::警告级));
        assert!(启用判定(日志等级::错误级));
        log_debug!("test_module", "调试 {}", "内容");
        log_info!("test_module", "信息 {}", 42);
        log_warn!("test_module", "警告");
        log_error!("test_module", "错误");
    }

    #[test]
    fn 程序化设置不被初始化覆盖测试() {
        // 程序化设置后，`初始化()`（读环境变量）不得覆盖——契约：程序化优先级更高
        let _等级 = 测试等级(日志等级::错误级);
        assert!(等级已程序化.load(Ordering::Relaxed));
        初始化();
        assert_eq!(当前等级(), 日志等级::错误级);
        // 规则本体走纯函数断言：上面的 `初始化()` 受一次性约束，若不是本进程第一个
        // 调用它的用例，「没被覆盖」可能只是时序巧合，这里把判定逻辑单独钉死。
        assert!(!环境应覆盖(true), "已程序化设置时环境变量不得覆盖");
        assert!(环境应覆盖(false), "未程序化设置时环境变量应生效");
    }
}
