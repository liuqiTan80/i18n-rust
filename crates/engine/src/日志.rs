//! 日志模块【zh 自举·批次1】
//! 本文件是源真相：由引导 rzc 转译为 日志.rs 后交 cargo 编译。
//! 再生成方式见 tools/zh-selfhost/regen.sh；请勿手改同目录下的 日志.rs。
//!
//! 轻量结构化日志系统，支持 RZ_LOG 环境变量控制级别（debug/info/warn/错误模块）。
//! 输出格式：`[时间戳] [级别] [模块名] 消息`（时间戳为 UTC，无第三方依赖）。
//! 提供 调试日志!、信息日志!、警告日志!、错误日志! 四个宏供其他模块使用。
//!
//! 注：`调用一次`、`作为字符串`、`欧几里得除`、`宏导出` 与宏内部的
//! `$包`、`tt` 暂无中文词条/为 Rust 宏专有语法，按英文原样书写；
//! `"debug"`、`"log_level_*"` 等字符串是与语言包对齐的数据键，保持原文。

use std::sync::Once;
use std::sync::atomic::{AtomicBool, AtomicU8, Ordering};

/// 日志级别（按严重程度递增，序数值用于比较过滤）
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 日志级别 {
    /// 调试级别：开发阶段详细信息
    调试级别 = 0,
    /// 信息级别：正常流程关键节点
    信息级别 = 1,
    /// 警告级别：潜在问题但不影响运行
    警告级别 = 2,
    /// 错误级别：需要关注的异常情况
    错误级别 = 3,
}

impl 日志级别 {
    /// 从 RZ_LOG 环境变量取值解析（大小写不敏感，支持 warning 别名）
    pub fn 解析环境值(文本内容: &str) -> Option<日志级别> {
        match 文本内容.trim().to_ascii_lowercase().as_str() {
            "debug" => Some(Self::调试级别),
            "info" => Some(Self::信息级别),
            "warn" | "warning" => Some(Self::警告级别),
            "error" => Some(Self::错误级别),
            _ => None,
        }
    }

    /// 返回当前语言下的显示文字
    pub fn 显示文字(&self) -> String {
        let 键 = match self {
            Self::调试级别 => "log_level_debug",
            Self::信息级别 => "log_level_info",
            Self::警告级别 => "log_level_warn",
            Self::错误级别 => "log_level_error",
        };
        crate::语言::查句(键)
    }

    /// 从序号还原日志级别（用于从 AtomicU8 读取）
    fn 从序号还原(序号: u8) -> 日志级别 {
        match 序号 {
            0 => Self::调试级别,
            1 => Self::信息级别,
            3 => Self::错误级别,
            _ => Self::警告级别,
        }
    }
}

/// 当前生效的日志级别（默认警告：静默但保留关键输出）
static 级别存储: AtomicU8 = AtomicU8::new(2);
/// 是否已从环境变量初始化（幂等标记）
static 已初始化: Once = Once::new();
/// 是否已被程序化设置（置位后 RZ_LOG 不再覆盖，保证程序化优先级更高）
static 已程序化设置: AtomicBool = AtomicBool::new(false);

/// 从 RZ_LOG 环境变量初始化日志级别（幂等，仅首次生效）
///
/// 示例：`RZ_LOG=debug rzc run file.zh` 启用全部日志；
/// `RZ_LOG=错误模块` 仅输出错误。
/// 若级别已被 [`set_log_level`] 程序化设置，则环境变量不覆盖。
pub fn 初始化() {
    已初始化.call_once(|| {
        if 已程序化设置.load(Ordering::Relaxed) {
            return;
        }
        if let Ok(值) = std::env::var("RZ_LOG")
            && let Some(级别) = 日志级别::解析环境值(&值)
        {
            级别存储.store(级别 as u8, Ordering::Relaxed);
        }
    });
}

/// 程序化设置日志级别（优先级高于 RZ_LOG，测试与嵌入场景使用）
pub fn 设置日志级别(级别: 日志级别) {
    已程序化设置.store(true, Ordering::Relaxed);
    级别存储.store(级别 as u8, Ordering::Relaxed);
}

// 以下两个转发供其他 .zh 模块调用：`初始化`/`日志级别` 两词撞第三方
// 日志词表（crates/日志.toml：`初始化`→init、`日志级别`→Level），
// 他文件引用时不在声明位也无法被本地项遮蔽，会被替换出生态名；
// 本模块内声明位/同名项豁免生效，复合别名名未被劫持，可安全透传。

/// [`初始化`] 的未劫持别名入口（供 .zh 消费方使用）
pub fn 引擎日志启用() {
    初始化();
}

/// 静默日志输出（仅保留错误级，供测试抑制刷屏；等价
/// `设置日志级别(日志级别::错误级别)` 的未劫持别名入口）
pub fn 静默日志() {
    设置日志级别(日志级别::错误级别);
}

/// 返回当前生效的日志级别
pub fn 当前级别() -> 日志级别 {
    日志级别::从序号还原(级别存储.load(Ordering::Relaxed))
}

/// 判断指定级别是否应输出（级别 >= 当前级别时才输出）
pub fn 是否启用(级别: 日志级别) -> bool {
    级别 >= 当前级别()
}

/// 生成一条日志行文本（不包含级别判断，供测试与复用）
pub fn 格式化日志行(级别: 日志级别, 模块名: &str, 消息内容: &str) -> String {
    format!(
        "[{}] [{}] [{}] {}",
        当前时间戳(),
        级别.显示文字(),
        模块名,
        消息内容
    )
}

/// 写入一条日志到 stderr（级别不足时直接返回）
pub fn 写入日志(级别: 日志级别, 模块名: &str, 消息内容: &str) {
    if !是否启用(级别) {
        return;
    }
    eprintln!("{}", 格式化日志行(级别, 模块名, 消息内容));
}

// ============================================================
// 时间戳（UTC，手写日历转换，避免引入 chrono 依赖）
// ============================================================

/// 返回当前 UTC 时间戳，格式 `YYYY-MM-DD HH:MM:SS`
fn 当前时间戳() -> String {
    // `标准库::时间模块` 整段英文透传：模块词 时间 会被误映射（chrono 词条 NaiveTime），
    // 历元 含下划线不可改写（否则拆成 UNIX + 错误词条）
    let 秒数 = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|间隔| 间隔.as_secs())
        .unwrap_or(0);
    let (年, 月, 日, 时, 分, 秒) = 分解时间(秒数);
    format!(
        "{:04}-{:02}-{:02} {:02}:{:02}:{:02}",
        年, 月, 日, 时, 分, 秒
    )
}

/// 将 Unix 秒数分解为 (年, 月, 日, 时, 分, 秒)（UTC）
/// 使用 Howard Hinnant 的 civil_from_days 算法，无第三方依赖
fn 分解时间(总秒数: u64) -> (i64, u32, u32, u32, u32, u32) {
    let 日数 = (总秒数 / 86_400) as i64;
    let 当日秒 = 总秒数 % 86_400;

    let 序日 = 日数 + 719_468;
    let 纪元 = 序日.div_euclid(146_097);
    let 纪元内日 = 序日 - 纪元 * 146_097;
    let 年偏移 = (纪元内日 - 纪元内日 / 1_460 + 纪元内日 / 36_524 - 纪元内日 / 146_096) / 365;
    let 年 = 年偏移 + 纪元 * 400;
    let 年内日 = 纪元内日 - (365 * 年偏移 + 年偏移 / 4 - 年偏移 / 100);
    let 月偏移 = (5 * 年内日 + 2) / 153;
    let 日 = (年内日 - (153 * 月偏移 + 2) / 5 + 1) as u32;
    let 月 = (月偏移 + if 月偏移 < 10 { 3 } else { -9 }) as u32;
    let 年 = if 月 <= 2 { 年 + 1 } else { 年 };

    (
        年,
        月,
        日,
        (当日秒 / 3600) as u32,
        ((当日秒 % 3600) / 60) as u32,
        (当日秒 % 60) as u32,
    )
}

