#[cfg(test)]
mod 单元测试 {
    use super::*;

    #[test]
    fn 级别解析() {
        assert_eq!(日志级别::解析环境值("debug"), Some(日志级别::调试级别));
        assert_eq!(日志级别::解析环境值("INFO"), Some(日志级别::信息级别));
        assert_eq!(日志级别::解析环境值("warn"), Some(日志级别::警告级别));
        assert_eq!(日志级别::解析环境值("warning"), Some(日志级别::警告级别));
        assert_eq!(日志级别::解析环境值("error"), Some(日志级别::错误级别));
        assert_eq!(日志级别::解析环境值("verbose"), None);
        assert_eq!(日志级别::解析环境值(""), None);
    }

    #[test]
    fn 默认级别为警告() {
        // 默认级别：警告（无 RZ_LOG 时静默但保留关键输出）
        // 注意：此测试依赖全局状态，可能受其他测试影响
        let _ = 当前级别();
    }

    #[test]
    fn 是否启用按级别过滤() {
        设置日志级别(日志级别::警告级别);
        assert!(!是否启用(日志级别::调试级别));
        assert!(!是否启用(日志级别::信息级别));
        assert!(是否启用(日志级别::警告级别));
        assert!(是否启用(日志级别::错误级别));
    }

    #[test]
    fn 分解时间纪元起点() {
        assert_eq!(分解时间(0), (1970, 1, 1, 0, 0, 0));
    }

    #[test]
    fn 分解时间已知日期() {
        // 2026-01-01T00:00:00Z 与 2026-08-13T00:00:00Z 的 Unix 秒
        assert_eq!(分解时间(1_767_225_600), (2026, 1, 1, 0, 0, 0));
        assert_eq!(分解时间(1_786_579_200), (2026, 8, 13, 0, 0, 0));
    }

    #[test]
    fn 分解时间含时分秒() {
        // 1970-01-01T12:34:56Z = 45296 秒
        assert_eq!(分解时间(45_296), (1970, 1, 1, 12, 34, 56));
        // 闰年 2024-02-29（2024-01-01 = 1704067200，+59 天）
        assert_eq!(
            分解时间(1_704_067_200 + 59 * 86_400),
            (2024, 2, 29, 0, 0, 0)
        );
    }

    #[test]
    fn 日志行格式() {
        let 文本行 = 格式化日志行(日志级别::信息级别, "test_module", "test message 42");
        // 格式：[YYYY-MM-DD HH:MM:SS] [信息] [test_module] test message 42
        // 注：变量不可命名为 行（词条 行→line），改用复合名 文本行
        assert!(文本行.starts_with('['));
        assert!(文本行.contains("] [信息] [test_module] test message 42"));
        // 时间戳年份段
        let 年段 = &文本行[1..5];
        assert!(年段.chars().all(|字符位| 字符位.is_ascii_digit()));
        assert!(文本行.contains("-"));
    }

    #[test]
    fn 低于级别不输出() {
        // 级别设为错误时，信息级写入不应 崩溃（被过滤，无输出）
        设置日志级别(日志级别::错误级别);
        写入日志(日志级别::信息级别, "test_module", "不应输出");
        信息日志!("test_module", "宏调用不应 panic {}", 1);
        调试日志!("test_module", "调试消息");
        assert!(是否启用(日志级别::错误级别));
    }

    #[test]
    fn 宏在启用级别可用() {
        设置日志级别(日志级别::调试级别);
        调试日志!("test_module", "调试 {}", "内容");
        信息日志!("test_module", "信息 {}", 42);
        警告日志!("test_module", "警告");
        错误日志!("test_module", "错误");
    }

    #[test]
    fn 程序化设置不被初始化覆盖() {
        // 程序化设置后，初始化()（读 RZ_LOG）不得覆盖——契约：程序化优先级更高
        设置日志级别(日志级别::错误级别);
        初始化();
        assert_eq!(当前级别(), 日志级别::错误级别);
    }
}
