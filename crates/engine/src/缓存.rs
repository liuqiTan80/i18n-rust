    /// 批量转译：N 次插入只在 flush 时写盘一次，且全部落盘
    ///
    /// 回归：此前每次 插入 都会把整个缓存序列化写盘（N 文件 → N 次全量写，
    /// 且发生在调用方持锁期间），是批量转译的主要 I/O 开销来源。
    #[test]
    fn 持久化批量写盘直到刷盘() {
        let 目录 = tempfile::tempdir().expect("创建临时目录失败");
        let 磁盘路径 = 目录.path().join("transpile.json");
        let 指纹 = 样本指纹();
        let mut 缓存 = 转译缓存::启用持久化(&磁盘路径);
        for 名 in ["甲", "乙", "丙", "丁"] {
            缓存.写入缓存(&format!("内容{名}"), 指纹, 样本产物(名));
            assert!(!磁盘路径.exists(), "flush 前不应有任何写盘");
        }
        assert_eq!(缓存.条目数目(), 4);
        缓存.刷盘();
        let 重载 = 转译缓存::启用持久化(&磁盘路径);
        assert_eq!(重载.条目数目(), 4, "一次 flush 应写入全部累积条目");
        // 幂等：无新变更时再 flush 不产生写盘（文件 mtime 不变）
        let 修改前 = std::fs::metadata(&磁盘路径)
            .and_then(|标记项| 标记项.modified())
            .ok();
        缓存.刷盘();
        let 修改后 = std::fs::metadata(&磁盘路径)
            .and_then(|标记项| 标记项.modified())
            .ok();
        assert_eq!(修改前, 修改后, "无变更时 flush 应为空操作");
    }
