/// 源映射条目：输入文本中一个被替换的标识符 token
///
/// 记录输入侧信息（字节偏移、长度）与翻译前后文本；
/// 不提供目标偏移——完整管线后续的模块路径替换/别名替换会改变输出偏移，
/// 输入侧信息始终保持精确。
/// 语义按使用场景分两级：
/// - 词法阶段 `源映射`：偏移为母语源坐标，replacement 为词法阶段文本；
/// - 全管线 `管线映射`：偏移为母语源坐标，replacement 为**最终输出文本**；
/// - 各中间阶段 `_with_map` 的 edits：偏移为该阶段输入文本坐标。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct 源映射条目 {
    /// 源文件中的字节偏移（token 起点）
    pub 源偏移: usize,
    /// token 字节长度
    pub 字节长度: usize,
    /// 源 token 文本（如 `函数`）
    pub 原文: String,
    /// 翻译后文本（如 `fn`）
    pub 替换文本: String,
}

impl 源映射条目 {
    pub fn 新建条目(
        源偏移: usize, 字节长度: usize, 原文: &str, 替换文本: &str
    ) -> Self {
        Self {
            源偏移,
            字节长度,
            原文: 原文.to_string(),
            替换文本: 替换文本.to_string(),
        }
    }
}

/// 翻译产物：翻译后的代码、词法阶段源映射与全管线编辑地图
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct 转译产出 {
    /// 翻译后的代码文本
    pub 产出: String,
    /// 词法阶段源映射（向后兼容：仅含词法阶段的替换，replacement 为词法阶段文本）
    pub 源映射: Vec<源映射条目>,
    /// 全管线编辑地图：以母语源偏移升序记录，replacement 为**最终输出文本**
    ///（宏调用自动补充的 `!` 已计入 replacement）。
    /// 列映射等消费方只需回放此表，无需复刻任何转译规则。
    pub 管线映射: Vec<源映射条目>,
}

impl 转译产出 {
    /// 仅创建输出（无源映射）
    pub fn 新建产出(产出: String) -> Self {
        Self {
            产出,
            源映射: Vec::new(),
            管线映射: Vec::new(),
        }
    }

    /// 创建输出并附带词法阶段源映射
    pub fn 附带源映射(产出: String, 源映射: Vec<源映射条目>) -> Self {
        Self {
            产出,
            源映射,
            管线映射: Vec::new(),
        }
    }

    /// 创建输出并附带词法阶段源映射与全管线编辑地图
    pub fn 附带全映射(
        产出: String,
        源映射: Vec<源映射条目>,
        管线映射: Vec<源映射条目>,
    ) -> Self {
        Self {
            产出,
            源映射,
            管线映射,
        }
    }
}

/// 缓存条目：内容哈希 → 条目
#[derive(Debug, Clone)]
struct 缓存条目 {
    /// 源内容字节长度（哈希冲突时的廉价校验）
    内容长度: usize,
    /// 翻译语境指纹（语言包映射内容变化时指纹变化，缓存自动失效）
    语境指纹: u64,
    /// 缓存的翻译产物
    产物: 转译产出,
}

/// 基于内容哈希的 LRU 翻译缓存
///
/// - 键：内容 FNV-1a 64 位哈希（附长度校验，降低冲突风险）
/// - 值：翻译产物（输出 + 源映射）
/// - 语境指纹：关键字/模块路径/标识符别名映射内容的哈希，
///   语言包更新后旧缓存自动失效，保证翻译结果与映射一致
/// - 淘汰策略：LRU（最近最少使用），容量可配置
///
/// 统计计数用 [`原子u64`]，类型满足 `Send + Sync`，
/// 可置于 `Mutex`/`RwLock` 后在多线程间共享（如并行转译项目文件）。
pub struct 转译缓存 {
    条目表: HashMap<u64, 缓存条目>,
    /// LRU 顺序：队首最旧、队尾最新；每个条目附带代际计数器，
    /// `标记命中` 递增代际并在队尾添加新条目，旧代际条目在淘汰时惰性跳过
    访问队列: VecDeque<(u64, u64)>,
    /// 每个哈希的当前代际：与队列条目的代际匹配时为有效条目
    代际表: HashMap<u64, u64>,
    容量: usize,
    命中计数: AtomicU64,
    未命中计数: AtomicU64,
    /// 磁盘持久化路径：有值 时由 [`转译缓存::flush`] 原子写盘
    ///（跨进程复用：CLI 短命进程把上次运行的翻译结果留给下次）
    持久化路径: Option<PathBuf>,
    /// 待写盘标记：变更后置位，[`转译缓存::flush`] 成功写盘后清除。
    ///
    /// 不每次变更都写盘的原因：`save` 会把**整个**缓存序列化为 JSON，
    /// 批量转译 N 个文件（各自 miss 后插入）会产生 N 次全量写，
    /// 且这些写发生在调用方持有缓存的临界区内，把并行转译串行化。
    /// 改为累积变更、批量一次写盘（进程退出由 `Drop` 兜底，不丢数据）。
    待写盘: bool,
}

/// 退出兜底：保证累积的未写盘变更不丢失（正常路径无需显式 `flush`）
impl Drop for 转译缓存 {
    fn drop(&mut self) {
        self.刷盘();
    }
}

/// 磁盘持久化文件格式（版本不匹配/解析失败时静默丢弃，回退内存缓存）
#[derive(Serialize, Deserialize)]
struct 持久化缓存文件 {
    /// 格式版本：结构变更时递增，旧版本文件直接丢弃
    格式版本: u32,
    /// LRU 顺序（旧→新）；加载时按序重建代际队列
    条目列表: Vec<持久化条目>,
}

/// 磁盘上的单个缓存条目（结构与内存条目对应）
#[derive(Serialize, Deserialize)]
struct 持久化条目 {
    哈希值: u64,
    内容长度: usize,
    语境指纹: u64,
    产物: 转译产出,
}

/// 当前持久化格式版本
const 持久化格式版本: u32 = 1;

/// 持久化缓存的默认容量（磁盘缓存面向多项目，比内存默认稍大）
const 持久化容量: usize = 512;

impl 转译缓存 {
    /// 新建缓存（容量至少为 1）
    pub fn 新建缓存(容量: usize) -> Self {
        Self {
            条目表: HashMap::new(),
            访问队列: VecDeque::new(),
            代际表: HashMap::new(),
            容量: 容量.max(1),
            命中计数: AtomicU64::new(0),
            未命中计数: AtomicU64::new(0),
            持久化路径: None,
            待写盘: false,
        }
    }

    /// 默认容量：256 个文件条目
    pub fn 默认容量新建() -> Self {
        Self::新建缓存(256)
    }

    /// 带磁盘持久化的缓存：从 `路径模块` 加载既有条目（尽力而为：文件不存在、
    /// 版本不匹配、JSON 损坏时静默回退为空缓存），此后变更累积、由
    /// [`自身::flush`] 批量写盘（进程退出由 `Drop` 兜底）。
    ///
    /// 跨进程增量复用场景（如 CLI 每次运行都是新进程）：上次运行转译过的
    /// 文件内容未变时直接命中，省去整条转译管线（Unicode/全角/lint 检查 + 词法）。
    pub fn 启用持久化(磁盘路径: &Path) -> Self {
        let mut 缓存 = Self::新建缓存(持久化容量);
        if let Ok(字节串) = std::fs::read(磁盘路径)
            && let Ok(磁盘文件) = serde_json::from_slice::<持久化缓存文件>(&字节串)
        {
            if 磁盘文件.格式版本 == 持久化格式版本 {
                缓存.重建自磁盘(磁盘文件.条目列表);
            } else {
                // 版本不匹配或结构损坏：丢弃旧文件（下次插入时重建）
                crate::警告日志!(
                    "translation_cache",
                    "{}（{}）",
                    crate::语言::查句("log_cache_disk_discard"),
                    磁盘路径.display()
                );
            }
        }
        // 文件不存在：首次使用，属正常路径，保持空缓存
        缓存.持久化路径 = Some(磁盘路径.to_path_buf());
        缓存
    }

    /// 默认位置的持久化缓存：`~/.rz/cache/transpile-v1.json`
    ///（与工具链/语言包同根，见 [`包::工具链::安装根目录`]）
    pub fn 持久默认项() -> Self {
        let 磁盘路径 = crate::工具链::安装根目录()
            .join("cache")
            .join("transpile-v1.json");
        Self::启用持久化(&磁盘路径)
    }

    /// 显式写盘（幂等；无持久化路径时为空操作）
    pub fn 存盘(&self, 磁盘路径: &Path) -> std::io::Result<()> {
        let 磁盘文件 = 持久化缓存文件 {
            格式版本: 持久化格式版本,
            条目列表: self.导出条目(),
        };
        let 字节串 = serde_json::to_vec(&磁盘文件)?;
        // 父目录可能不存在（首次运行 ~/.rz/cache/ 未创建）：先建目录再写
        if let Some(上级目录) = 磁盘路径.parent() {
            std::fs::create_dir_all(上级目录)?;
        }
        // 原子写：临时文件 + 重命名，避免进程中断留下半截 JSON
        let 临时 = 磁盘路径.with_extension("json.tmp");
        std::fs::write(&临时, &字节串)?;
        std::fs::rename(&临时, 磁盘路径)?;
        Ok(())
    }

    /// 批量写盘：有待写变更且绑定了持久化路径时写盘一次（幂等，无变更时空操作）。
    ///
    /// 批量转译场景应在全部文件处理完后调用一次（而非每个文件一次）：
    /// [`自身::save`] 会序列化整个缓存，逐次写盘会把并行转译串行化。
    /// 进程退出时由 `Drop` 兜底调用，正常路径无需显式调用。
    pub fn 刷盘(&mut self) {
        if !self.待写盘 {
            return;
        }
        let Some(磁盘路径) = self.持久化路径.clone() else {
            // 无持久化路径：变更无需落盘，标记清零避免无谓重试
            self.待写盘 = false;
            return;
        };
        match self.存盘(&磁盘路径) {
            Ok(()) => self.待写盘 = false,
            // 写失败：保留 待写盘 以便后续（含 Drop）重试；缓存丢失可接受，不阻断转译
            Err(错误值) => crate::警告日志!(
                "translation_cache",
                "{}（{}）",
                crate::语言::查句("log_cache_disk_save_failed"),
                错误值
            ),
        }
    }

    /// 从磁盘条目重建内存 LRU 结构（条目按旧→新顺序导入，代际队列保持一致）
    fn 重建自磁盘(&mut self, 磁盘条目: Vec<持久化条目>) {
        for 条目项 in 磁盘条目 {
            let 哈希值 = 条目项.哈希值;
            let 代际 = self.代际表.entry(哈希值).or_insert(0);
            self.访问队列.push_back((哈希值, *代际));
            self.条目表.insert(
                哈希值,
                缓存条目 {
                    内容长度: 条目项.内容长度,
                    语境指纹: 条目项.语境指纹,
                    产物: 条目项.产物,
                },
            );
        }
        crate::信息日志!(
            "translation_cache",
            "{}",
            crate::语言::查译("log_cache_disk_loaded", &[&self.条目表.len().to_string()])
        );
    }

    /// 按 LRU 顺序（旧→新）导出全部有效条目
    fn 导出条目(&self) -> Vec<持久化条目> {
        let mut 列表 = Vec::with_capacity(self.条目表.len());
        for (哈希值, 代际) in &self.访问队列 {
            if self.代际表.get(哈希值) != Some(代际) {
                continue; // 过时代际条目：惰性跳过
            }
            if let Some(条目项) = self.条目表.get(哈希值) {
                列表.push(持久化条目 {
                    哈希值: *哈希值,
                    内容长度: 条目项.内容长度,
                    语境指纹: 条目项.语境指纹,
                    产物: 条目项.产物.clone(),
                });
            }
        }
        列表
    }

    /// FNV-1a 64 位哈希（无第三方依赖，速度快，适合缓存键）
    pub fn 计算内容哈希(内容: &str) -> u64 {
        let mut 哈希值 = 0xcbf29ce484222325u64;
        for 字节值 in 内容.as_bytes() {
            哈希值 ^= *字节值 as u64;
            哈希值 = 哈希值.wrapping_mul(0x100000001b3);
        }
        哈希值
    }

    /// 生成翻译语境指纹：任一映射表内容变化或引擎源码变化时指纹变化
    ///
    /// 基于排序后的键值对拼接哈希，与映射表的插入顺序无关。
    ///
    /// 四张表全部参与：关键字、模块路径、别名、派生特征。
    /// 派生特征表由 `映射管理器` 从「派生特征」节单独存放（不并入
    /// 关键词映射表，避免与方法名别名冲突），若漏算会导致只改派生表时
    /// 指纹不变、缓存返回旧转译产物。
    /// 另混入引擎源码指纹（build.rs 对 src/ 全量生成）：缓存不仅须跟随
    /// 语言包映射变化，也须跟随转译算法变化——否则升级 rzc 后（算法修复/
    /// 调整），源文件未变时旧缓存仍命中、修复不生效（真实事故：别名替换
    /// 细则修复后，旧转译产物继续被复用）。
    pub fn 生成语境指纹(
        关键字表: &HashMap<String, String>,
        模块路径表: &HashMap<String, String>,
        别名表: &HashMap<String, String>,
        派生表: &HashMap<String, String>,
    ) -> u64 {
        let mut 配对: Vec<String> = Vec::new();
        // 引擎源码指纹：转译算法自身的身份，算法代码变化即失效全部缓存
        配对.push(format!(
            "engine-source:{:#x}",
            crate::语言::ENGINE_SOURCE_FINGERPRINT
        ));
        for 映射表 in [关键字表, 模块路径表, 别名表, 派生表] {
            for (键名, 值项) in 映射表 {
                // 长度前缀 + NUL 定界：键/值中出现任意字符（含 `=`、`\0`）
                // 都不会产生歧义（`"a=b"/"c"` 与 `"a"/"b=c"` 若用 `=`
                // 拼接会生成相同指纹，缓存语境误判为未变化）
                配对.push(format!("{}:{}\0{}", 键名.len(), 键名, 值项));
            }
        }
        配对.sort();
        Self::计算内容哈希(&配对.join("\n"))
    }

    /// 组合语言包语境指纹与项目上下文指纹为最终缓存指纹
    ///
    /// 不用异或：异或满足交换律（`(测试甲, 测试乙)` 与 `(测试乙, 测试甲)` 不可区分），且
    /// `无` 与「项目指纹恰为 0」的组合结果相同，会把「无项目上下文」与
    /// 「项目上下文指纹为 0」混为一谈而错误复用缓存。此处对 `无`/`有值`
    /// 使用显式标签，并用无歧义定界拼接后走稳定哈希（FNV-1a，跨进程一致，
    /// 与 [`自身::生成语境指纹`] 同一算法，便于磁盘缓存比对）。
    pub fn 合并语境指纹(管理器指纹: u64, 项目指纹: Option<u64>) -> u64 {
        let 项目段 = match 项目指纹 {
            Some(指纹值) => format!("project:{指纹值:#x}"),
            None => "project:none".to_string(),
        };
        Self::计算内容哈希(&format!("{管理器指纹:#x}\n{项目段}"))
    }

    /// 查询缓存（计数命中/未命中；不更新 LRU 顺序）
    ///
    /// 命中条件：内容哈希一致、内容长度一致、语境指纹一致。
    pub fn 检索(&self, 内容: &str, 语境指纹: u64) -> Option<&转译产出> {
        let 哈希值 = Self::计算内容哈希(内容);
        match self.条目表.get(&哈希值) {
            Some(条目项) if 条目项.内容长度 == 内容.len() && 条目项.语境指纹 == 语境指纹 =>
            {
                self.命中计数.fetch_add(1, Ordering::Relaxed);
                Some(&条目项.产物)
            }
            _ => {
                self.未命中计数.fetch_add(1, Ordering::Relaxed);
                None
            }
        }
    }

    /// 插入缓存条目（同哈希存在时覆盖并视为最近使用；超容量淘汰最旧条目）
    pub fn 写入缓存(&mut self, 内容: &str, 语境指纹: u64, 产物: 转译产出) {
        let 哈希值 = Self::计算内容哈希(内容);
        self.插入预计算(哈希值, 内容.len(), 语境指纹, 产物);
    }

    /// 获取或翻译：命中则直接返回缓存产物，未命中则执行翻译闭包并写入缓存
    ///
    /// 翻译闭包返回 `IO结果`，失败时错误透传、不写入缓存。
    pub fn 检索或转译<闭包类型>(
        &mut self,
        内容: &str,
        语境指纹: u64,
        转译闭包: 闭包类型,
    ) -> Result<转译产出, 转译错误>
    where
        闭包类型: FnOnce() -> Result<转译产出, 转译错误>,
    {
        // 预计算哈希一次（旧实现 miss 路径计算两次）
        let 哈希值 = Self::计算内容哈希(内容);
        // 内联查询逻辑，避免 `检索()` 重复计算哈希
        let 缓存命中 = match self.条目表.get(&哈希值) {
            Some(条目项) if 条目项.内容长度 == 内容.len() && 条目项.语境指纹 == 语境指纹 =>
            {
                self.命中计数.fetch_add(1, Ordering::Relaxed);
                Some(条目项.产物.clone())
            }
            _ => {
                self.未命中计数.fetch_add(1, Ordering::Relaxed);
                None
            }
        };
        if let Some(产物) = 缓存命中 {
            crate::信息日志!(
                "translation_cache",
                "{}",
                crate::语言::查译(
                    "log_cache_hit",
                    &[&内容.len().to_string(), &语境指纹.to_string()]
                )
            );
            self.标记命中(哈希值);
            return Ok(产物);
        }
        crate::信息日志!(
            "translation_cache",
            "{}",
            crate::语言::查译(
                "log_cache_miss",
                &[&内容.len().to_string(), &语境指纹.to_string()]
            )
        );
        let 产物 = 转译闭包()?;
        self.插入预计算(哈希值, 内容.len(), 语境指纹, 产物.clone());
        Ok(产物)
    }

    /// 清空全部条目（统计计数保留；绑定持久化路径时同步清空磁盘文件）
    pub fn 清空记录(&mut self) {
        self.条目表.clear();
        self.访问队列.clear();
        self.代际表.clear();
        // 清空是显式破坏性操作，立即落盘（不等批量写盘）
        self.待写盘 = true;
        self.刷盘();
    }

    /// 当前缓存条目数
    pub fn 条目数目(&self) -> usize {
        self.条目表.len()
    }

    /// 缓存容量值
    pub fn 容量数值(&self) -> usize {
        self.容量
    }

    /// 累计命中次数
    pub fn 命中数目(&self) -> u64 {
        self.命中计数.load(Ordering::Relaxed)
    }

    /// 累计未命中次数
    pub fn 缺失数目(&self) -> u64 {
        self.未命中计数.load(Ordering::Relaxed)
    }

    /// 命中率（0.0 ~ 1.0；无查询记录时为 0.0）
    pub fn 命中率数值(&self) -> f64 {
        let 命中读数 = self.命中计数.load(Ordering::Relaxed);
        let 总数 = 命中读数 + self.未命中计数.load(Ordering::Relaxed);
        if 总数 == 0 {
            0.0
        } else {
            命中读数 as f64 / 总数 as f64
        }
    }

    // ===== 内部实现 =====

    fn 插入预计算(
        &mut self, 哈希值: u64, 内容长度: usize, 语境指纹: u64, 产物: 转译产出
    ) {
        if let Some(条目项) = self.条目表.get_mut(&哈希值) {
            // 同内容（含语境变化）覆盖，保持 LRU 位置为最新
            条目项.内容长度 = 内容长度;
            条目项.语境指纹 = 语境指纹;
            条目项.产物 = 产物;
            self.标记命中(哈希值);
            // 覆盖也是内容变更：置脏（此前该路径不回写磁盘，磁盘副本会残留旧产物）
            self.待写盘 = true;
            return;
        }
        self.条目表.insert(
            哈希值,
            缓存条目 {
                内容长度,
                语境指纹,
                产物,
            },
        );
        let 代际 = self.代际表.entry(哈希值).or_insert(0);
        self.访问队列.push_back((哈希值, *代际));
        // 淘汰最旧有效条目（跳过代际不匹配的过时条目）
        while self.条目表.len() > self.容量 {
            while let Some((队首哈希, 队首代际)) = self.访问队列.pop_front() {
                if self.代际表.get(&队首哈希) == Some(&队首代际) {
                    // 代际匹配：这是有效条目，执行淘汰
                    self.代际表.remove(&队首哈希);
                    self.条目表.remove(&队首哈希);
                    crate::调试日志!(
                        "translation_cache",
                        "{}",
                        crate::语言::查译("log_cache_evict", &[&队首哈希.to_string()])
                    );
                    break;
                }
                // 代际不匹配：过时条目，惰性跳过
            }
        }
        // 标记待写盘：实际写盘由 `刷盘()` 批量执行（详见 `待写盘` 字段说明）
        self.待写盘 = true;
    }

    /// O(1) LRU 命中更新：递增代际并在队尾添加新条目，
    /// 旧代际条目留在队列中，淘汰时因代际不匹配被惰性跳过；
    /// 队列膨胀超过阈值（容量 4 倍，最少 64）时压缩，
    /// 防止长期运行（如 LSP 会话）下过时条目无限累积
    fn 标记命中(&mut self, 哈希值: u64) {
        let 代际 = self.代际表.entry(哈希值).or_insert(0);
        *代际 += 1;
        self.访问队列.push_back((哈希值, *代际));
        if self.访问队列.len() > self.容量.saturating_mul(4).max(64) {
            self.压缩队列();
        }
    }

    /// 压缩 LRU 队列：从队尾（最新）向队首扫描，每个哈希只保留
    /// 最后一次访问的有效条目，其余过时条目全部移除
    ///（压缩后队列长度 ≤ 缓存条目数 ≤ 容量，淘汰逻辑照常工作）
    fn 压缩队列(&mut self) {
        let mut 已见 = HashSet::new();
        let mut 压缩: VecDeque<(u64, u64)> = VecDeque::with_capacity(self.条目表.len());
        for &(哈希值, 代际) in self.访问队列.iter().rev() {
            if 已见.insert(哈希值) && self.代际表.get(&哈希值) == Some(&代际) {
                压缩.push_front((哈希值, 代际));
            }
        }
        self.访问队列 = 压缩;
    }
}

