//! 全角标点检测与修复模块【zh 自举试点·全中文化】
//! 本文件是源真相：由已发布的 rzc 转译为 全角标点.rs 后交 cargo 编译。
//! 再生成方式见 tools/zh-selfhost/regen.sh；请勿手改同目录下的 全角标点.rs。
//!
//! 中文（及日/韩等）输入法下，用户常以全角标点书写代码（如 `打印行！（"你好"）；`），
//! 这些字符在 Rust 语法中非法或会形成错误标识符，是初学者最常见的编译错误来源。
//! 本模块在词法处理前扫描源码，仅报告代码位置（字符串字面量与注释内的全角标点
//! 合法，不报告）的全角标点：
//! - 有明确半角对应（，；：（）！？等）→ 提示对应字符，`rzc check --fix` 可自动转换
//! - 无一对一映射的中文标点（、 与全角空格等）→ 仅提示，需人工修改
//!
//! 注：`"fullwidth_*"` 系列字符串是与 11 个语言包 ui.toml 及 LSP 诊断码
//! 对齐的协议键（数据，非代码），按约定保持英文，不得本地化。

/// 全角标点 → 半角映射表（可自动修复的字符）
///
/// 覆盖中文输入法全角模式下可输入的所有常见标点；
/// 字符串/注释内的全角标点是合法内容，由调用方保证仅扫描代码位置。
const 可修复映射: &[(char, char)] = &[
    ('，', ','),
    ('。', '.'),
    ('；', ';'),
    ('：', ':'),
    ('！', '!'),
    ('？', '?'),
    ('（', '('),
    ('）', ')'),
    ('【', '['),
    ('】', ']'),
    ('｛', '{'),
    ('｝', '}'),
    ('「', '['),
    ('」', ']'),
    ('『', '['),
    ('』', ']'),
    ('〔', '('),
    ('〕', ')'),
    ('“', '"'),
    ('”', '"'),
    ('‘', '\''),
    ('’', '\''),
    ('～', '~'),
    ('＠', '@'),
    ('＃', '#'),
    ('％', '%'),
    ('＆', '&'),
    ('＊', '*'),
    ('＋', '+'),
    ('－', '-'),
    ('＝', '='),
    ('／', '/'),
    ('＼', '\\'),
    ('｜', '|'),
    ('＜', '<'),
    ('＞', '>'),
    ('＿', '_'),
    ('＄', '$'),
    ('＾', '^'),
];

/// 无一对一映射、仅提示不可自动修复的字符
const 仅提示字符: &[char] = &['、', '　', '·'];

/// 单个全角标点警告：位置（1 起行/列）+ 字符 + 建议的半角字符
#[derive(Debug, Clone, PartialEq)]
pub struct 全角警告 {
    /// 行号（从 1 开始）
    pub 行号: usize,
    /// 列号（从 1 开始，按字符计数）
    pub 列号: usize,
    /// 全角字符
    pub 全角字: char,
    /// 建议的半角字符；无 表示无对应（仅提示）
    pub 替换建议: Option<char>,
}

impl 全角警告 {
    /// 格式化为单行警告文本，模板随当前语言变化
    /// 示例（zh）：`第 1 行第 5 列：检测到全角标点「，」，应改为半角「,」`
    pub fn 格式化输出(&self) -> String {
        let 提示文本 = match self.替换建议 {
            Some(半角) => crate::语言::查译("fullwidth_to_half", &[&半角.to_string()]),
            None => crate::语言::查句("fullwidth_hint_only"),
        };
        crate::语言::查译(
            "fullwidth_warning_at",
            &[
                &self.行号.to_string(),
                &self.列号.to_string(),
                &self.全角字.to_string(),
                &提示文本,
            ],
        )
    }
}

/// 查找代码位置（非字符串/注释）的全角标点
///
/// 状态机跳过字符串字面量（含转义与原始字符串 r#""#）、字符字面量、
/// 行注释与块注释；其余位置出现的全角标点均报告。
/// 字符串/注释内的列号只保证大致正确（这些位置不产生警告）。
pub fn 查找全角标点(源码: &str) -> Vec<全角警告> {
    let 序列: Vec<char> = 源码.chars().collect();
    let mut 警告列表 = Vec::new();
    let mut 当前行 = 1usize;
    let mut 当前列 = 1usize;
    // 字面量状态：0 = 代码位置；1=双引号串 2=字符 3=原始串
    let mut 字面量状态: u8 = 0;
    let mut 原始井号数 = 0usize; // 原始字符串的 # 数量
    // 保存上一个非空白字符（用于识别 r#"..."/b"..." 前缀与注释 `//`）
    let mut 前实字 = '\0';
    let mut 下标 = 0usize;
    while 下标 < 序列.len() {
        let 当前字 = 序列[下标];
        if 当前字 == '\n' {
            当前行 += 1;
            当前列 = 1;
            前实字 = '\0';
            if 字面量状态 == 2 || 字面量状态 == 3 {
                // 防御：字符/原始串内出现未闭合引号时在行尾强制退出，
                // 避免状态污染后续行（编译器本就会报错，此处只为正确报告全角标点）
                字面量状态 = 0;
            }
            下标 += 1;
            continue;
        }
        match 字面量状态 {
            1 | 2 => {
                // 字符串/字符字面量：转义跳过下一字符，闭合引号退出
                if 当前字 == '\\' {
                    下标 += 2;
                    当前列 += 1;
                    continue;
                }
                let 闭引号 = if 字面量状态 == 1 { '"' } else { '\'' };
                if 当前字 == 闭引号 {
                    字面量状态 = 0;
                }
            }
            3 => {
                // 原始字符串 r#"..."#：遇 " 后跟等量 #（或行尾/EOF）退出
                if 当前字 == '"' {
                    let 井数 = 序列[下标 + 1..]
                        .iter()
                        .take_while(|字符值| **字符值 == '#')
                        .count();
                    if 井数 >= 原始井号数 {
                        字面量状态 = 0;
                        原始井号数 = 0;
                    }
                }
            }
            _ => match 当前字 {
                '"' => 字面量状态 = 1,
                '\'' => 字面量状态 = 2,
                // 行注释：吞到行尾（\n 留给主循环统一处理）
                '/' if 前实字 == '/' => {
                    当前列 -= 1; // 回退第一个 '/' 已计的列
                    while 下标 < 序列.len() && 序列[下标] != '\n' {
                        下标 += 1;
                        当前列 += 1;
                    }
                    前实字 = '\0';
                    continue;
                }
                // 块注释（不处理嵌套，够用）
                '*' if 前实字 == '/' => {
                    当前列 -= 1;
                    while 下标 < 序列.len() {
                        let 次字 = 序列[下标];
                        下标 += 1;
                        if 次字 == '\n' {
                            当前行 += 1;
                            当前列 = 1;
                        } else if 次字 == '*' && 下标 < 序列.len() && 序列[下标] == '/' {
                            下标 += 1;
                            当前列 += 2;
                            break;
                        } else {
                            当前列 += 1;
                        }
                    }
                    前实字 = '\0';
                    continue;
                }
                // 原始字符串前缀 r#"..."#（r 或 br 后跟 " 或 #）
                'r' | 'b' if 是否原始串前缀(前实字) => {
                    // 前瞻后续字符：连续 # 后遇 " 才进入原始串
                    let mut 前缀井数 = 0usize;
                    let mut 探测下标 = 下标 + 1;
                    while 探测下标 < 序列.len() && 序列[探测下标] == '#' {
                        前缀井数 += 1;
                        探测下标 += 1;
                    }
                    if 探测下标 < 序列.len() && 序列[探测下标] == '"' {
                        原始井号数 = 前缀井数;
                        字面量状态 = 3;
                        // 消费前缀字符（r + # 序列 + 引号）
                        下标 = 探测下标 + 1;
                        当前列 += 1 + 前缀井数 + 1;
                        continue;
                    }
                }
                字符值 if 可修复映射.iter().any(|(全角项, _)| *全角项 == 字符值) =>
                {
                    let 替换建议 = 可修复映射
                        .iter()
                        .find(|(全角项, _)| *全角项 == 字符值)
                        .map(|(_, 半角项)| *半角项);
                    警告列表.push(全角警告 {
                        行号: 当前行,
                        列号: 当前列,
                        全角字: 字符值,
                        替换建议,
                    });
                }
                字符值 if 仅提示字符.contains(&字符值) => {
                    警告列表.push(全角警告 {
                        行号: 当前行,
                        列号: 当前列,
                        全角字: 字符值,
                        替换建议: None,
                    });
                }
                _ => {}
            },
        }
        下标 += 1;
        当前列 += 1;
        if 当前字 != ' ' && 当前字 != '\t' && 字面量状态 == 0 {
            前实字 = 当前字;
        }
    }
    警告列表
}

/// 判断前一字符是否可作为原始字符串前缀（r#/br#：前一字为 行首/空白/运算符）
fn 是否原始串前缀(前字: char) -> bool {
    前字 == '\0' || 前字.is_whitespace() || "([{<,;:!?&|=+-*/%^".contains(前字)
}

/// 自动修复代码位置的全角标点，返回（修复后文本, 替换数量）
///
/// 仅替换 [`可修复映射`] 中的字符；顿号/全角空格等仅提示字符保持原样。
/// 字符串与注释内容不受影响。
pub fn 修复全角标点(源码: &str) -> (String, usize) {
    let 序列: Vec<char> = 源码.chars().collect();
    let mut 输出 = String::new();
    let mut 替换数 = 0usize;
    let mut 字面量状态: u8 = 0;
    let mut 原始井号数 = 0usize;
    let mut 前实字 = '\0';
    let mut 下标 = 0usize;
    while 下标 < 序列.len() {
        let 当前字 = 序列[下标];
        if 当前字 == '\n' {
            前实字 = '\0';
            if 字面量状态 == 2 || 字面量状态 == 3 {
                字面量状态 = 0;
            }
            输出.push(当前字);
            下标 += 1;
            continue;
        }
        match 字面量状态 {
            1 | 2 => {
                输出.push(当前字);
                if 当前字 == '\\' {
                    if let Some(下一位) = 序列.get(下标 + 1) {
                        输出.push(*下一位);
                    }
                    下标 += 2;
                    continue;
                }
                let 闭引号 = if 字面量状态 == 1 { '"' } else { '\'' };
                if 当前字 == 闭引号 {
                    字面量状态 = 0;
                }
            }
            3 => {
                输出.push(当前字);
                if 当前字 == '"' {
                    let 井数 = 序列[下标 + 1..]
                        .iter()
                        .take_while(|字符值| **字符值 == '#')
                        .count();
                    if 井数 >= 原始井号数 {
                        字面量状态 = 0;
                        原始井号数 = 0;
                    }
                }
            }
            _ => match 当前字 {
                '"' => {
                    字面量状态 = 1;
                    输出.push(当前字);
                }
                '\'' => {
                    字面量状态 = 2;
                    输出.push(当前字);
                }
                '/' if 前实字 == '/' => {
                    输出.push(当前字);
                    下标 += 1;
                    while 下标 < 序列.len() && 序列[下标] != '\n' {
                        输出.push(序列[下标]);
                        下标 += 1;
                    }
                    前实字 = '\0';
                    continue;
                }
                '*' if 前实字 == '/' => {
                    输出.push(当前字);
                    下标 += 1;
                    while 下标 < 序列.len() {
                        let 次字 = 序列[下标];
                        输出.push(次字);
                        下标 += 1;
                        if 次字 == '\n' {
                            break;
                        }
                        if 次字 == '*' && 下标 < 序列.len() && 序列[下标] == '/' {
                            输出.push('/');
                            下标 += 1;
                            break;
                        }
                    }
                    前实字 = '\0';
                    continue;
                }
                'r' | 'b' if 是否原始串前缀(前实字) => {
                    let mut 前缀井数 = 0usize;
                    let mut 探测下标 = 下标 + 1;
                    while 探测下标 < 序列.len() && 序列[探测下标] == '#' {
                        前缀井数 += 1;
                        探测下标 += 1;
                    }
                    if 探测下标 < 序列.len() && 序列[探测下标] == '"' {
                        原始井号数 = 前缀井数;
                        字面量状态 = 3;
                        输出.push(当前字);
                        for 前缀字 in &序列[下标 + 1..=探测下标] {
                            输出.push(*前缀字);
                        }
                        下标 = 探测下标 + 1;
                        continue;
                    }
                    输出.push(当前字);
                }
                字符值 => {
                    // 可修复映射 命中则改写为半角；未命中原样输出
                    // （单次查找，无需 任意() 守卫 + 解包 的双重遍历）
                    if let Some((_, 半角项)) =
                        可修复映射.iter().find(|(全角项, _)| *全角项 == 字符值)
                    {
                        输出.push(*半角项);
                        替换数 += 1;
                    } else {
                        输出.push(当前字);
                    }
                }
            },
        }
        下标 += 1;
        if 当前字 != ' ' && 当前字 != '\t' && 字面量状态 == 0 {
            前实字 = 当前字;
        }
    }
    (输出, 替换数)
}

#[cfg(test)]
mod 单元测试 {
    use super::*;

    #[test]
    fn 检测代码位置全角() {
        let 警告列表 = 查找全角标点("函数 主函数（）{\n    打印行！（\"你好\"）；\n}");
        let 字符序列: Vec<char> = 警告列表.iter().map(|警告项| 警告项.全角字).collect();
        assert_eq!(字符序列, vec!['（', '）', '！', '（', '）', '；']);
        assert_eq!(警告列表[0].行号, 1);
        assert_eq!(警告列表[0].列号, 7);
        assert_eq!(警告列表[0].替换建议, Some('('));
    }

    #[test]
    fn 忽略字符串与注释() {
        let 源码 = "打印行!(\"你好，世界！？\"); // 注释：这里随便，。！\n/* 块注释：（）； */\n让 文本 = \"括号（）内的不算\";";
        let 警告列表 = 查找全角标点(源码);
        assert!(
            警告列表.is_empty(),
            "字符串/注释内全角标点不应报告：{警告列表:?}"
        );
    }

    #[test]
    fn 忽略字符与原始串() {
        let 源码 = "让 字符 = '，';  // 字符字面量\n让 原始 = r#\"（全角）\"#;";
        let 警告列表 = 查找全角标点(源码);
        assert!(警告列表.is_empty(), "字符/原始字符串不应报告：{警告列表:?}");
    }

    #[test]
    fn 仅提示字符无建议() {
        let 警告列表 = 查找全角标点("让 顿号、= 1;");
        assert_eq!(警告列表.len(), 1);
        assert_eq!(警告列表[0].全角字, '、');
        assert_eq!(警告列表[0].替换建议, None);
    }

    #[test]
    fn 转义引号在串内() {
        let 源码 = "让 文本 = \"包含\\\"引号（全角）\";";
        let 警告列表 = 查找全角标点(源码);
        assert!(警告列表.is_empty(), "转义串不应报告：{警告列表:?}");
    }

    #[test]
    fn 修复仅动代码位置() {
        let 源码 = "函数 主函数（）{\n    打印行！（\"你好，世界\"）；\n}";
        let (成品, 替换数) = 修复全角标点(源码);
        assert_eq!(替换数, 6);
        assert_eq!(成品, "函数 主函数(){\n    打印行!(\"你好，世界\");\n}");
        // 字符串内的全角逗号保留
        assert!(成品.contains("你好，世界"));
    }

    #[test]
    fn 修复保留仅提示字符() {
        let (成品, 替换数) = 修复全角标点("让 甲、乙 = 1；");
        assert_eq!(替换数, 1, "只有全角分号被替换");
        assert_eq!(成品, "让 甲、乙 = 1;");
    }

    #[test]
    fn 修复不动原始字符串() {
        let 源码 = "让 原始 = r#\"（全角）\"#;\n打印行！(\"x\");";
        let (成品, 替换数) = 修复全角标点(源码);
        assert_eq!(替换数, 1);
        assert!(成品.contains("r#\"（全角）\"#"), "原始字符串应保留：{成品}");
    }
}
