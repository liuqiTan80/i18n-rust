//! 全角标点检测与修复模块
//! 中文（及日/韩等）输入法下，用户常以全角标点书写代码（如 `打印行！（"你好"）；`），
//! 这些字符在 Rust 语法中非法或会形成错误标识符，是初学者最常见的编译错误来源。
//! 本模块在词法处理前扫描源码，仅报告代码位置（字符串字面态与注释内的全角标点
//! 合法，不报告）的全角标点：
//! - 有明确半角对应（，；：（）！？等）→ 提示对应字符，`rzc check --fix` 可自动转换
//! - 无一对一映射的中文标点（、 与全角空格等）→ 仅提示，需人工修改

/// 全角标点 → 半角映射表（可自动修复的字符）
///
/// 覆盖中文输入法全角模式下可输入的所有常见标点；
/// 字符串/注释内的全角标点是合法内容，由调用方保证仅扫描代码位置。
const 可修复对表: &[(char, char)] = &[
    ('，', ','),
    ('。', '.'),
    ('；', ';'),
    ('：', ':'),
    ('！', '!'),
    ('？', '?'),
    ('（', '('),
    ('）', ')'),
    ('【', '['),
    ('】', ']'),
    ('｛', '{'),
    ('｝', '}'),
    ('「', '['),
    ('」', ']'),
    ('『', '['),
    ('』', ']'),
    ('〔', '('),
    ('〕', ')'),
    ('“', '"'),
    ('”', '"'),
    ('‘', '\''),
    ('’', '\''),
    ('～', '~'),
    ('＠', '@'),
    ('＃', '#'),
    ('％', '%'),
    ('＆', '&'),
    ('＊', '*'),
    ('＋', '+'),
    ('－', '-'),
    ('＝', '='),
    ('／', '/'),
    ('＼', '\\'),
    ('｜', '|'),
    ('＜', '<'),
    ('＞', '>'),
    ('＿', '_'),
    ('＄', '$'),
    ('＾', '^'),
];

/// 无一对一映射、仅提示不可自动修复的字符
const 仅提示表: &[char] = &['、', '　', '·'];

/// 单个全角标点警告：位置（1 起行/列）+ 字符 + 建议的半角字符
#[derive(Debug, Clone, PartialEq)]
pub struct 全角警告 {
    /// 行号（从 1 开始）
    pub 行号: usize,
    /// 列号（从 1 开始，按字符计数）
    pub 列序: usize,
    /// 全角字符
    pub 涉事字符: char,
    /// 建议的半角字符；无值 表示无对应（仅提示）
    pub 替代字符: Option<char>,
}

impl 全角警告 {
    /// 格式化为单行警告文本，模板随当前语言变化
    /// 示例（中文）：`第 1 行第 5 列：检测到全角标点「，」，应改为半角「,」`
    pub fn 展示行(&self) -> String {
        let 指引 = match self.替代字符 {
            Some(半角) => {
                crate::语言::取带参消息("fullwidth_to_half", &[&半角.to_string()])
            }
            None => crate::语言::取消息("fullwidth_hint_only"),
        };
        crate::语言::取带参消息(
            "fullwidth_warning_at",
            &[
                &self.行号.to_string(),
                &self.列序.to_string(),
                &self.涉事字符.to_string(),
                &指引,
            ],
        )
    }
}

/// 查找代码位置（非字符串/注释）的全角标点
///
/// 状态机跳过字符串字面态（含转义与原始字符串 r#""#）、字符字面态、
/// 行注释与块注释；其余位置出现的全角标点均报告。
/// 字符串/注释内的列号只保证大致正确（这些位置不产生警告）。
pub fn 检测全角标点(源码: &str) -> Vec<全角警告> {
    let 字符们: Vec<char> = 源码.chars().collect();
    检测全角标点字符(&字符们)
}

/// [`检测全角标点`] 的字符切片入口
///
/// 与教学检查各扫描器共用同一份字符切片（见转译管线内部）：
/// 一轮教学检查里全角扫描、易混词表检查都只看这份切片，不再各自展开源码。
pub fn 检测全角标点字符(字符切片: &[char]) -> Vec<全角警告> {
    let mut 警告们 = Vec::new();
    let mut 行号: usize = 1;
    let mut 列序: usize = 1;
    // 字面态：0 = 代码位置；1=双引号串 2=字符 3=原始串
    let mut 字面态: u8 = 0;
    let mut 原始井号数: usize = 0; // 原始字符串的 # 数量
    // 保存上一个非空白字符（用于识别 r#"..."/b"..." 前缀与注释 `//`）
    let mut 前普通 = '\0';
    let mut 游标: usize = 0;
    while 游标 < 字符切片.len() {
        let 码元 = 字符切片[游标];
        if 码元 == '\n' {
            行号 += 1;
            列序 = 1;
            前普通 = '\0';
            if 字面态 == 2 || 字面态 == 3 {
                // 防御：字符/原始串内出现未闭合引号时在行尾强制退出，
                // 避免状态污染后续行（编译器本就会报错，此处只为正确报告全角标点）
                字面态 = 0;
            }
            游标 += 1;
            continue;
        }
        match 字面态 {
            1 | 2 => {
                // 字符串/字符字面态：转义跳过下一字符，闭合引号退出
                if 码元 == '\\' {
                    游标 += 2;
                    列序 += 1;
                    continue;
                }
                let 闭合符 = if 字面态 == 1 { '"' } else { '\'' };
                if 码元 == 闭合符 {
                    字面态 = 0;
                }
            }
            3 => {
                // 原始字符串 r#"..."#：遇 " 后跟等量 #（或行尾/EOF）退出
                if 码元 == '"' {
                    let 井数 = 字符切片[游标 + 1..]
                        .iter()
                        .take_while(|元| **元 == '#')
                        .count();
                    if 井数 >= 原始井号数 {
                        字面态 = 0;
                        原始井号数 = 0;
                    }
                }
            }
            _ => match 码元 {
                '"' => 字面态 = 1,
                '\'' => 字面态 = 2,
                // 行注释：吞到行尾（\n 留给主循环统一处理）
                '/' if 前普通 == '/' => {
                    列序 -= 1; // 回退第一个 '/' 已计的列
                    while 游标 < 字符切片.len() && 字符切片[游标] != '\n' {
                        游标 += 1;
                        列序 += 1;
                    }
                    前普通 = '\0';
                    continue;
                }
                // 块注释（不处理嵌套，够用）
                '*' if 前普通 == '/' => {
                    列序 -= 1;
                    while 游标 < 字符切片.len() {
                        let 内元 = 字符切片[游标];
                        游标 += 1;
                        if 内元 == '\n' {
                            行号 += 1;
                            列序 = 1;
                        } else if 内元 == '*' && 游标 < 字符切片.len() && 字符切片[游标] == '/'
                        {
                            游标 += 1;
                            列序 += 2;
                            break;
                        } else {
                            列序 += 1;
                        }
                    }
                    前普通 = '\0';
                    continue;
                }
                // 原始字符串前缀（`r` 或字节前缀 `b` 起头，后跟 井号 或 引号）
                'r' | 'b' if 是原始前缀(前普通) => {
                    // 前瞻后续字符：连续 # 后遇 " 才进入原始串
                    let mut 前缀井数: usize = 0;
                    let mut 探 = 游标 + 1;
                    while 探 < 字符切片.len() && 字符切片[探] == '#' {
                        前缀井数 += 1;
                        探 += 1;
                    }
                    if 探 < 字符切片.len() && 字符切片[探] == '"' {
                        原始井号数 = 前缀井数;
                        字面态 = 3;
                        // 消费前缀字符（r + # 序列 + 引号）
                        游标 = 探 + 1;
                        列序 += 1 + 前缀井数 + 1;
                        continue;
                    }
                }
                可疑 if 可修复对表.iter().any(|配对| 配对.0 == 可疑) => {
                    let 替代 = 可修复对表
                        .iter()
                        .find(|配对| 配对.0 == 可疑)
                        .map(|配对| 配对.1);
                    警告们.push(全角警告 {
                        行号,
                        列序,
                        涉事字符: 可疑,
                        替代字符: 替代,
                    });
                }
                可疑 if 仅提示表.contains(&可疑) => {
                    警告们.push(全角警告 {
                        行号,
                        列序,
                        涉事字符: 可疑,
                        替代字符: None,
                    });
                }
                _ => {}
            },
        }
        游标 += 1;
        列序 += 1;
        if 码元 != ' ' && 码元 != '\t' && 字面态 == 0 {
            前普通 = 码元;
        }
    }
    警告们
}

/// 判断前一字符是否可作为原始字符串前缀（`r` 或 `b` 起头：前一字为 行首/空白/运算符）
fn 是原始前缀(前普通: char) -> bool {
    前普通 == '\0' || 前普通.is_whitespace() || "([{<,;:!?&|=+-*/%^".contains(前普通)
}

/// 自动修复代码位置的全角标点，返回（修复后文本, 替换数量）
///
/// 仅替换 [`可修复对表`] 中的字符；顿号/全角空格等仅提示字符保持原样。
/// 字符串与注释内容不受影响。
pub fn 修复全角标点(源码: &str) -> (String, usize) {
    let 字符们: Vec<char> = 源码.chars().collect();
    let mut 改写串 = String::with_capacity(源码.len());
    let mut 替换数 = 0;
    let mut 字面态: u8 = 0;
    let mut 原始井号数: usize = 0;
    let mut 前普通 = '\0';
    let mut 游标: usize = 0;
    while 游标 < 字符们.len() {
        let 码元 = 字符们[游标];
        if 码元 == '\n' {
            前普通 = '\0';
            if 字面态 == 2 || 字面态 == 3 {
                字面态 = 0;
            }
            改写串.push(码元);
            游标 += 1;
            continue;
        }
        match 字面态 {
            1 | 2 => {
                改写串.push(码元);
                if 码元 == '\\' {
                    if 游标 + 1 < 字符们.len() {
                        改写串.push(字符们[游标 + 1]);
                    }
                    游标 += 2;
                    continue;
                }
                let 闭合符 = if 字面态 == 1 { '"' } else { '\'' };
                if 码元 == 闭合符 {
                    字面态 = 0;
                }
            }
            3 => {
                改写串.push(码元);
                if 码元 == '"' {
                    let 井数 = 字符们[游标 + 1..]
                        .iter()
                        .take_while(|元| **元 == '#')
                        .count();
                    if 井数 >= 原始井号数 {
                        字面态 = 0;
                        原始井号数 = 0;
                    }
                }
            }
            _ => match 码元 {
                '"' => {
                    字面态 = 1;
                    改写串.push(码元);
                }
                '\'' => {
                    字面态 = 2;
                    改写串.push(码元);
                }
                '/' if 前普通 == '/' => {
                    改写串.push(码元);
                    游标 += 1;
                    while 游标 < 字符们.len() && 字符们[游标] != '\n' {
                        改写串.push(字符们[游标]);
                        游标 += 1;
                    }
                    前普通 = '\0';
                    continue;
                }
                '*' if 前普通 == '/' => {
                    改写串.push(码元);
                    游标 += 1;
                    while 游标 < 字符们.len() {
                        let 内元 = 字符们[游标];
                        改写串.push(内元);
                        游标 += 1;
                        if 内元 == '\n' {
                            break;
                        }
                        if 内元 == '*' && 游标 < 字符们.len() && 字符们[游标] == '/' {
                            改写串.push('/');
                            游标 += 1;
                            break;
                        }
                    }
                    前普通 = '\0';
                    continue;
                }
                'r' | 'b' if 是原始前缀(前普通) => {
                    let mut 前缀井数: usize = 0;
                    let mut 探 = 游标 + 1;
                    while 探 < 字符们.len() && 字符们[探] == '#' {
                        前缀井数 += 1;
                        探 += 1;
                    }
                    if 探 < 字符们.len() && 字符们[探] == '"' {
                        原始井号数 = 前缀井数;
                        字面态 = 3;
                        改写串.push(码元);
                        for 元 in &字符们[游标 + 1..=探] {
                            改写串.push(*元);
                        }
                        游标 = 探 + 1;
                        continue;
                    }
                    改写串.push(码元);
                }
                可疑 => {
                    // 可修复对表 命中则改写为半角；未命中原样输出
                    // （单次查找，无需先 任意() 判定再取值的两次遍历）
                    if let Some((_, 半角)) = 可修复对表.iter().find(|配对| 配对.0 == 可疑)
                    {
                        改写串.push(*半角);
                        替换数 += 1;
                    } else {
                        改写串.push(码元);
                    }
                }
            },
        }
        游标 += 1;
        if 码元 != ' ' && 码元 != '\t' && 字面态 == 0 {
            前普通 = 码元;
        }
    }
    (改写串, 替换数)
}

#[cfg(test)]
mod 母语测试 {
    use super::*;

    #[test]
    fn 检测代码位全角() {
        let 警告们 = 检测全角标点("函数 主函数（）{\n    打印行！（\"你好\"）；\n}");
        let 字符们: Vec<char> = 警告们.iter().map(|警| 警.涉事字符).collect();
        assert_eq!(字符们, vec!['（', '）', '！', '（', '）', '；']);
        assert_eq!(警告们[0].行号, 1);
        assert_eq!(警告们[0].列序, 7);
        assert_eq!(警告们[0].替代字符, Some('('));
    }

    /// 字符切片入口与字符串入口口径一致（CLI 多文件路径两处共用一份切片）
    #[test]
    fn 字符切片入口与字符串入口一致() {
        let 源码 =
            "函数 主函数() {\n    让 x = 项们.展平（）;\n}\"里头的，不算\" // 注释里的，也不算";
        let 按串 = 检测全角标点(源码);
        let 字符们: Vec<char> = 源码.chars().collect();
        assert_eq!(检测全角标点字符(&字符们), 按串, "{按串:?}");
        assert!(
            !按串.is_empty(),
            "用例应至少命中一个全角标点，否则这条锁形同虚设"
        );
    }

    #[test]
    fn 忽略字符串与注释() {
        let 源码 = "打印行!(\"你好，世界！？\"); // 注释：这里随便，。！\n/* 块注释：（）； */\n让 文本 = \"括号（）内的不算\";";
        let 警告们 = 检测全角标点(源码);
        assert!(
            警告们.is_empty(),
            "字符串/注释内全角标点不应报告：{警告们:?}"
        );
    }

    #[test]
    fn 忽略字符字面态与原始串() {
        let 源码 = "让 字符 = '，';  // 字符字面态\n让 原始 = r#\"（全角）\"#;";
        let 警告们 = 检测全角标点(源码);
        assert!(警告们.is_empty(), "字符/原始字符串不应报告：{警告们:?}");
    }

    #[test]
    fn 仅提示字符无替代() {
        let 警告们 = 检测全角标点("让 顿号、= 1;");
        assert_eq!(警告们.len(), 1);
        assert_eq!(警告们[0].涉事字符, '、');
        assert_eq!(警告们[0].替代字符, None);
    }

    #[test]
    fn 串内转义引号() {
        let 源码 = "让 文本 = \"包含\\\"引号（全角）\";";
        let 警告们 = 检测全角标点(源码);
        assert!(警告们.is_empty(), "转义串不应报告：{警告们:?}");
    }

    #[test]
    fn 修复仅改代码位() {
        let 源码 = "函数 主函数（）{\n    打印行！（\"你好，世界\"）；\n}";
        let (修复后, 替换数) = 修复全角标点(源码);
        assert_eq!(替换数, 6);
        assert_eq!(修复后, "函数 主函数(){\n    打印行!(\"你好，世界\");\n}");
        // 字符串内的全角逗号保留
        assert!(修复后.contains("你好，世界"));
    }

    #[test]
    fn 修复保留仅提示字符() {
        let (修复后, 替换数) = 修复全角标点("让 甲、乙 = 1；");
        assert_eq!(替换数, 1, "只有全角分号被替换");
        assert_eq!(修复后, "让 甲、乙 = 1;");
    }

    #[test]
    fn 修复保留原始串() {
        let 源码 = "让 原始 = r#\"（全角）\"#;\n打印行！(\"x\");";
        let (修复后, 替换数) = 修复全角标点(源码);
        assert_eq!(替换数, 1);
        assert!(
            修复后.contains("r#\"（全角）\"#"),
            "原始字符串应保留：{修复后}"
        );
    }

    #[test]
    fn 修复保留转义引号串() {
        // 自动修复不得改写串内内容：源码含反斜杠转义引号，若被误判为字符串结束，
        // 后半全角括号会被当代码位替换。断言只改代码位全角分号、串内逐字节原样。
        // 补 串内转义引号 只测检测、未测改写（破坏性更强）的缺口。
        let 源码 = r#"让 文本 = "含\"号（全角）"；"#;
        let (修复后, 替换数) = 修复全角标点(源码);
        assert_eq!(替换数, 1, "只有代码位全角分号应被替换：{修复后}");
        assert!(
            修复后.contains("号（全角）"),
            "串内全角括号须原样：{修复后}"
        );
        assert_eq!(修复后, r#"让 文本 = "含\"号（全角）";"#);
    }
}
