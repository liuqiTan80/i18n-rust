//! 诊断翻译器：结合错误消息翻译表与类型映射，将 `rustc` 的英文诊断
//! 转化为面向母语学习者的教学诊断信息。
//!
//! ## 类型名本地化只作用于「注入值」
//!
//! 语言包 `消息模板` 里同时存在两类反引号英文词：一类是 `rustc` 填进来的类型名
//! （`{期望}`/`{实际}`/`{类型}`/`{qN}` 等占位符的值，该按 `类型映射` 中文化），
//! 另一类是作者手写的源代码语法示例（如 `[E0601]`「找不到入口函数」、
//! 「插入一层间接引用（如各类智能指针）」，必须保持原样。两者名字可能相同、
//! 只能按位置区分，所以本模块把本地化做在**写入模板之前**（`本地化记号`），
//! 模板字面不再参与全文改写；只有「整段文本就是 `rustc` 英文原文」的兜底路径
//! （两表未命中、占位符无法回填、英文残段回拼）才走 `替换类型名` 全文改写。

