/// 诊断翻译器：将 `rustc` 诊断翻译为教学诊断
///
/// 结合错误消息翻译表和类型映射，将 `rustc` 的英文诊断转化为
/// 面向中文学习者的教学诊断信息。
pub struct 诊断翻译器 {
    译表: 错误消息管理器,
    类型映射: HashMap<String, String>, // 来自关键字映射表，用于替换消息中的英文类型
    /// 待译清单登记用语言代码（`无` 取当前界面语言，见 [`超级::待译清单`]）
    待译语言: Option<String>,
}

/// 对带模块路径的类型名做最长后缀匹配
///
/// 带模块路径的类型名逐段尝试（从最短后缀试到最长），命中映射段后
/// 保留原路径前缀，仅替换命中的末段为母语名。
pub(crate) fn 替换类型段(
    记号: &str, 类型映射: &HashMap<String, String>
) -> Option<String> {
    let 段集: Vec<&str> = 记号.split("::").collect();
    for 我 in 1..段集.len() {
        let 后缀段 = 段集[我..].join("::");
        if let Some(中文) = 类型映射.get(&后缀段) {
            let mut 成品 = 段集[..我].join("::");
            if !成品.is_empty() {
                成品.push_str("::");
            }
            成品.push_str(中文);
            return Some(成品);
        }
    }
    None
}

/// 本地化带模块路径的类型名（三段式）
///
/// 1. 类型后缀段映射：末段特征名换成母语名，路径前缀保留
/// 2. 路径前缀完整匹配（从长到短）：整段模块路径映射为母语模块路径
/// 3. 剩余中间段单段映射：逐段查表替换为母语段名
///    最终：某格式化模块下的特征名可三段全本地化；
///    仅含路径而各段都未命中时返回 `无` 保持原样。
pub(crate) fn 本地化类型段(
    记号: &str, 映射表: &HashMap<String, String>
) -> Option<String> {
    let 原文 = 记号.to_string();
    // 1. 类型后缀段映射
    let 成品 = 替换类型段(记号, 映射表).unwrap_or_else(|| 记号.to_string());
    // 2. 路径前缀完整匹配（从长到短）
    let mut 段集: Vec<String> = 成品.split("::").map(|段| 段.to_string()).collect();
    if 段集.len() >= 2 {
        for 我 in (1..段集.len()).rev() {
            let 前缀段 = 段集[..我].join("::");
            if let Some(中文) = 映射表.get(&前缀段) {
                let 其余段 = 段集[我..].join("::");
                段集 = vec![中文.clone()];
                段集.extend(其余段.split("::").map(|段| 段.to_string()));
                break;
            }
        }
        // 3. 剩余中间段单段映射（跳过首尾，避免误伤已替换的路径与类型段）
        for 我 in 1..段集.len().saturating_sub(1) {
            if let Some(中文) = 映射表.get(&段集[我]) {
                段集[我] = 中文.clone();
            }
        }
    }
    let 改写串 = 段集.join("::");
    (改写串 != 原文).then_some(改写串)
}

/// 统计类型字符串开头的引用层数（`&` 前缀个数）
///
/// 规则：连续剥离引用前缀符，遇可变修饰（其后紧跟空格或位于串尾）即停止
/// —— 「引用符 + 可变 + 类型」是单层可变引用，不算两层。
/// 示例：单层引用计 1，两层引用计 2，可变引用计 1，无引用计 0。
pub(crate) fn 数引用层数(类型文: &str) -> usize {
    let mut 剩余 = 类型文;
    let mut 层数 = 0;
    while let Some(后半) = 剩余.strip_prefix('&') {
        层数 += 1;
        if 后半.starts_with("mut ") || 后半 == "mut" || 后半.starts_with("mut\t") {
            break;
        }
        剩余 = 后半;
    }
    层数
}

/// 去掉全部前导引用符与可变修饰后的核心类型
///
/// 用于判定两侧差异是否**仅为引用层数**：仅当剥去引用后的核心类型相同
/// （同一裸类型的不同引用层数）时，提示「检查引用符数量」才
/// 成立；剥尽引用后核心类型仍不同名是真实类型不
/// 匹配，此时提示引用层数是假阳性。
/// 示例：多层可变引用剥尽后回到裸类型名。
pub(crate) fn 引用本体类型(类型文: &str) -> &str {
    let mut 剩余 = 类型文;
    loop {
        if let Some(后半) = 剩余.strip_prefix('&') {
            剩余 = 后半;
        } else if let Some(后半) = 剩余.strip_prefix("mut ") {
            剩余 = 后半;
        } else {
            break;
        }
    }
    剩余.trim()
}

/// 本地化引用类型：先整体查类型映射（带引用符的完整类型名），
/// 未命中时逐个拆开引用前缀符，对本体做类型本地化后拼回
/// （保留原引用层数，仅把本体换成母语名）。
pub(crate) fn 本地化引用类型(
    类型文: &str, 映射表: &HashMap<String, String>
) -> String {
    if let Some(中文) = 映射表.get(类型文) {
        return 中文.clone();
    }
    let mut 前缀串 = String::new();
    let mut 剩余 = 类型文;
    while let Some(后半) = 剩余.strip_prefix('&') {
        前缀串.push('&');
        剩余 = 后半;
    }
    if 前缀串.is_empty() {
        return 类型文.to_string();
    }
    let (可变标记, 本体) = match 剩余.strip_prefix("mut ") {
        Some(本体) => ("mut ", 本体),
        None => ("", 剩余),
    };
    let 本体中文 = 映射表
        .get(本体)
        .cloned()
        .or_else(|| 本地化类型段(本体, 映射表))
        .unwrap_or_else(|| 本体.to_string());
    format!("{}{}{}", 前缀串, 可变标记, 本体中文)
}

/// 提取 `rustc` "if you wanted to use a crate named `X`" 建议中的包名
///
/// 公开给命令行侧复用：加依赖提示需要认出这条建议里的名字是否与包名相同，
/// 复制一份解析会造成两侧漂移（引擎已按此形状过滤非 ASCII 名）。
pub fn 建议包名(消息文: &str) -> Option<&str> {
    消息文
        .strip_prefix("if you wanted to use a crate named `")
        .and_then(|剩余| 剩余.split('`').next())
        .filter(|包名| !包名.is_empty())
}

/// 从「期望某类型、实际另一类型」形式的文本（`rustc` 标签）中提取期望/实际类型
fn 取期望实际(文字: &str) -> Option<(String, String)> {
    let 命中处 = 文字.find("expected ")?;
    let 后半 = &文字[命中处 + "expected ".len()..];
    let 逗号处 = 后半.find(", found ")?;
    let 预期类型 = 后半[..逗号处].trim().trim_matches('`').to_string();
    let 实际类型 = 后半[逗号处 + ", found ".len()..]
        .trim()
        .trim_matches('`')
        .to_string();
    Some((预期类型, 实际类型))
}

/// 整词替换：仅当目标前后字符均非标识符字符（字母/数字/下划线）时替换，
/// 避免裸词模式把以目标词为子串的驼峰或下划线标识符误伤
pub(crate) fn 整词替换(文字: &str, 从串: &str, 到串: &str) -> String {
    let 判定标识符 = |每字: char| 每字.is_alphanumeric() || 每字 == '_';
    let mut 成品 = String::with_capacity(文字.len());
    let mut 剩余 = 文字;
    while let Some(命中处) = 剩余.find(从串) {
        let 结尾 = 命中处 + 从串.len();
        let 前可 = 剩余[..命中处]
            .chars()
            .last()
            .is_none_or(|每字| !判定标识符(每字));
        let 后可 = 剩余[结尾..]
            .chars()
            .next()
            .is_none_or(|每字| !判定标识符(每字));
        成品.push_str(&剩余[..命中处]);
        成品.push_str(if 前可 && 后可 { 到串 } else { 从串 });
        剩余 = &剩余[结尾..];
    }
    成品.push_str(剩余);
    成品
}

/// 提取文本中所有反引号包裹的内容（按出现顺序）
fn 取反引号记号(文字: &str) -> Vec<String> {
    let mut 记号集 = Vec::new();
    let mut 剩余 = 文字;
    while let Some(首处) = 剩余.find('`') {
        let 后半 = &剩余[首处 + 1..];
        match 后半.find('`') {
            Some(尾处) => {
                记号集.push(后半[..尾处].to_string());
                剩余 = &后半[尾处 + 1..];
            }
            None => break,
        }
    }
    记号集
}

/// 从诊断消息中提取前两个反引号包裹的类型
///
/// `rustc` 1.97+ 的算术错误不再输出标签，类型信息嵌入消息，
/// 如 `E0369`：消息里两个反引号类型即期望/实际。
fn 从消息取类型(消息文: &str) -> Option<(String, String)> {
    let 记号集 = 取反引号记号(消息文);
    if 记号集.len() >= 2 {
        Some((记号集[0].clone(), 记号集[1].clone()))
    } else {
        None
    }
}

/// 由映射管理器构建诊断类型反查表（英文类型名 → 母语名），命令行与服务端共用。
///
/// 数据来源与优先级：`映射管理器` 在加载时已把候选按「模块路径 → 关键字
/// `[类型]` 节 → 标准库标识符 → 第三方标识符」与各来源的 **TOML 书写序**排好
/// （见其反查候选来源），这里只按「同一英文名取首个命中」落表；
/// 「只收母语键（含非 ASCII 字符）」的过滤也在候选汇总时完成，避免把
/// 同义纯英文修正项引入诊断译文（会让译文出现英文值）。
///
/// 为什么需要确定序：语言包允许同一英文值有多个母语同义词（如某显示特征
/// 既写在特征区作 `可显示`、又写在格式化区作 `显示`，两种方言写法都合法），
/// 早期实现直接遍历哈希表做「取条目后或插入」，胜出者取决于随机哈希
/// 种子——同一份代码两次「检查」的译文会翻转（实机 15 轮翻 7 轮），读者拿
/// 译文去搜 `rustc` 文档时偶尔搜不到。现在取书写序最前的主词条，译文与进程
/// 无关，门禁用例也能硬写期望值。
pub fn 构建类型映射(映射源: &映射管理器) -> HashMap<String, String> {
    let mut 反查表: HashMap<String, String> = HashMap::new();
    for (母语, 英文) in 映射源.取反查候选() {
        反查表.entry(英文.clone()).or_insert_with(|| 母语.clone());
    }
    反查表
}

/// 错误码模板（`[E0xxx]` 节）支持的动态占位符：按此顺序从消息原文反引号
/// 内容中依次回填。顺序须与各模板内占位符的出现先后相容（如 `E0609` 的
/// `{类型}` 先于 `{字段名}`、`E0027` 的 `{结构名}` 先于 `{字段名}`）；
/// 模板不含某占位符时不消费记号，故跨模板共用一份列表不会串位。
/// `{期望}`/`{实际}` 另有专门的期望/实际提取逻辑，不在此列。
///
/// `公开(超级)`：语言包门禁（测试模块）要用同一份清单校验教学提示，
/// 新增占位符时自动纳入检查，不必两处维护。
pub(super) const 码模板占位符集: &[&str] = &[
    "{变量名}",
    "{名称}",
    "{类型}",
    "{特征}",
    "{模块名}",
    "{字段名}",
    "{方法名}",
    "{函数名}",
    "{结构名}",
    "{关联类型}",
    "{特征名}",
    "{生命周期}",
];

/// [`诊断翻译器::渲染主消息`] 的返回：主消息译文与其教学提示。
#[derive(Debug, Clone)]
pub struct 已渲染消息 {
    /// 已回填占位符并完成类型中文化的主消息译文
    pub 文字: String,
    /// 命中条目的教学提示（若有），供调用方按需追加
    pub 提示: Option<String>,
}

impl 诊断翻译器 {
    /// 创建诊断翻译器
    pub fn 新建(译表: 错误消息管理器, 类型映射: HashMap<String, String>) -> Self {
        Self {
            译表,
            类型映射,
            待译语言: None,
        }
    }

    /// 指定待译清单登记语言（命令行按源文件扩展名传入，避免把别的语言漏译记到中文）
    pub fn 带待译语言(mut self, 语言码: impl Into<String>) -> Self {
        self.待译语言 = Some(语言码.into());
        self
    }

    /// 消息表本体（供 cargo 纯文本错误行等**非 JSON 通道**复用同一张表）
    pub fn 取译表(&self) -> &错误消息管理器 {
        &self.译表
    }

    /// 登记一条英文残留（兜底照旧输出原文，仅记录待补线索）
    fn 登记待译(&self, 级别文字: &str, 错误码文: Option<&str>, 消息文: &str) {
        super::待译清单::登记缺口(
            self.待译语言.as_deref().unwrap_or(""),
            级别文字,
            错误码文.unwrap_or(""),
            消息文,
        );
    }

    /// 仅凭（错误码, 消息原文, 主跨度标签）渲染主消息——命令行/服务端同口径共享入口。
    ///
    /// 渲染链与 [`诊断翻译器::翻译诊断`] 的主消息分支一致：
    /// 消息表的整句译文优先于会猜槽位的码表桩（见消息表胜出）→ 错误码表
    /// （完整桩/静态模板）→ 消息表（精确/前缀/后缀/通配段 + `{qN}` 回填）→
    /// 占位符按序回填；类型中文化只作用于回填进来的**值**，
    /// 模板字面不参与（见模块文档）。区别在于不依赖完整编译器诊断：
    /// 期望/实际取自 `主标签`（`rustc` 主跨度标签），其次从消息原文
    /// 期望/实际句式/前两个反引号类型提取；`{变量名}`/`{名称}`/`{类型}`/`{特征}`
    /// 按序取消息反引号内容。
    ///
    /// 安全兵：错误码模板存在无法回填的占位符时（如 `rust-analyzer` 把
    /// 期望/实际放在关联信息而非主消息的 `E0308`）**回退消息表**而非输出英文
    /// 或裸占位符——保证译文不劣于旧行为。命中任一表返回 `有值`，两表皆未命中
    /// 返回 `无`（调用方走轻量兵底）。
    pub fn 渲染主消息(
        &self,
        错误码文: Option<&str>,
        消息文: &str,
        主标签: Option<&str>,
    ) -> Option<已渲染消息> {
        let 码表条目 = 错误码文
            .filter(|码| !码.is_empty())
            .and_then(|码| self.译表.按码查询(码));
        let 消息查询 = self.译表.按消息查询(消息文);

        // 0. 消息表对该句有整条译文、而码表桩要靠记号顺序猜结构 → 用整句译文
        //    （`?` 的两条 `E0277` 消息：桩会渲染成「类型 `?` 未实现特征 `结果`」）
        let 优先消息 = super::消息翻译::消息表胜出(码表条目, 整句命中(&消息查询));

        // 1. 错误码表优先（与命令行「码表条目或用否则消息查询」对齐）
        if let Some(翻译条目) = 码表条目.filter(|_| !优先消息) {
            let mut 模板文字 = 翻译条目.消息模板.clone();
            let 预期实际 = 主标签
                .and_then(取期望实际)
                .or_else(|| 取期望实际(消息文))
                .or_else(|| 从消息取类型(消息文));
            if let Some((预期类型, 实际类型)) = 预期实际
                && !预期类型.is_empty()
                && !实际类型.is_empty()
            {
                // 注入前本地化：只有 rustc 报出的类型名进类型映射，模板字面
                // 里的英文标识符不参与（见 `替换类型名` 说明）
                模板文字 = 模板文字
                    .replace("{期望}", &self.本地化记号(&预期类型))
                    .replace("{实际}", &self.本地化记号(&实际类型));
            }
            // 其余占位符按出现顺序从消息反引号内容回退填充
            let mut 记号流 = 取反引号记号(消息文).into_iter();
            for 占位符 in 码模板占位符集 {
                if 模板文字.contains(占位符) {
                    match 记号流.next() {
                        Some(记号) => {
                            let 记号 = self.本地化记号(&记号);
                            模板文字 = 模板文字.replace(占位符, &记号);
                        }
                        None => break,
                    }
                }
            }
            // 仍有未回填占位符 → 码表桩无法从可用信息渲染 → 回退消息表（不出英文/裸占位符）
            let 未解析 = ["{期望}", "{实际}"]
                .iter()
                .chain(码模板占位符集.iter())
                .any(|占位| 模板文字.contains(占位));
            if !未解析 {
                return Some(已渲染消息 {
                    文字: 模板文字,
                    提示: 翻译条目.教学提示.clone(),
                });
            }
        }

        // 2. 消息表（精确/前缀/后缀/通配段）+ `{qN}` 回填，注入值额外做类型中文化
        if let Some((翻译条目, 残段)) = 消息查询 {
            let mut 文字 = 翻译条目.消息模板.clone();
            if let Some(残段值) = 残段 {
                let (已填充, 已消费) =
                    填充动态占位定制(&文字, &残段值, &mut |记号| self.本地化记号(记号));
                文字 = 已填充;
                if !已消费 {
                    // 残段未被模板消费 → 英文拼回尾巴（兜底），登记待译
                    //（残段整段是 rustc 原文，按全文口径中文化）
                    let 尾巴 = self.替换类型名(残段值.文字().to_string());
                    文字.push_str(&尾巴);
                    self.登记待译(super::待译清单::主消息级, 错误码文, 消息文);
                }
            }
            return Some(已渲染消息 {
                文字,
                提示: 翻译条目.教学提示.clone(),
            });
        }

        // 两表皆未命中：调用方兜底显示英文原文 → 登记待译清单
        self.登记待译(super::待译清单::主消息级, 错误码文, 消息文);
        None
    }

    /// 翻译单条诊断信息
    pub fn 翻译诊断(&self, 诊断: &编译器诊断) -> 教学诊断 {
        let 错误码文 = 诊断.诊断码.as_ref().map(|码| 码.码值.clone());

        let 码表条目 = 错误码文.as_deref().and_then(|码| self.译表.按码查询(码));
        // 无错误码或错误码未收录时，按消息原文匹配（消息翻译节）；
        // 消息表查询结果保留匹配来源（前缀/后缀键），供动态部分回填
        let 消息查询 = self.译表.按消息查询(&诊断.诊断消息);
        // 消息表对该句有整条译文、而码表桩要靠记号顺序猜结构 → 用整句译文
        //（`?` 的两条 `E0277` 消息：桩会渲染成「类型 `?` 未实现特征 `结果`」）
        let 优先消息 = super::消息翻译::消息表胜出(码表条目, 整句命中(&消息查询));
        let 匹配条目 = if 优先消息 {
            整句命中(&消息查询)
        } else {
            码表条目.or_else(|| 消息查询.as_ref().map(|(翻译条目, _)| *翻译条目))
        };
        // 选中哪张表决定动态部是否回拼：码表桩回拼会在母语模板后粘英文尾段
        //（见下方注释），只有走消息表条目时才按 `{qN}` 填充 / 回拼残段
        let 用码表条目 = !优先消息 && 码表条目.is_some();

        // 从主要跨度的标签中提取期望与实际；
        // rustc 1.97+ 的算术错误（`E0369` 等）不再输出标签，类型信息
        // 直接嵌入消息（算术不匹配消息里两个反引号类型即期望/实际），
        // 因此提取失败时回退从消息中解析反引号包裹的类型。
        let 主标签 = 诊断
            .跨度集
            .iter()
            .find(|每跨度| 每跨度.是否主因)
            .and_then(|每跨度| 每跨度.标签文本.as_deref());

        let (预期类型, 实际类型) = 主标签
            .and_then(取期望实际)
            .or_else(|| 从消息取类型(&诊断.诊断消息))
            .unwrap_or_default();

        // 构建翻译消息。第二个布尔位标记「文本就是 rustc 英文原文」：这类文本
        // 里的反引号记号全是 rustc 报出的类型，收尾要统一中文化；模板渲染
        // 出的文本已在注入点本地化，不能再全文改写（那会把模板字面里指源代码
        // 语法的入口函数名、智能指针类型等标识符二次翻译）。
        let (mut 译文消息, mut 原文标记) = if let Some(翻译条目) = 匹配条目 {
            let mut 模板文字 = 翻译条目.消息模板.clone();
            let mut 原文 = false;
            if !预期类型.is_empty() && !实际类型.is_empty() {
                模板文字 = 模板文字
                    .replace("{期望}", &self.本地化记号(&预期类型))
                    .replace("{实际}", &self.本地化记号(&实际类型));
            } else if 模板文字.contains("{期望}") || 模板文字.contains("{实际}") {
                // 无法提取期望/实际类型时回退 rustc 原文，避免输出裸占位符
                模板文字 = 诊断.诊断消息.clone();
                原文 = true;
                self.登记待译(
                    super::待译清单::主消息级,
                    错误码文.as_deref(),
                    &诊断.诊断消息,
                );
            }
            // 动态部分回填仅对消息表条目生效（前缀/后缀键匹配时保留动态名，
            // 如「你是否想用某名?」）；错误码条目是完整桩，回拼会在中文模板后
            // 粘上英文残段。错误码条目需要展示动态名称时用 `{名称}` 等占位符
            //（从消息反引号内容回退填充，见下方）。
            if !用码表条目 && let Some((_, Some(残段值))) = 消息查询 {
                let (已填充, 已消费) = 填充动态占位定制(&模板文字, &残段值, &mut |记号| {
                    self.本地化记号(记号)
                });
                模板文字 = 已填充;
                if !已消费 {
                    // 残段是 rustc 原文：整段按全文口径中文化后再拼回
                    let 尾巴 = self.替换类型名(残段值.文字().to_string());
                    模板文字.push_str(&尾巴);
                    self.登记待译(
                        super::待译清单::主消息级,
                        错误码文.as_deref(),
                        &诊断.诊断消息,
                    );
                }
            }
            (模板文字, 原文)
        } else {
            // 错误码表与消息表均未命中：原样显示英文（兜底），登记待译清单
            self.登记待译(
                super::待译清单::主消息级,
                错误码文.as_deref(),
                &诊断.诊断消息,
            );
            (诊断.诊断消息.clone(), true)
        };

        let mut 提示集 = Vec::new();
        if let Some(翻译条目) = 匹配条目
            && let Some(提示) = &翻译条目.教学提示
        {
            提示集.push(提示.clone());
        }
        for 子诊断 in &诊断.子诊断 {
            if 子诊断.级别 == "help" {
                // "if you wanted to use a crate named `X`" 建议：包名规则不允许
                // 非 ASCII，中文名实为拼写错误的母语模块，建议加依赖必然无效；
                // 静默丢弃，避免误导初学者。
                if 建议包名(&子诊断.诊断消息).is_some_and(|包名| !包名.is_ascii()) {
                    continue;
                }
                // 建议通道短语优先查消息表翻译（前缀匹配保留动态后缀），未命中保留原文
                let 提示 = self
                    .译表
                    .按消息查询(&子诊断.诊断消息)
                    .map(|(翻译条目, 残段)| {
                        let mut 文字 = 翻译条目.消息模板.clone();
                        if let Some(残段值) = 残段 {
                            // 模板含 `{q0}`/`{q1}` 捕获占位符时，从动态部分提取引号内容填充；
                            // 捕获完整覆盖时不再追加英文残段。
                            let (已填充, 已消费) = 填充动态占位(&文字, &残段值);
                            文字 = 已填充;
                            if !已消费 {
                                文字.push_str(残段值.文字());
                                self.登记待译(
                                    super::待译清单::建议级,
                                    错误码文.as_deref(),
                                    &子诊断.诊断消息,
                                );
                            }
                        }
                        文字
                    })
                    .unwrap_or_else(|| {
                        // 建议通道未译：英文原样进建议行，登记待译清单
                        self.登记待译(
                            super::待译清单::建议级,
                            错误码文.as_deref(),
                            &子诊断.诊断消息,
                        );
                        子诊断.诊断消息.clone()
                    });
                提示集.push(crate::语言::取带参消息(
                    "diag_fix_suggestion",
                    &[&提示],
                ));
            }
        }

        // `E0308` 引用层数教学提示：两侧引用层数不同（如一侧带引用符、
        // 另一侧为裸类型）且**剥去引用后的核心类型相同**时，追加一条检查
        // 引用符数量的提示，覆盖初学者最常见的借用错误之一。核心类型不同
        // （剥尽引用后仍不同名）是真实类型不匹配，不追加——
        // 否则建议「调整引用符数量」会误导（加/去引用符变不出另一种核心类型）。
        if 错误码文.as_deref() == Some("E0308") && !预期类型.is_empty() && !实际类型.is_empty()
        {
            let 预期层数 = 数引用层数(&预期类型);
            let 实际层数 = 数引用层数(&实际类型);
            if 预期层数 != 实际层数
                && (预期层数 > 0 || 实际层数 > 0)
                && 引用本体类型(&预期类型) == 引用本体类型(&实际类型)
            {
                提示集.push(crate::语言::取带参消息(
                    "diag_ref_depth_hint",
                    &[
                        &本地化引用类型(&预期类型, &self.类型映射),
                        &本地化引用类型(&实际类型, &self.类型映射),
                    ],
                ));
            }
        }

        let 位置集 = 诊断.跨度集.iter().map(诊断位置::自跨度).collect();

        // 所有权错误：提取叙事化详情（变量名、移动/借用、再次使用位置）
        let 所有权详情 = 错误码文.as_deref().and_then(|码| 提取所有权详情(码, 诊断));

        // 翻译消息中含 `{变量名}` 占位符时，用提取到的变量名填充（同上面注入点口径）
        if let Some(详情) = &所有权详情 {
            let 变量名 = self.本地化记号(&详情.变量名);
            译文消息 = 译文消息.replace("{变量名}", &变量名);
        }

        // 其余占位符（`{变量名}`/`{名称}`/`{类型}`/`{特征}`/`{模块名}`/`{字段名}` 等）
        // 按出现顺序从消息反引号内容回退填充，覆盖无标签的错误
        //（`E0384` 重复赋值、`E0433` 未找到类型、`E0583` 模块文件缺失等）；
        // 提取不到时回退 rustc 原文，避免输出裸占位符。
        let mut 记号流 = 取反引号记号(&诊断.诊断消息).into_iter();
        for 占位符 in 码模板占位符集 {
            if 译文消息.contains(占位符) {
                match 记号流.next() {
                    Some(记号) => {
                        let 记号 = self.本地化记号(&记号);
                        译文消息 = 译文消息.replace(占位符, &记号);
                    }
                    None => {
                        译文消息 = 诊断.诊断消息.clone();
                        原文标记 = true;
                        break;
                    }
                }
            }
        }
        // `rustc` 原文兜底路径（两表未命中、占位符无法回填）里的反引号记号
        // 就是 `rustc` 报出的类型名，在此统一中文化（如带模块路径的特征名
        // 本地化为母语模块路径下的母语名、数字字面量占位符换成母语名）；模板路径已在注入点
        // 本地化，不能再跑一遍——那会改写模板字面里作者手写的英文标识符。
        if 原文标记 {
            译文消息 = self.替换类型名(译文消息);
        }

        let 子诊断集 = 诊断
            .子诊断
            .iter()
            .map(|子诊断| self.翻译诊断(子诊断))
            .collect();

        教学诊断 {
            级别: 诊断级别::解析级别(&诊断.级别),
            错误码: 错误码文,
            译文消息,
            原文消息: 诊断.诊断消息.clone(),
            提示集,
            位置集,
            子诊断: 子诊断集,
            所有权详情,
        }
    }

    /// 使用类型映射替换消息中的英文类型名（**全文改写**）
    ///
    /// 只用于「整段文本就是 `rustc` 英文原文」的兜底路径（两表未命中、无法提取
    /// 期望/实际而回拼原句）：原文里的每个反引号记号都是 `rustc` 报出的类型，
    /// 该译的就译。模板渲染路径**不得**调用本函数——那里的反引号记号混着
    /// 作者写的源代码语法标识符，会被双重翻译；模板路径改为在
    /// 注入前用 [`诊断翻译器::本地化记号`] 处理 rustc 的实际值。
    fn 替换类型名(&self, 消息文: String) -> String {
        let 成品 = self.本地化字面量(消息文);
        self.本地化全部反引号(成品)
    }

    /// `rustc` 自身对数字字面量的占位显示名按全局语言替换
    ///
    /// `rustc` 未推断的数字字面量占位符及 1.97+ 的裸显示名；裸整数字面量名
    /// 用整词匹配，避免误伤以它为子串的方法名标识符。
    fn 本地化字面量(&self, 消息文: String) -> String {
        let mut 成品 = 消息文;
        成品 = 成品
            .replace("{integer}", &crate::语言::取消息("diag_rustc_integer"))
            .replace("{float}", &crate::语言::取消息("diag_rustc_float"))
            .replace(
                "floating-point number",
                &crate::语言::取消息("diag_rustc_float"),
            );
        整词替换(&成品, "integer", &crate::语言::取消息("diag_rustc_integer"))
    }

    /// 对文本里**所有**反引号记号做类型中文化（供 rustc 英文残段兜底使用）
    ///
    /// 仅替换反引号包裹的完整类型名（`rustc` 诊断中的类型均在反引号内），
    /// 避免过短条目命中长单词前缀，把消息里的整词错替成中英拼接串。
    fn 本地化全部反引号(&self, 文字: String) -> String {
        let mut 成品 = 文字;
        for 记号 in 取反引号记号(&成品) {
            if let Some(中文) = self.类型映射.get(&记号) {
                成品 = 成品.replace(&format!("`{}`", 记号), &format!("`{}`", 中文));
            } else if let Some(已替换) = 本地化类型段(&记号, &self.类型映射) {
                // 带模块路径的类型名：三段式本地化
                //（路径与末段特征名逐段映射为母语名）
                成品 = 成品.replace(&format!("`{}`", 记号), &format!("`{}`", 已替换));
            }
        }
        成品
    }

    /// 本地化**单个**由 rustc 注入模板的值（类型名、条目名、变量名等）
    ///
    /// 解析顺序与 [`诊断翻译器::本地化全部反引号`] 内的循环完全一致
    /// （字面量显示名 → 类型映射整项 → 三段式路径 → 原样），
    /// 保证「注入前本地化」与旧的「全文改写」对同一 rustc 值给出同一结果。
    fn 本地化记号(&self, 记号: &str) -> String {
        let 显示名 = self.本地化字面量(记号.to_string());
        if let Some(已本地化) = self.类型映射.get(&显示名) {
            return 已本地化.clone();
        }
        本地化类型段(&显示名, &self.类型映射).unwrap_or(显示名)
    }

    /// 批量翻译诊断列表
    pub fn 批量翻译(&self, 诊断集: &[编译器诊断]) -> Vec<教学诊断> {
        诊断集.iter().map(|诊断| self.翻译诊断(诊断)).collect()
    }
}
