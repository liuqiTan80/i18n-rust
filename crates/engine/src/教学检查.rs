//! 教学 lint 模块
//! 针对 Rust 初学者的启发式代码风格提示（教学价值驱动）：
//! 与编译器错误不同，这些提示不阻断编译，只在代码位置出现常见
//! 教学问题时给出建设性建议。规则刻意保守，避免噪音——教学工具的
//! 提示必须每条都有价值：
//! - 未标注类型：仅在类型**无法靠初始化式自行推导**的歧义形态提示
//!   （`让 横坐标 = 向量::新建();`、`让 横坐标 = 迭代器.收集();`）——这类位置
//!   rustc 迟早要求 E0282 注解，提前给出建设性建议；字面量、普通函数/
//!   方法调用、结构体/元组/数组、路径与块表达式的类型均可自行推导，
//!   提示「显式写出类型」无解且成噪音，不报告
//! - 魔法数字：非平凡数字字面量（命名常量教学）
//! - 嵌套过深：代码行缩进过深（重构教学，每文件仅首个）
//! - 易混方法名：方法调用位未命中映射表且与表内词近似的长中文串
//!   （如 `.拉平()` 应为 `.展平()`，编辑距离 ≤1 才提示以降噪）
//!
//! 行注释含「教学忽略」时整行跳过（教师可标注故意不修的示例）：
//! `让 横坐标 = 5;  // 教学忽略` 不产生任何教学警告。
//!
//! 扫描器与 fullwidth 模块同构：状态机跳过字符串/字符/原始字符串与
//! 注释，仅在代码位置判定，避免把字符串内容误判为代码问题。

use std::collections::HashSet;
use std::sync::atomic::{AtomicBool, Ordering};

/// 教学 lint 全局开关（默认开启，进程级）
///
/// 项目开发（非教学）场景下，初学者代码风格提示会在每次转译时刷屏；
/// CLI `--no-lint` 置为关闭（见 [`设定教学检查开关`]）。
/// 仅影响教学 lint 输出，Unicode 混杂/全角标点告警不受影响；
/// 与日志级别（logger）同为进程级配置。
static 教学提示开关: AtomicBool = AtomicBool::new(true);

/// 设置教学 lint 开关（进程级；测试与嵌入场景使用）
pub fn 设定教学检查开关(启用值: bool) {
    教学提示开关.store(启用值, Ordering::Relaxed);
}

/// 查询教学 lint 开关（输出方：转译管线/CLI 逐文件告警均据此静默）
pub fn 教学检查开关() -> bool {
    教学提示开关.load(Ordering::Relaxed)
}

/// 教学 lint 规则种类
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 检查种类 {
    /// `让` 绑定缺少类型注解
    未标注类型,
    /// 非平凡数字字面量（建议命名常量）
    魔法数字,
    /// 代码行嵌套过深（建议拆分函数）
    嵌套过深,
    /// 方法调用位的长中文串未命中映射表且与表内词近似（疑似笔误）
    易混方法名,
}

/// 单个教学 lint 警告：位置（1 起行/列）+ 规则 + 相关文本
#[derive(Debug, Clone, PartialEq)]
pub struct 检查警告 {
    /// 行号（从 1 开始）
    pub 行号: usize,
    /// 列号（从 1 开始，按字符计数）
    pub 列号: usize,
    /// 规则种类
    pub 种类: 检查种类,
    /// 相关文本（魔法数字原文、方法名等；其他规则为空串）
    pub 相关文本: String,
    /// 补充文本（易混词提示的候选词等；其他规则为空串）
    pub 补充文本: String,
}

impl 检查警告 {
    /// 格式化为单行提示文本，模板随当前语言变化
    pub fn 格式化提示(&self) -> String {
        match self.种类 {
            检查种类::未标注类型 => crate::语言::查译(
                "lint_untyped_let",
                &[&self.行号.to_string(), &self.列号.to_string()],
            ),
            检查种类::魔法数字 => crate::语言::查译(
                "lint_magic_number",
                &[
                    &self.行号.to_string(),
                    &self.列号.to_string(),
                    &self.相关文本,
                ],
            ),
            检查种类::嵌套过深 => crate::语言::查译(
                "lint_deep_indent",
                &[&self.行号.to_string(), &self.相关文本],
            ),
            检查种类::易混方法名 => crate::语言::查译(
                "lint_confusable_method",
                &[
                    &self.行号.to_string(),
                    &self.列号.to_string(),
                    &self.相关文本,
                    &self.补充文本,
                ],
            ),
        }
    }
}

/// 进行中的 `让` 绑定扫描（等待语句结束判定是否有类型注解）
struct 让扫描状态 {
    行号: usize,
    列号: usize,
    /// 已见到 `=`（其后出现的 `:` 是路径分隔符而非类型注解）
    已见等号: bool,
    /// 已见到 `:`（类型注解）
    已注解: bool,
    /// `=` 之后的初始化式原文（到 `;`/`{`/`}` 为止；用于判定类型能否
    /// 自行推导，仅在无注解时参与判定）
    初始化式: String,
}

/// 类型推导歧义构造器的英文被调名（无映射表时的兜底集合）
const 英文歧义构造器: &[&str] = &["new", "default"];

/// 对源码执行教学 lint（无已知词表：不做易混方法名提示），返回全部警告（升序）
///
/// 兼容入口；需要易混方法名提示（方法调用位未命中映射表）时用
/// [`执行教学检查并词表`] 并传入映射表键集合。
pub fn 执行教学检查(源码: &str) -> Vec<检查警告> {
    let 歧义词集: HashSet<String> = 英文歧义构造器
        .iter()
        .map(|字符串项| 字符串项.to_string())
        .collect();
    执行教学检查并词表(源码, &HashSet::new(), &歧义词集)
}

/// 对源码执行教学 lint，返回全部警告（升序）
///
/// `known_words`：全部映射表键的集合（关键字/宏/派生/模块路径/别名）。
/// 方法调用位出现未命中词表的长中文串（≥2 字）且与表内词近似
/// （编辑距离 ≤1）时提示疑似笔误——未命中词会被原样保留，错误在
/// 产物侧才爆发（如 `.拉平()` 应为 `.展平()`）。
///
/// `ambiguous_constructors`：类型推导歧义构造器的被调名集合（含英文
/// `新建`/`缺省` 及其各方言映射词，如「新建」「缺省」），由
/// `映射管理器::歧义构造词集` 提供；仅这些关联构造
/// 的无 turbofish 调用与无 turbofish 的 `.收集()` 才触发未标注类型提示。
///
/// 仅报告代码位置的问题；字符串/注释内的同名文本被状态机跳过。
pub fn 执行教学检查并词表(
    源码: &str,
    已知词表: &HashSet<String>,
    歧义构造器集: &HashSet<String>,
) -> Vec<检查警告> {
    let 字符序列: Vec<char> = 源码.chars().collect();
    let mut 警告表 = Vec::new();
    let mut 行号 = 1usize;
    let mut 列号 = 1usize;
    // 字面量状态：0 = 代码位置；1 = 双引号串 2 = 字符 3 = 原始串
    let mut 字面量态: u8 = 0;
    let mut 原始井数 = 0usize;
    let mut 上一字 = '\0';
    // 行首缩进追踪（仅代码行累计，用于嵌套深度提示）
    let mut 行缩进 = 0usize;
    let mut 在行首 = true;
    let mut 首非空是注释 = false;
    let mut 深层已报 = false;
    // 未标注类型扫描状态
    let mut 让扫描: Option<让扫描状态> = None;
    // 行注释含「教学忽略」的行号：整行跳过教学警告（教师标注故意不修的示例）
    let mut 忽略行集: HashSet<usize> = HashSet::new();

    let mut 下标 = 0usize;
    while 下标 < 字符序列.len() {
        let 本字符 = 字符序列[下标];
        // 行首缩进累计（独立于字面量状态：多行字符串内部行由 literal
        // 分支吞掉，不会走到这里；行首仅代码位置才累计）
        if 在行首 && 字面量态 == 0 {
            match 本字符 {
                ' ' => {
                    行缩进 += 1;
                    下标 += 1;
                    列号 += 1;
                    continue;
                }
                '\t' => {
                    行缩进 += 4;
                    下标 += 1;
                    列号 += 1;
                    continue;
                }
                '\n' => {
                    // 空行/纯空白行的换行：须与主循环的换行处理一致（行号 +1、列复位），
                    // 否则空行不计行，其后所有警告位置整体前移（回归：第 5 行的 `让`
                    // 因上方两个空行被报成第 3 行）
                    行号 += 1;
                    列号 = 1;
                    行缩进 = 0;
                    在行首 = true;
                    首非空是注释 = false;
                    上一字 = '\0';
                    下标 += 1;
                    continue;
                }
                '/' if !首非空是注释
                    && 下标 + 1 < 字符序列.len()
                    && (字符序列[下标 + 1] == '/' || 字符序列[下标 + 1] == '*') =>
                {
                    // 注释行：不参与嵌套深度提示
                    首非空是注释 = true;
                    在行首 = false;
                }
                _ => {
                    // 首个非空白字符（非注释）：代码行，判定嵌套深度
                    if 行缩进 >= 嵌套深度阈值 && !深层已报 {
                        深层已报 = true;
                        警告表.push(检查警告 {
                            行号,
                            列号: 行缩进 + 1,
                            种类: 检查种类::嵌套过深,
                            相关文本: 行缩进.to_string(),
                            补充文本: String::new(),
                        });
                    }
                    在行首 = false;
                }
            }
        }
        if 本字符 == '\n' {
            行号 += 1;
            列号 = 1;
            行缩进 = 0;
            在行首 = true;
            首非空是注释 = false;
            上一字 = '\0';
            if 字面量态 == 2 || 字面量态 == 3 {
                // 防御：字符/原始串内出现未闭合引号时在行尾强制退出，
                // 避免状态污染后续行（编译器本就会报错，此处只为正确判定）
                字面量态 = 0;
            }
            下标 += 1;
            continue;
        }
        match 字面量态 {
            1 | 2 => {
                // 字符串/字符字面量：转义跳过下一字符，闭合引号退出
                if 本字符 == '\\' {
                    下标 += 2;
                    列号 += 1;
                    continue;
                }
                let 结束引号 = if 字面量态 == 1 { '"' } else { '\'' };
                if 本字符 == 结束引号 {
                    字面量态 = 0;
                }
            }
            3 => {
                // 原始字符串 r#"..."#：遇 " 后跟等量 #（或行尾/EOF）退出
                if 本字符 == '"' {
                    let 井号数 = 字符序列[下标 + 1..]
                        .iter()
                        .take_while(|字符值| **字符值 == '#')
                        .count();
                    if 井号数 >= 原始井数 {
                        字面量态 = 0;
                        原始井数 = 0;
                    }
                }
            }
            _ => match 本字符 {
                '"' => 字面量态 = 1,
                '\'' => 字面量态 = 2,
                // 行注释：吞到行尾（\n 留给主循环统一处理）
                '/' if 上一字 == '/' => {
                    let 注释起始 = 下标;
                    列号 -= 1;
                    while 下标 < 字符序列.len() && 字符序列[下标] != '\n' {
                        下标 += 1;
                        列号 += 1;
                    }
                    // 注释含「教学忽略」：整行跳过教学警告
                    let 注释文: String = 字符序列[注释起始..下标].iter().collect();
                    if 注释文.contains(教学忽略标记) {
                        忽略行集.insert(行号);
                    }
                    上一字 = '\0';
                    continue;
                }
                // 块注释（不处理嵌套，够用）
                '*' if 上一字 == '/' => {
                    列号 -= 1;
                    while 下标 < 字符序列.len() {
                        let 次字符 = 字符序列[下标];
                        下标 += 1;
                        if 次字符 == '\n' {
                            行号 += 1;
                            列号 = 1;
                        } else if 次字符 == '*' && 下标 < 字符序列.len() && 字符序列[下标] == '/'
                        {
                            下标 += 1;
                            列号 += 2;
                            break;
                        } else {
                            列号 += 1;
                        }
                    }
                    上一字 = '\0';
                    continue;
                }
                // 原始字符串前缀 r#"..."#（r 或 br 后跟 " 或 #）
                'r' | 'b' if 是原始前缀(上一字) => {
                    let mut 新井数 = 0usize;
                    let mut 内索引 = 下标 + 1;
                    while 内索引 < 字符序列.len() && 字符序列[内索引] == '#' {
                        新井数 += 1;
                        内索引 += 1;
                    }
                    if 内索引 < 字符序列.len() && 字符序列[内索引] == '"' {
                        原始井数 = 新井数;
                        字面量态 = 3;
                        下标 = 内索引 + 1;
                        列号 += 1 + 新井数 + 1;
                        continue;
                    }
                }
                // `让` 关键字：简单标识符绑定时开始未标注类型扫描（前后均须
                // 有标识符边界）；模式解构绑定（元组/结构体/数组/枚举解构、
                // 让-否则、let 链）不做提示——教学示例均以不标注形式书写，
                // 且无法自然标注类型（须标注整个模式），提示无解成噪音
                '让' if 是标识符边界(上一字)
                    && (下标 + 1 >= 字符序列.len() || 是标识符边界(字符序列[下标 + 1])) =>
                {
                    // 前一个 let 未闭合（上一语句缺分号）：先收尾
                    收尾让扫描(&mut 让扫描, &mut 警告表, 歧义构造器集);
                    if 是简单让绑定(&字符序列, 下标 + 1) {
                        让扫描 = Some(让扫描状态 {
                            行号,
                            列号,
                            已见等号: false,
                            已注解: false,
                            初始化式: String::new(),
                        });
                    }
                }
                // 数字字面量（前一字不是标识符字符时才是独立字面量）
                字 if 字.is_ascii_digit() && 是标识符边界(上一字) => {
                    下标 = 扫描数字(&字符序列, 下标, 本字符, &mut 警告表, 行号, 列号, 上一字);
                    continue;
                }
                // 方法调用位的长中文串（如 `.拉平()`）：未命中映射表且与
                // 表内词近似时提示疑似笔误——未命中词会被原样保留，错误在
                // 产物侧才爆发（#14）。仅调用位（后随 `(`）判定以降噪；
                // `..` 范围与浮点（前一字为 `.`/数字）不启动扫描。
                '.' if 上一字 != '.' && !上一字.is_ascii_digit() => {
                    if let Some(名字) = 扫描方法名(&字符序列, 下标)
                        && let Some(候选词) = 易混候选(&名字, 已知词表)
                    {
                        警告表.push(检查警告 {
                            行号,
                            列号: 列号 + 1,
                            种类: 检查种类::易混方法名,
                            相关文本: 名字,
                            补充文本: 候选词.to_string(),
                        });
                    }
                }
                _ => {}
            },
        }
        // let 扫描推进：仅在代码位置处理语句内符号
        if let Some(扫描) = 让扫描.as_mut() {
            match 本字符 {
                ':' if !扫描.已见等号 => 扫描.已注解 = true,
                '=' => 扫描.已见等号 = true,
                ';' | '{' | '}' => 收尾让扫描(&mut 让扫描, &mut 警告表, 歧义构造器集),
                _ if 扫描.已见等号 => 扫描.初始化式.push(本字符),
                _ => {}
            }
        }
        下标 += 1;
        列号 += 1;
        if 本字符 != ' ' && 本字符 != '\t' && 字面量态 == 0 {
            上一字 = 本字符;
        }
    }
    收尾让扫描(&mut 让扫描, &mut 警告表, 歧义构造器集);
    // 过滤被「教学忽略」标记的行（三种规则统一按行过滤）
    警告表.retain(|警告项| !忽略行集.contains(&警告项.行号));
    警告表
}

/// 教学忽略标记：行注释含此文本时该行跳过全部教学警告
pub const 教学忽略标记: &str = "教学忽略";

/// 嵌套深度阈值：前导缩进 ≥ 此空格数时提示（24 = 6 层，4 空格一层）
const 嵌套深度阈值: usize = 24;

/// 判定字符是否可作为标识符边界（非字母/数字/下划线即边界）
fn 是标识符边界(字: char) -> bool {
    !(字.is_alphanumeric() || 字 == '_')
}

/// 判定前一字符是否可作为原始字符串前缀（r#/br#：前一字为行首/空白/运算符）
fn 是原始前缀(前一: char) -> bool {
    前一 == '\0' || 前一.is_whitespace() || "([{<,;:!?&|=+-*/%^".contains(前一)
}

/// 判定 `让` 后的绑定是否为简单标识符绑定（`名字` / `可变 名字`）
///
/// `从` 为「让」之后的下标。仅简单绑定参与「未标注类型」提示；
/// 模式解构绑定（`(甲, 乙)`、`点 { 横坐标, 纵坐标 }`、`[首, 次]`、`有值(数)`、
/// `枚举::变体(数)` 等）返回 false——这类绑定须标注整个模式的类型
/// （远超初学者范围），教程示例均不标注，提示无解且成噪音。
///
/// 无法归类的形态（如语法错误、注释紧跟）一律返回 false（宁缺毋滥）。
fn 是简单让绑定(字符序列: &[char], 起始下标: usize) -> bool {
    let mut 内索引 = 起始下标;
    // 跳过空白（含换行：多行布局不影响绑定判定）
    while 内索引 < 字符序列.len() && 字符序列[内索引].is_whitespace() {
        内索引 += 1;
    }
    // 可选「可变」前缀（`让 可变 名字 = …`；须为独立词）
    if 以独立词开始(字符序列, 内索引, "可变") {
        内索引 += "可变".chars().count();
        while 内索引 < 字符序列.len() && 字符序列[内索引].is_whitespace() {
            内索引 += 1;
        }
    }
    // 绑定首字符须为标识符字符：`(`/`[`/`{` 等模式起始一律排除
    if 内索引 >= 字符序列.len() || !(字符序列[内索引].is_alphanumeric() || 字符序列[内索引] == '_')
    {
        return false;
    }
    // 收集标识符（到名字结束），再跳过名字与后续符号之间的空白
    let mut 次索引 = 内索引;
    while 次索引 < 字符序列.len() && (字符序列[次索引].is_alphanumeric() || 字符序列[次索引] == '_')
    {
        次索引 += 1;
    }
    while 次索引 < 字符序列.len() && 字符序列[次索引].is_whitespace() {
        次索引 += 1;
    }
    match 字符序列.get(次索引) {
        // `名字 = …` / `名字;`（语法错，交给编译器）：简单绑定
        Some('=' | ';') => true,
        // 单个 `:` 是类型标注（`名字: 类型 = …`）；`::` 是路径
        // （`枚举::变体(数)` 模式）——后者非简单绑定
        Some(':') => !matches!(字符序列.get(次索引 + 1), Some(':')),
        // `名字(` / `名字 {` 等模式、行尾、无法归类的形态：不提示
        _ => false,
    }
}

/// 判断 `逐字符[内索引..]` 是否以独立词 `word` 开头（词后不能紧跟标识符续字符）
fn 以独立词开始(字符序列: &[char], 内索引: usize, 词项: &str) -> bool {
    let 词: Vec<char> = 词项.chars().collect();
    if 内索引 + 词.len() > 字符序列.len() || 字符序列[内索引..内索引 + 词.len()] != 词[..]
    {
        return false;
    }
    !matches!(字符序列.get(内索引 + 词.len()), Some(字) if 字.is_alphanumeric() || *字 == '_')
}

