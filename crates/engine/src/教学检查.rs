    #[test]
    fn 测试深嵌套仅报一次() {
        // 两处深层嵌套：仅首个报告（避免刷屏）；缩进逐层递增
        let mut 源码 = String::from("函数 主函数() {\n");
        for 层级 in 1..=7 {
            源码.push_str(&"    ".repeat(层级));
            源码.push_str("if 真 {\n");
        }
        源码.push_str(&"    ".repeat(8));
        源码.push_str("让 x = 1;\n");
        for 层级 in (1..=7).rev() {
            源码.push_str(&"    ".repeat(层级));
            源码.push_str("}\n");
        }
        源码.push_str("    if 真 {\n        如果 真 {\n            循环 {\n");
        源码.push_str(&"    ".repeat(5));
        源码.push_str("让 y = 1;\n");
        源码.push_str("            }\n        }\n    }\n}\n");
        let 警告表 = 执行教学检查(&源码);
        let 深层表: Vec<_> = 警告表
            .iter()
            .filter(|警告项| 警告项.种类 == 检查种类::嵌套过深)
            .collect();
        assert_eq!(深层表.len(), 1, "{警告表:?}");
        // 第 7 层 if（第 7 行）缩进已达 24 空格阈值，是首个触发点
        assert_eq!(深层表[0].行号, 7);
    }

