//! 将源代码中的中文标识符别名（如第三方库的中文名称）替换为英文标识符。
//! 仅替换标识符类型的词元，不触碰字符串字面量和注释等内容。
//! 声明位保护：紧跟在声明关键字（函数、结构体、枚举、特征、类型、模块、让 等）
//! 后的标识符是用户自己的定义，不是库 API 引用，不参与别名替换；且用户声明的
//! 名字在整个文件内的裸使用处都豁免（两遍扫描：先收集声明名，再逐词元替换），
//! 避免 `让 新建 = 5` 声明位受保护而后续使用处被误替换成「新建」的映射目标。
//! 三条精细规则：
//! 1. `::` 限定后的路径段按「链根」分级处理：根是项目符号
//!    （包根、自身、父级、项目模块名、项目项名）时链内**与项目声明名
//!    同名**的段豁免——`平台Linux::新建` 的定义侧与调用侧一致
//!    （避免 E0599）；链内非项目名与根非项目符号的段都照常替换
//!    （`源码映射项::新建` 的 `新建` 未定义于项目、`盒子::新建`
//!    的 `新建` 是库 API）；无项目上下文时退化为「本文件项名豁免」
//!    （`接口错误::错误请求`）；
//! 2. 库特征实现块（`实现 某特征 对于 类型 {}`）内的方法名是库 API
//!    规定的名称（用户从映射表抄写而来），不是用户自定义名字，不受声明位
//!    保护——`实现 抄写器 对于 类型 { 函数 渲染（...） }` 中的 `渲染`
//!    必须转译，否则无法匹配库特征规定的同名方法（E0407/E0046）；
//! 3. 函数参数与闭包参数是「值绑定」（用户命名）：`函数 完整网址(路径: &文本)`
//!    的 `路径` 在声明与使用处都豁免替换（参数「类型」位置的字照常替换），
//!    与格式化串中的 `{路径}` 保持一致，避免 E0425（找不到名称 `路径`）；
//! 4. 结构体字段名与枚举变体名同样是用户命名，纳入声明收集：
//!    字段 `结构体 容器 { 值: 整数 }` 的 `值`（撞「值」映射键）
//!    在定义/构造/访问处（`实例.值`）全豁免；枚举变体
//!    `枚举 判定结果 { 保留, 丢弃 }` 的 `保留`/`丢弃`（撞
//!    retain/drop 映射键）同理；变体可经 `::` 访问
//!    （`判定结果::保留`）故收集为项，字段收集为值绑定。
//!    方法调用位（`实例.方法()`）不查字段名：`编辑表.长度()` 的
//!    `长度` 是 `向量::长度` 调用，只查「项目方法名集合」（项）；
//! 5. 模式绑定（匹配臂、让 解构、循环模式）同样是值绑定：
//!    `匹配 有值(入参) { 有值(连接) => … }` 的 `连接` 全文件豁免
//!    （见「收集模式绑定」）。

use rustc_lexer::TokenKind;
use std::collections::{HashMap, HashSet};

use crate::名字缓存::名字缓存;
use crate::缓存::源码映射条目;

/// 单阶段替换结果：输出与编辑表
///
/// 编辑表以**本阶段输入文本**的字节偏移记录（输入偏移升序、互不重叠），
/// 替换文字为本阶段输出文本。
#[derive(Debug, Clone)]
pub struct 替换结果 {
    /// 替换后的文本
    pub 输出文本: String,
    /// 编辑表
    pub 编辑表: Vec<源码映射条目>,
}

/// 声明位关键字（转译后的英文形式）：其后紧跟的标识符为用户定义
///
/// 不含「可变」：仅在 `让 可变 名称` 场景下透明传递声明状态（见替换循环），
/// `&可变 类型` 等非声明位的可变不传递，避免误保护库类型引用。
/// 不含「实现」：`实现 特征 对于 类型` 中的特征/类型多为库 API，仍需替换。
/// 列映射模拟别名替换时复用同一张表，保证两侧行为一致。
pub const 声明关键字表: &[&str] = &[
    "fn", "struct", "enum", "trait", "type", "mod", "let", "const", "static",
];

/// 变量声明关键字：其后名字是「变量」（不可经 `::` 访问）；
/// [`声明关键字表`] 的其余关键字（函数/结构体/枚举/特征/类型/模块）声明的
/// 是「项」，项可经 `::` 访问（见模块文档第 1 条规则）
const 变量声明关键字表: &[&str] = &["let", "const", "static"];

/// 用户声明名与库特征方法名的收集结果
#[derive(Debug, Default)]
pub struct 已声明名集合 {
    /// 项声明名（函数/结构体/枚举/特征/类型/模块）+ 枚举变体名：
    /// `::` 后的同名标识符仍豁免
    pub 条目集: HashSet<String>,
    /// 变量声明名（让/常量/静态）+ 函数/闭包参数：
    /// `::` 后的同名标识符照常替换
    pub 变量集: HashSet<String>,
    /// 结构体命名字段：裸使用处豁免（`实例.字段`/结构体字面量）；
    /// `::` 后照常替换（字段不能经 `::` 访问）。
    /// 与变量集分开收集，供项目级合并（绑定名是文件局部的）
    pub 成员集: HashSet<String>,
    /// 库特征实现块内的方法名：声明位保护对这些名字失效（库 API 名称）
    pub 库方法集: HashSet<String>,
}

/// 项目级声明上下文（跨文件声明豁免）
///
/// 单文件的声明豁免无法覆盖跨文件调用：甲文件声明 `公开 函数 新建()`，
/// 乙文件调用 `包::甲::新建()` 时乙的转译单元看不到甲的声明，
/// `新建` 被当作库别名替换成「新建」的映射目标（E0599）。转译前扫描同包
/// 全部方言源文件汇总本结构，把使用处豁免升级到项目级。
///
/// 保守近似与单文件声明豁免一致：不做作用域/可见性分析，同名即豁免。
#[derive(Debug, Default, Clone)]
pub struct 项目上下文 {
    /// 项目模块名（方言文件名词干）：`::` 路径链根
    pub 模块集: HashSet<String>,
    /// 项目声明名（项 + 结构体字段）：裸使用处豁免
    ///（让/参数等文件内绑定不参与合并——绑定名是文件局部的）
    pub 名字集: HashSet<String>,
    /// 项目项名（函数/结构体/枚举/特征/类型/模块 + 枚举变体）：
    /// `::` 路径段豁免与路径链根判定（字段不参与：不可经 `::` 访问）
    pub 条目集: HashSet<String>,
}

impl 项目上下文 {
    /// 从项目源文件集合构建：`模块集` 为项目模块名词干，
    /// `源集合` 为全部方言源文件内容（母语原文）
    ///
    /// 声明收集工作在关键字转译后的文本上进行（声明关键字需英文形式），
    /// 内部对每个源文件先跑词法转译阶段再收集。
    pub fn 从源集合<'甲>(
        模块集: HashSet<String>,
        源集合: impl IntoIterator<Item = &'甲 str>,
        管理器: &crate::映射管理器::映射管理器,
    ) -> Self {
        let 声明们: Vec<已声明名集合> = 源集合
            .into_iter()
            .map(|原因| 收集源声明(原因, 管理器))
            .collect();
        Self::从声明集合(模块集, 声明们.iter())
    }

    /// 同 [`自身::从源集合`]，但单文件声明收集结果由调用方提供
    ///
    /// 汇总规则唯一来源（[`自身::从源集合`] 亦委托本函数）：调用方可按
    /// 文件粒度缓存 [`收集源声明`] 的结果（如列映射服务按内容哈希
    /// 缓存），避免同一内容被重复跑词法转译，同时无需复刻合并规则。
    pub fn 从声明集合<'甲>(
        模块集: HashSet<String>,
        声明集合: impl IntoIterator<Item = &'甲 已声明名集合>,
    ) -> Self {
        let mut 名字集 = HashSet::new();
        let mut 条目集 = HashSet::new();
        for 已声明 in 声明集合 {
            for 名字值 in &已声明.条目集 {
                名字集.insert(名字值.clone());
                条目集.insert(名字值.clone());
            }
            名字集.extend(已声明.成员集.iter().cloned());
        }
        Self {
            模块集,
            名字集,
            条目集,
        }
    }

    /// 是否为空（无模块且无声明名）：空上下文不产生任何豁免
    pub fn 上下文为空(&self) -> bool {
        self.模块集.is_empty() && self.名字集.is_empty()
    }

    /// 项目上下文指纹（排序后哈希，跨进程确定）：并入转译缓存指纹，
    /// 项目声明集合变化时相关缓存自动失效
    pub fn 指纹(&self) -> u64 {
        use std::hash::{Hash, Hasher};
        let mut 模块向量: Vec<&String> = self.模块集.iter().collect();
        模块向量.sort_unstable();
        let mut 名字向量: Vec<&String> = self.名字集.iter().collect();
        名字向量.sort_unstable();
        let mut 条目向量: Vec<&String> = self.条目集.iter().collect();
        条目向量.sort_unstable();
        let mut 散列器 = std::collections::hash_map::DefaultHasher::new();
        ("i18n-rust-project", 模块向量, 名字向量, 条目向量).hash(&mut 散列器);
        散列器.finish()
    }

    /// 裸使用处豁免：项目声明名（项 + 结构体字段，含其他文件声明）
    fn 裸使用豁免(&self, 文本响应: &str) -> bool {
        self.名字集.contains(文本响应)
    }

    /// 路径链根判定：包根、父级、自身、项目模块名、项目项名。
    /// 根段后跟 `::` 时整条路径视为项目路径（链内全部段豁免）
    fn 是路径根(&self, 文本响应: &str) -> bool {
        matches!(文本响应, "crate" | "super" | "self")
            || self.模块集.contains(文本响应)
            || self.条目集.contains(文本响应)
    }
}

/// 类型体（结构体/枚举）扫描状态：收集命名字段与枚举变体
#[derive(Debug)]
struct 类型体扫描 {
    /// 是否为枚举体（枚举顶层成员是变体，收集为项）
    为枚举体: bool,
    /// 花括号深度（1 = 类型体顶层）
    深度: u32,
    /// 处于成员开始位置（`{`/`,` 之后）：下一个标识符是字段名/变体名
    位于起点: bool,
    /// 已见的名字（等 `:` 确认后收集为字段）
    待定成员: Option<String>,
}
/// 收集单个方言源文件的声明名（词法转译 + 声明扫描）
///
/// 与 [`项目上下文::从源集合`] 内部的单文件收集步骤完全一致
/// （后者亦委托本函数，规则唯一来源），供需要按文件粒度缓存结果的调用方
/// 使用——例如列映射服务每按键都要汇总全部打开文件的声明名，若每次重算
/// 等于 O(项目规模) 次词法转译；按内容哈希缓存本函数的返回值后，
/// 每次按键只有内容真正变化的那个文件需要重算。
pub fn 收集源声明(
    原因: &str, 管理器: &crate::映射管理器::映射管理器
) -> 已声明名集合 {
    let 词法产物 = crate::词法器::分词转译(
        原因,
        管理器.取关键词表(),
        管理器.取宏表(),
        管理器.取派生特征表(),
        管理器.取让位词(),
        管理器.取方法让位词(),
        管理器.取别名表(),
    );
    收集声明名(&词法产物.输出, 管理器.取别名表())
}

/// 收集用户在声明位定义的标识符名（第一遍扫描）
///
/// 状态机与替换主循环一致：声明关键字后紧跟的标识符计入集合；
/// 「可变」在声明态内透明传递；空白/注释不打断声明态；符号终结声明位。
/// 另收集「值绑定」：函数参数名（`函数 名(参数: 类型)` 中的参数开始位
/// 且后跟 `:`）与闭包参数名（`|甲, 乙|`，可无类型标注直接收集）——
/// 绑定名是用户命名，不是库 API 引用。
/// 结构体/枚举体扫描（[`类型体扫描`]）：命名字段（`字段: 类型`）
/// 收集为值绑定，枚举顶层变体名收集为项（变体可经 `::` 访问）。
/// 集合内的名字在文件内的使用处豁免别名替换（保守近似：不做作用域
/// 分析，同名遮蔽场景同样豁免，与声明位保护的设计意图一致）。
/// 库特征实现块内的方法名（见「库特征实现方法收集」）从保护集合剔除。
pub fn 收集声明名(原因: &str, 别名映射: &HashMap<String, String>) -> 已声明名集合 {
    let 词元们 = crate::收集令牌(原因);
    在文本中收集声明名(原因, 别名映射, &词元们)
}

/// [`收集声明名`] 的实现：调用方已持有词元序列时直接复用，
/// 避免同一份源码被重复词法化
///
/// 管线内部也直接走本入口：延迟项目上下文的入口要对词法产物的输出文本
/// 切分令牌才能收集声明，而导入路径阶段恰好也在这份文本上跑，两者共用
/// 同一份词元流。
///
/// 声明收集的三个方面合并为**一次**词元遍历：
/// - 声明位（函数/结构体/让/常量/静态… 后的名字）、类型体成员、
///   函数与闭包参数；
/// - 库特征实现块的方法名：`实现 特征 对于 类型 { 函数 方法 }` 中，特征名
///   既不是本文件声明的项、又在别名映射表里时，块内方法名是库 API（用户从
///   映射表抄写而来），必须照常参与替换；实现用户自定义特征时方法名是用户
///   取的名字，保持声明位保护；
/// - 模式绑定：匹配臂（`=>` 向左回溯到臂起点）、让 解构括号内、循环到
///   迭代源之间的名字是用户命名的值绑定，与参数一样全文件豁免替换
///   （`有值(连接) =>` 的 `连接` 撞「连接」词条，误替换即缺陷）。
///
/// 三组状态互不读对方的中途结果（库特征判定用的 `条目集` 只在整份源码扫完
/// 后），所以能并在一起：每个词元只取一次文本切片、只分派一次。此前
/// 三者各走一遍词元流，98 千字节 / 2805 行样例声明收集 1684 → 1513 µs
/// （−10.2%，同进程交替 5/5 轮）；1193 份语料与旧实现逐字段零差异。
///
/// 但仍保留原来的**两阶段顺序**：库特征方法名要拿扫完后的完整 `条目集` 判定
/// 并统一剔除（实现块可以出现在目标类型声明之前），模式绑定在那之后再并入。
pub(crate) fn 在文本中收集声明名<'甲>(
    原因: &'甲 str,
    别名映射: &HashMap<String, String>,
    词元序列: &[rustc_lexer::Token],
) -> 已声明名集合 {
    let mut 声明累计 = 已声明名集合::default();
    // —— 一：声明位 / 类型体 / 函数与闭包参数 ——
    let mut 前一关键字: Option<&'甲 str> = None;
    let mut 待定类型: Option<(bool, bool)> = None;
    let mut 类型体: Option<类型体扫描> = None;
    let mut 体内圆括号 = 0u32;
    let mut 体内尖括号 = 0u32;
    let mut 体内方括号 = 0u32;
    let mut 函数头态 = 0u32;
    let mut 函数尖括号 = 0u32;
    let mut 圆括号深度 = 0u32;
    let mut 位于参数起点 = false;
    let mut 待定参数: Option<String> = None;
    let mut 在闭包内 = false;
    let mut 闭包圆括号 = 0u32;
    let mut 闭包起点 = false;
    let mut 前为值结尾 = false;
    let mut 上个或号结尾 = usize::MAX;
    // —— 二：实现块（库特征判定延后到扫完之后）——
    // 实现块可以出现在目标类型声明之前，故不能边扫边按 `条目集` 判定；
    // 先把每块的（目标名, 块内函数名）记下，扫完后统一判定。
    // 名字用源码切片，不分配。
    let mut 实现头态 = false;
    let mut 实现目标: Option<&'甲 str> = None;
    let mut 实现块号: Option<usize> = None;
    let mut 实现尖括号 = 0u32;
    let mut 实现花括号 = 0u32;
    let mut 前一为函数 = false;
    let mut 实现块们: Vec<(&'甲 str, Vec<&'甲 str>)> = Vec::new();
    // —— 三：模式绑定 ——
    let mut 在让态 = false;
    let mut 让深度 = 0u32;
    let mut 在循环态 = false;
    let mut 循环深度 = 0u32;
    let mut 循环待定: Vec<&'甲 str> = Vec::new();
    let mut 在实现头内 = false;
    // 模式绑定单独暂存：库特征方法名的剔除只作用于声明位收集结果，
    // 旧实现是「先剔除、再把模式绑定并入变量集」，此处保持同一顺序
    let mut 绑定集: HashSet<String> = HashSet::new();
    let mut 偏移 = 0usize;
    for 序号 in 0..词元序列.len() {
        let 当前类别 = 词元序列[序号].kind;
        let 文本响应 = &原因[偏移..偏移 + 词元序列[序号].len];
        match 当前类别 {
            TokenKind::Ident => {
                // —— 一：类型头推进（结构体/枚举后第一个标识符是类型名）——
                if 文本响应 == "struct" {
                    待定类型 = Some((false, false));
                } else if 文本响应 == "enum" {
                    待定类型 = Some((true, false));
                } else if let Some((_, 已见)) = &mut 待定类型
                    && !*已见
                    && 文本响应 != "pub"
                {
                    *已见 = true;
                }
                // —— 一：类型体成员收集 ——
                if let Some(请求体) = &mut 类型体
                    && 体内圆括号 == 0
                    && 体内尖括号 == 0
                    && 体内方括号 == 0
                    && 请求体.位于起点
                    && 文本响应 != "pub"
                {
                    if 请求体.为枚举体 && 请求体.深度 == 1 {
                        声明累计.条目集.insert(文本响应.to_string());
                    } else {
                        请求体.待定成员 = Some(文本响应.to_string());
                    }
                    请求体.位于起点 = false;
                }
                // —— 一：声明位 ——
                if let Some(关键字值) = 前一关键字 {
                    if 变量声明关键字表.contains(&关键字值) {
                        声明累计.变量集.insert(文本响应.to_string());
                    } else {
                        声明累计.条目集.insert(文本响应.to_string());
                    }
                }
                前一关键字 = 下一声明关键字(前一关键字, 文本响应);
                // —— 一：函数参数名 ——
                if 函数头态 == 2 && 圆括号深度 == 1 && 位于参数起点 && 文本响应 != "mut"
                {
                    待定参数 = Some(文本响应.to_string());
                    位于参数起点 = false;
                }
                if 函数头态 == 0 && 文本响应 == "fn" {
                    函数头态 = 1;
                    函数尖括号 = 0;
                }
                // —— 一：闭包参数名 ——
                if 在闭包内 && 闭包圆括号 == 0 && 闭包起点 && 文本响应 != "mut" {
                    声明累计.变量集.insert(文本响应.to_string());
                    闭包起点 = false;
                }
                前为值结尾 = 文本响应 != "move";

                // —— 二：实现块 ——
                if let Some(块号) = 实现块号 {
                    // 块体内的函数名：紧跟在「函数」关键字之后的标识符
                    if 前一为函数 {
                        实现块们[块号].1.push(文本响应);
                    }
                } else if 实现头态 {
                    // `<...>` 泛型参数里的名字不是实现目标
                    if 实现尖括号 == 0 {
                        实现头态 = false;
                        实现目标 = Some(文本响应);
                    }
                } else if 实现目标.is_none() && 文本响应 == "impl" {
                    实现头态 = true;
                    实现尖括号 = 0;
                }
                前一为函数 = 文本响应 == "fn";

                // —— 三：模式绑定 ——
                if 文本响应 == "impl" {
                    在实现头内 = true;
                }
                if 在循环态 {
                    if 文本响应 == "in" && 循环深度 == 0 {
                        // 模式结束：提交挂起绑定
                        绑定集.extend(循环待定.drain(..).map(str::to_string));
                        在循环态 = false;
                    } else if 循环深度 == 0
                        && (文本响应 == "for" || 语句边界关键字表.contains(&文本响应))
                    {
                        // 遇嵌套循环重启挂起；遇声明/语句关键字丢弃挂起
                        循环待定.clear();
                        在循环态 = 文本响应 == "for";
                        循环深度 = 0;
                    } else if 是模式绑定(词元序列, 序号, 文本响应) {
                        循环待定.push(文本响应);
                    }
                } else if 文本响应 == "for" && !在实现头内 {
                    在循环态 = true;
                    循环深度 = 0;
                    循环待定.clear();
                }
                if 在让态 && 让深度 > 0 && 是模式绑定(词元序列, 序号, 文本响应)
                {
                    绑定集.insert(文本响应.to_string());
                }
                if 文本响应 == "let" {
                    在让态 = true;
                    让深度 = 0;
                }
            }
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            TokenKind::OpenParen => {
                前一关键字 = None;
                if 类型体.is_some() {
                    体内圆括号 += 1;
                }
                if 函数头态 == 1 && 函数尖括号 == 0 {
                    函数头态 = 2;
                    圆括号深度 = 1;
                    位于参数起点 = true;
                } else if 函数头态 == 2 {
                    圆括号深度 += 1;
                    位于参数起点 = false;
                }
                if 在闭包内 {
                    闭包圆括号 += 1;
                    闭包起点 = false;
                }
                待定参数 = None;
                前为值结尾 = false;
                前一为函数 = false;
                if 在让态 {
                    让深度 += 1;
                }
                if 在循环态 {
                    循环深度 += 1;
                }
            }
            TokenKind::CloseParen => {
                前一关键字 = None;
                if 类型体.is_some() {
                    体内圆括号 = 体内圆括号.saturating_sub(1);
                }
                if 函数头态 == 2 {
                    圆括号深度 = 圆括号深度.saturating_sub(1);
                    if 圆括号深度 == 0 {
                        函数头态 = 0;
                    }
                    位于参数起点 = false;
                }
                if 在闭包内 {
                    闭包圆括号 = 闭包圆括号.saturating_sub(1);
                    闭包起点 = false;
                }
                待定参数 = None;
                前为值结尾 = true;
                前一为函数 = false;
                让深度 = 让深度.saturating_sub(1);
                循环深度 = 循环深度.saturating_sub(1);
            }
            TokenKind::Comma => {
                前一关键字 = None;
                if 函数头态 == 2 && 圆括号深度 == 1 {
                    位于参数起点 = true;
                }
                if 在闭包内 && 闭包圆括号 == 0 {
                    闭包起点 = true;
                }
                // 类型体成员分隔：重置成员开始位（括号/尖括号/方括号内的
                // 逗号是类型参数分隔，不是成员分隔）
                if 体内圆括号 == 0
                    && 体内尖括号 == 0
                    && 体内方括号 == 0
                    && let Some(请求体) = &mut 类型体
                {
                    请求体.位于起点 = true;
                    请求体.待定成员 = None;
                }
                待定参数 = None;
                前为值结尾 = false;
                前一为函数 = false;
            }
            TokenKind::Colon => {
                前一关键字 = None;
                // `名:` → 确认函数参数绑定（其他位置不会有待确认候选）
                if let Some(名字值) = 待定参数.take() {
                    声明累计.变量集.insert(名字值);
                }
                // `字段:` → 确认结构体字段名
                if let Some(请求体) = &mut 类型体
                    && let Some(名字值) = 请求体.待定成员.take()
                {
                    声明累计.成员集.insert(名字值);
                }
                前为值结尾 = false;
                前一为函数 = false;
                // `让 名: 类型` 的 `:` 是类型标注分隔——其后是类型，不再是
                // 模式绑定；`::` 是路径分隔（两个相邻冒号），不结束让态
                if 在让态
                    && 让深度 == 0
                    && !前有效下标(词元序列, 序号)
                        .is_some_and(|前下标| 词元序列[前下标].kind == TokenKind::Colon)
                    && !后有效下标(词元序列, 序号)
                        .is_some_and(|后下标| 词元序列[后下标].kind == TokenKind::Colon)
                {
                    在让态 = false;
                    让深度 = 0;
                }
                // 循环模式里 `:` 不合法（类型标注等非循环场景，防御）
                if 在循环态 && 循环深度 == 0 {
                    循环待定.clear();
                    在循环态 = false;
                }
            }
            TokenKind::Or => {
                前一关键字 = None;
                if 在闭包内 {
                    if 闭包圆括号 == 0 {
                        在闭包内 = false;
                    }
                } else if !前为值结尾 && 上个或号结尾 != 偏移 {
                    // 前一个有效词元不是表达式结尾，且不与上一个 `|`
                    // 相邻（`a || b` 是连续两个 `|` 词元）→ 闭包起始
                    在闭包内 = true;
                    闭包圆括号 = 0;
                    闭包起点 = true;
                }
                上个或号结尾 = 偏移 + 词元序列[序号].len;
                待定参数 = None;
                前为值结尾 = false;
                前一为函数 = false;
            }
            TokenKind::Lt => {
                前一关键字 = None;
                if 函数头态 == 1 {
                    函数尖括号 += 1;
                }
                if 类型体.is_some() {
                    体内尖括号 += 1;
                }
                待定参数 = None;
                前为值结尾 = false;
                if 实现头态 {
                    实现尖括号 += 1;
                }
                前一为函数 = false;
                // 循环模式里 `<` 不合法（泛型等非循环场景，防御）
                if 在循环态 && 循环深度 == 0 {
                    循环待定.clear();
                    在循环态 = false;
                }
            }
            TokenKind::Gt => {
                前一关键字 = None;
                if 函数头态 == 1 {
                    函数尖括号 = 函数尖括号.saturating_sub(1);
                }
                if 类型体.is_some() {
                    体内尖括号 = 体内尖括号.saturating_sub(1);
                }
                待定参数 = None;
                前为值结尾 = false;
                if 实现头态 {
                    实现尖括号 = 实现尖括号.saturating_sub(1);
                }
                前一为函数 = false;
                // `=>`（相等 + 大于号相邻两词元）：匹配臂箭头 → 回溯收集
                if let Some(前下标) = 前有效下标(词元序列, 序号)
                    && 词元序列[前下标].kind == TokenKind::Eq
                    && 前下标 == 序号 - 1
                {
                    收集匹配臂绑定(词元序列, 偏移, 序号, 原因, &mut 绑定集);
                }
            }
            TokenKind::OpenBrace => {
                // `结构体/枚举 名 {` → 进入类型体成员扫描
                if let Some((为枚举体, 已见)) = 待定类型.take() {
                    if 已见 {
                        类型体 = Some(类型体扫描 {
                            为枚举体,
                            深度: 1,
                            位于起点: true,
                            待定成员: None,
                        });
                        体内圆括号 = 0;
                        体内尖括号 = 0;
                        体内方括号 = 0;
                    }
                } else if 类型体.is_some()
                    && 体内圆括号 == 0
                    && 体内尖括号 == 0
                    && 体内方括号 == 0
                    && let Some(请求体) = &mut 类型体
                {
                    请求体.深度 += 1;
                    请求体.位于起点 = true;
                    请求体.待定成员 = None;
                }
                前一关键字 = None;
                待定参数 = None;
                前为值结尾 = false;
                // `实现 目标 {` → 进入块体；体内嵌套花括号加深一层
                if let Some(块目标) = 实现目标.take() {
                    实现块们.push((块目标, Vec::new()));
                    实现块号 = Some(实现块们.len() - 1);
                    实现花括号 = 0;
                } else if 实现块号.is_some() {
                    实现花括号 += 1;
                } else {
                    // `实现 {`：非法写法，放弃跟踪
                    实现头态 = false;
                }
                前一为函数 = false;
                // 实现头部结束（进入块体）
                在实现头内 = false;
                if 在让态 {
                    让深度 += 1;
                }
                if 在循环态 {
                    循环深度 += 1;
                }
            }
            TokenKind::CloseBrace => {
                // 类型体闭合：深度归零退出扫描（括号/尖括号/方括号内的
                // 花括号不是类型体边界）
                if 体内圆括号 == 0 && 体内尖括号 == 0 && 体内方括号 == 0 {
                    let 已退出 = if let Some(请求体) = &mut 类型体 {
                        请求体.深度 = 请求体.深度.saturating_sub(1);
                        if 请求体.深度 == 0 {
                            true
                        } else {
                            请求体.位于起点 = true;
                            请求体.待定成员 = None;
                            false
                        }
                    } else {
                        false
                    };
                    if 已退出 {
                        类型体 = None;
                    }
                }
                前一关键字 = None;
                待定参数 = None;
                前为值结尾 = true;
                // 实现块体闭合：嵌套深度归零时退出追踪
                if 实现块号.is_some() {
                    if 实现花括号 == 0 {
                        实现块号 = None;
                    } else {
                        实现花括号 -= 1;
                    }
                }
                前一为函数 = false;
                让深度 = 让深度.saturating_sub(1);
                循环深度 = 循环深度.saturating_sub(1);
            }
            TokenKind::OpenBracket => {
                // 方括号内的标识符不参与成员收集（属性、数组类型 `[T; N]`）
                if 类型体.is_some() {
                    体内方括号 += 1;
                }
                前一关键字 = None;
                待定参数 = None;
                前为值结尾 = false;
                前一为函数 = false;
                if 在让态 {
                    让深度 += 1;
                }
                if 在循环态 {
                    循环深度 += 1;
                }
            }
            TokenKind::CloseBracket => {
                if 类型体.is_some() {
                    体内方括号 = 体内方括号.saturating_sub(1);
                }
                前一关键字 = None;
                待定参数 = None;
                前为值结尾 = true;
                前一为函数 = false;
                让深度 = 让深度.saturating_sub(1);
                循环深度 = 循环深度.saturating_sub(1);
            }
            _ => {
                前一关键字 = None;
                待定参数 = None;
                if matches!(当前类别, TokenKind::Semi) {
                    // `结构体/枚举 名;`（单元结构体）：放弃类型体等待
                    待定类型 = None;
                    // 语句边界：清空全部模式状态
                    在实现头内 = false;
                    在让态 = false;
                    让深度 = 0;
                    循环待定.clear();
                    在循环态 = false;
                    循环深度 = 0;
                } else if matches!(当前类别, TokenKind::Eq) {
                    // `让 模式 =`：模式结束（`=` 之后是表达式）
                    if 在让态 && 让深度 == 0 {
                        在让态 = false;
                    }
                    // 循环模式里 `=` 不合法（防御）
                    if 在循环态 && 循环深度 == 0 {
                        循环待定.clear();
                        在循环态 = false;
                    }
                }
                前为值结尾 = matches!(
                    当前类别,
                    TokenKind::Literal { .. }
                        | TokenKind::CloseBracket
                        | TokenKind::CloseBrace
                        | TokenKind::Question
                );
                前一为函数 = false;
            }
        }
        偏移 += 词元序列[序号].len;
    }
    // 库特征实现块：目标名既不是用户项、又在别名映射表中 → 块内方法名是库 API
    //（判定用扫完后的完整条目集；先全部判定再统一剔除，与旧实现两阶段一致）
    let mut 库方法名: Vec<&str> = Vec::new();
    for (块目标, 方法们) in &实现块们 {
        if 声明累计.条目集.contains(*块目标) || !别名映射.contains_key(*块目标) {
            continue;
        }
        库方法名.extend(方法们.iter().copied());
    }
    for 方法 in 库方法名 {
        声明累计.库方法集.insert(方法.to_string());
        声明累计.条目集.remove(方法);
        声明累计.变量集.remove(方法);
    }
    // 模式绑定最后并入：旧实现顺序为「先剔除库方法名、再并入模式绑定」
    声明累计.变量集.extend(绑定集);
    声明累计
}

/// 推进声明关键字状态：「可变」透明传递，其余按是否声明关键字更新
fn 下一声明关键字<'甲>(
    前一关键字: Option<&'甲 str>,
    文本响应: &'甲 str,
) -> Option<&'甲 str> {
    if 文本响应 == "mut" {
        return 前一关键字;
    }
    声明关键字表
        .iter()
        .find(|&&关键字值| 关键字值 == 文本响应)
        .copied()
}

/// 循环模式挂起中出现的「非模式词」：声明/语句关键字
///
/// 真模式里不可能出现这些词，出现即说明挂起跨越了语句边界
/// （残留/剥离代码），须丢弃挂起，避免把后续代码里的名字误收为绑定。
const 语句边界关键字表: &[&str] = &[
    "fn", "struct", "enum", "impl", "trait", "mod", "type", "const", "static", "let", "use", "pub",
    "return", "if", "else", "while", "loop", "match", "break", "continue", "unsafe", "async",
    "await", "move", "where",
];

/// `=>` 回溯：收集匹配臂模式中的绑定名
///
/// 从箭头（索引 `箭头下标`，起点偏移 `箭头偏移`）向左回溯到臂起点
/// （深度 0 的 `,`/`{`/`;`），区间内标识符经 [`是模式绑定`]
/// 过滤后收为值绑定。`{}`/`()`/`[]` 深度配对处理结构体模式
/// （`点 { x, y }`）与嵌套模式。
///
/// 越界防护（weix-1 #27）：带块臂体（`=> { … }`）的**下一臂**回溯时
/// 会先遇到上一臂的块闭合 `}`；若不识别，深度失衡后 `,`/`;` 不再
/// 终止，回溯将穿透上一臂语句，把类型标注（`让 x: T = …` 的 `T`）
/// 等裸标识符误收为值绑定 → 其全文件豁免替换（`无符号机器整数`
/// 的映射目标实测不被翻译，产物 E0425）。块体臂的逗号可省略，其闭合
/// `}` 即当前臂模式的左边界：识别后立即截止
/// （见 [`闭花括号结束臂体`]）。
fn 收集匹配臂绑定(
    词元序列: &[rustc_lexer::Token],
    箭头偏移: usize,
    箭头下标: usize,
    原因: &str,
    绑定集: &mut HashSet<String>,
) {
    // 箭头前一个有意义词元是 `=`（调用方已确认 `=>` 相邻）
    let Some(等号下标) = 前有效下标(词元序列, 箭头下标) else {
        return;
    };
    let mut 深度 = 0u32;
    // 反向累计各词元的起点偏移（切分令牌连续覆盖全源）
    let mut 起点 = 箭头偏移.saturating_sub(词元序列[等号下标].len);
    for 下标 in (0..等号下标).rev() {
        起点 = 起点.saturating_sub(词元序列[下标].len);
        let 当前类别 = 词元序列[下标].kind;
        match 当前类别 {
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            TokenKind::CloseParen | TokenKind::CloseBracket => 深度 += 1,
            TokenKind::CloseBrace => {
                // 上一臂块体闭合即当前臂模式左边界：就此截止，
                // 不得穿入上一臂体（见函数文档「越界防护」）
                if 深度 == 0 && 闭花括号结束臂体(词元序列, 下标) {
                    break;
                }
                深度 += 1;
            }
            TokenKind::OpenParen | TokenKind::OpenBracket => {
                if 深度 == 0 {
                    break; // 模式区间外的括号（异常输入）：保守停止
                }
                深度 -= 1;
            }
            TokenKind::OpenBrace => {
                if 深度 == 0 {
                    break; // 匹配体（或宏体）的起点
                }
                深度 -= 1;
            }
            TokenKind::Comma | TokenKind::Semi => {
                if 深度 == 0 {
                    break; // 上一臂的分隔或语句边界
                }
            }
            TokenKind::Ident => {
                let 文本响应 = &原因[起点..起点 + 词元序列[下标].len];
                if 是模式绑定(词元序列, 下标, 文本响应) {
                    绑定集.insert(文本响应.to_string());
                }
            }
            _ => {}
        }
    }
}

/// `}`（索引 `闭合下标`）是否为「臂块体闭合」（`=> { … }` 的收尾）
///
/// 判定：向左找配对的 `{`，其前一个有意义词元是 `=>` 的 `>`（相等与大于号
/// 相邻）则为臂体闭合。结构体模式的 `}`（配对 `{` 前是路径名，如
/// `点 { x }`、`点<T> { x }`）返回假，照常参与深度配对。
fn 闭花括号结束臂体(词元序列: &[rustc_lexer::Token], 闭合下标: usize) -> bool {
    let mut 深度 = 0u32;
    let mut 游标 = 闭合下标;
    while 游标 > 0 {
        游标 -= 1;
        match 词元序列[游标].kind {
            TokenKind::CloseBrace => 深度 += 1,
            TokenKind::OpenBrace => {
                if 深度 == 0 {
                    // 配对 `{`：前一个有意义词元是 `=>` 的 `>`？
                    return 前有效下标(词元序列, 游标).is_some_and(|前下标| {
                        词元序列[前下标].kind == TokenKind::Gt
                            && 前有效下标(词元序列, 前下标).is_some_and(|再前下标| {
                                词元序列[再前下标].kind == TokenKind::Eq && 再前下标 == 前下标 - 1
                            })
                    });
                }
                深度 -= 1;
            }
            _ => {}
        }
    }
    false
}

/// 模式内标识符的「值绑定」判定
///
/// 「可变」/「引用」修饰符不是名字；`::` 路径段（变体/常量路径）、后跟
/// `(`/`{`/`[` 的构造路径（`有值(…)`、`点 { … }`）、后跟 `:` 的
/// 字段名（`x: 甲` 的 `x`，兼作 `::` 前段判定）都不是绑定。
fn 是模式绑定(词元序列: &[rustc_lexer::Token], 序号: usize, 文本响应: &str) -> bool {
    if 文本响应 == "mut" || 文本响应 == "ref" {
        return false;
    }
    if let Some(后下标) = 后有效下标(词元序列, 序号) {
        match 词元序列[后下标].kind {
            TokenKind::Colon
            | TokenKind::OpenParen
            | TokenKind::OpenBrace
            | TokenKind::OpenBracket => return false,
            _ => {}
        }
    }
    // 前是 `::` 后段（前两个有意义词元都是冒号）→ 路径段，不是绑定
    if let Some(前下标) = 前有效下标(词元序列, 序号)
        && 词元序列[前下标].kind == TokenKind::Colon
        && let Some(再前下标) = 前有效下标(词元序列, 前下标)
        && 词元序列[再前下标].kind == TokenKind::Colon
    {
        return false;
    }
    true
}

/// 序号之前（不含序号）第一个有意义词元的下标（跳过空白/注释）
fn 前有效下标(词元序列: &[rustc_lexer::Token], 序号: usize) -> Option<usize> {
    词元序列[..序号]
        .iter()
        .rposition(|词元| !是琐碎词元(词元.kind))
}

/// 序号之后（不含序号）第一个有意义词元的下标（跳过空白/注释）
fn 后有效下标(词元序列: &[rustc_lexer::Token], 序号: usize) -> Option<usize> {
    词元序列[序号 + 1..]
        .iter()
        .position(|词元| !是琐碎词元(词元.kind))
        .map(|位置| 位置 + 序号 + 1)
}

/// 空白/注释（琐碎词元）：不参与相邻性判断
fn 是琐碎词元(当前类别: TokenKind) -> bool {
    matches!(
        当前类别,
        TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
    )
}
/// 将源码中的中文别名替换为英文标识符（仅替换标识符词元）
///
/// 输入应为已完成关键字转译的代码（声明关键字已是英文形式）。
/// 声明位的标识符（如 `函数 绝对值()`、`让 字符串 = 1`）保留原样，
/// 且这些用户声明名在文件内的使用处也不替换；`::` 限定后的路径段
/// 仅对「变量名」不豁免（如 `字符串::新建` 里的 `新建` 是库 API，
/// 照常替换），用户声明的项可经 `::` 访问（`接口错误::错误请求`），
/// 仍豁免。库特征实现块内的方法名是库 API 名称，照常替换（见模块文档）。
///
/// # 参数
/// - `原因`: 待替换的源码字符串
/// - `别名映射表`: 中文别名 → 英文原名 的映射表
///
/// # 返回
/// 替换后的源码字符串
pub fn 替换别名(原因: &str, 别名映射: &HashMap<String, String>) -> String {
    带映射替换别名(原因, 别名映射).输出文本
}

/// 同 [`替换别名`]，同时产出编辑表（本阶段输入坐标）
pub fn 带映射替换别名(原因: &str, 别名映射: &HashMap<String, String>) -> 替换结果 {
    带上下文替换别名(原因, 别名映射, None)
}

/// 同 [`带映射替换别名`]，附项目级声明上下文（跨文件声明豁免）
///
/// `项目` 为 `无` 时行为与 [`带映射替换别名`] 完全一致。
/// 提供上下文时在逐文件豁免之上额外豁免：
/// - 项目声明名（含其他文件声明的项/结构体字段）的裸使用处；
/// - 项目模块名的裸使用处；
/// - 以包根、父级、自身、项目模块名、项目项名为根的 `::` 路径链：
///   链内**与项目声明名同名**的段豁免（`包::平台Linux::Linux内存源::新建`
///   ——跨文件引用成员与声明侧一致，避免 E0599）；链内非项目名
///   （`源码映射项::新建` 的 `新建` 未定义于项目）照常替换。
///   `::` 后非项目根的段（`盒子::新建`）同样照常替换：`新建` 是库 API。
pub fn 带上下文替换别名(
    原因: &str,
    别名映射: &HashMap<String, String>,
    项目: Option<&项目上下文>,
) -> 替换结果 {
    带上下文与模块路径替换别名(原因, 别名映射, &HashMap::new(), 项目)
}

/// 别名阶段的名字级事实：一次解出主循环要问的那几张表的答案
///
/// 主循环对每个标识符都要查别名表、判定项目路径根（`模块集`/`条目集` 两次
/// 哈希查找）、推进声明关键字状态（`声明关键字表` 线性扫）。这三件事只取决于
/// 名字本身，因此按名字直映缓存（见 [`包::名字缓存`]）：同名重复出现时
/// 只付一次探测。模块路径表**不在**缓存内——它只在路径根位（后跟 `::`）才
/// 需要，而路径根位是少数，无条件预查反而会为每个标识符多搭一次随机访存。
#[derive(Clone, Copy)]
struct 别名事实<'甲> {
    /// 别名表命中值
    别名值: Option<&'甲 str>,
    /// 项目路径根（包根、父级、自身、项目模块名、项目项名）；无项目上下文时恒假
    路径根: bool,
    /// 声明位关键字（「可变」除外：它的透明传递由调用处按上一个状态处理）
    声明关键字: Option<&'甲 str>,
}

/// 同 [`带上下文替换别名`]，附模块路径表（导入语句之外的模块前缀转译）
///
/// 管线的「模块路径替换」阶段只处理导入语句；表达式与属性位置的
/// `模块词::项`（`异步运行时::睡眠`、`#[异步运行时::主函数]`）在本函数内
/// 回退模块路径表完成（office-zb #10/#18：此前「模块词」保留、「项」被
/// 别名替换，产物 `异步运行时::主函数` 报 E0433）。回退规则：
/// - 仅**路径根位置**（后跟 `::`、且前不是 `::` 的段）触发；
/// - 别名表命中优先——标识符语义覆盖模块语义（`路径::新建` 的 `路径`
///   是 `Path` 而非 `path` 模块）；
/// - 路径根位上的字段/变量名豁免不适用（见 `使用处豁免` 的根位分支）；
/// - 替换值做包名连字符规范化（`-` → `_`）。
pub fn 带上下文与模块路径替换别名(
    原因: &str,
    别名映射: &HashMap<String, String>,
    模块路径映射: &HashMap<String, String>,
    项目: Option<&项目上下文>,
) -> 替换结果 {
    按声明替换别名(原因, 别名映射, 模块路径映射, 项目, None)
}

/// 同 [`带上下文与模块路径替换别名`]，但可复用调用方已收集好的声明名
///
/// 延迟项目上下文的管线入口必须在别名阶段之前先拿到本文件声明才能建项目
/// 上下文，而它拿到的声明是从**词法产物**收集的；本阶段的输入则是
/// 「词法 → 导入路径 → `包::` 前缀」之后的文本。两处的声明集合相同（后续
/// 两个阶段只改导入路径段与路径根位前缀，既不动声明关键字也不动声明位
/// 名字），因此可省掉本阶段内部那趟声明状态机（分词仍要为替换主循环付，
/// 省不掉）——359 行样例上该状态机 47.3 µs，占管线约 9%，现场收集整趟
/// （含分词）则占 ~21%。
///
/// 等价性由 `tests/alias_declared_reuse.rs` 的差分测试锁定：两条入口对同一
/// 语料的输出文本与编辑表逐字段一致。`已声明集合` 为 `无` 时行为与原入口相同。
pub fn 按声明替换别名(
    原因: &str,
    别名映射: &HashMap<String, String>,
    模块路径映射: &HashMap<String, String>,
    项目: Option<&项目上下文>,
    已声明集合: Option<&已声明名集合>,
) -> 替换结果 {
    复用替换别名(原因, 别名映射, 模块路径映射, 项目, 已声明集合, None)
}

/// [`按声明替换别名`] 的实现，另可复用调用方已分好的词元流
///
/// `词元序列` 必须与 `原因` 同一份文本（同一序列）。管线里本阶段的输入是
/// 「词法 → 导入路径」之后的文本，那份词元流可由「词法产物的词元 + 导入路径
/// 阶段各编辑的新长度」派生（见「派生词元序列」），省掉整份重新分词——
/// 359 行样例上该分词 46~72 µs，占管线一成上下。
pub(crate) fn 复用替换别名<'甲>(
    原因: &'甲 str,
    别名映射: &'甲 HashMap<String, String>,
    模块路径映射: &'甲 HashMap<String, String>,
    项目: Option<&'甲 项目上下文>,
    已声明集合: Option<&'甲 已声明名集合>,
    词元选项: Option<&'甲 [rustc_lexer::Token]>,
) -> 替换结果 {
    // 映射表为空时直接返回，避免不必要的词法分析开销
    if 别名映射.is_empty() && 模块路径映射.is_empty() {
        return 替换结果 {
            输出文本: 原因.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 词元序列只解析一次：候选位预扫、声明名收集与替换主循环共享（`.方法()`
    // 判定需向后看一位——下一个有意义词元是否为 `(`，字段访问 `实例.字段`
    // 与方法调用 `实例.方法()` 的豁免集合不同）。调用方已分好词时直接借用
    let 自持词元: Vec<rustc_lexer::Token>;
    let 词元序列: &[rustc_lexer::Token] = match 词元选项 {
        Some(词元流) => 词元流,
        None => {
            自持词元 = crate::收集令牌(原因);
            &自持词元
        }
    };
    // 候选位预扫：整份源码没有任何替换候选（别名表命中 / 路径根位命中模块
    // 路径表）时直接原样返回。真实语料 1192 份里 774 份属于这一类，此前照旧
    // 付「声明名收集 + 逐位置豁免判定」两趟（该阶段 6.1 ms 里的 4.2 ms）
    if !有替换候选(词元序列, 原因, 别名映射, 模块路径映射) {
        return 替换结果 {
            输出文本: 原因.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 第一遍：收集用户声明名与库特征方法名（使用处豁免见已声明名集合）。
    // 调用方已收集好时直接借用，未收集时才现场走状态机
    let 自持声明: 已声明名集合;
    let 已声明: &已声明名集合 = match 已声明集合 {
        Some(声明实例) => 声明实例,
        None => {
            自持声明 = 在文本中收集声明名(原因, 别名映射, 词元序列);
            &自持声明
        }
    };
    // 名字级事实缓存（见 [`别名事实`]）：按名字直映
    let mut 名字缓存实例: 名字缓存<'_, 别名事实<'_>> = 名字缓存::新建();
    // 单个冒号跟踪：词法器把 `::` 拆成两个冒号词元
    let mut 上一为冒号 = false;
    // 输出只在替换点刷出：未命中的词元不逐个推入，替换时才把
    // 「上次刷出位置 → 本词元起点」的原始片段整段拷过去。2000 行样例
    // 有 1.5 万个词元、替换点只有几十个，逐词元复制是纯开销
    let mut 输出文本 = String::with_capacity(原因.len());
    let mut 拷贝游标 = 0usize;
    let mut 编辑表 = Vec::new();
    let mut 当前偏移 = 0;
    // 上一个有意义词元若是声明关键字，记录其文本（「可变」透明传递）；
    // 空白/注释不重置该状态
    let mut 前一关键字: Option<&'甲 str> = None;
    // 上一个有意义词元是否为 `::`（两个连续冒号词元的第二个）
    let mut 前一为路径分隔 = false;
    // 上一个有意义词元是否为 `.`（成员访问/方法链）
    let mut 前一为圆点 = false;
    // —— 项目路径链跟踪（仅项目为有值时生效）——
    // 待定项目根：上一标识符是项目根候选（包根/模块名/项名），
    // 等待 `::` 确认；在项目路径内：根段已确认，链内段按项目声明名豁免
    let mut 待定项目根 = false;
    let mut 在项目路径内 = false;

    for (序号, 词元) in 词元序列.iter().enumerate() {
        let 词元长度 = 词元.len;
        let 文本响应 = &原因[当前偏移..当前偏移 + 词元长度];
        match 词元.kind {
            TokenKind::Ident => {
                // 替换候选先行判定：别名表命中，或处于路径根位且模块路径表命中。
                // 两者皆无时是否豁免不影响输出（豁免只决定要不要替换），直接原样
                // 输出：大文件里绝大多数标识符走这条快路，省掉 5 次豁免哈希查找
                let 事实 = 名字缓存实例.取或解析(文本响应, || 别名事实 {
                    别名值: 别名映射.get(文本响应).map(String::as_str),
                    路径根: 项目.is_some_and(|项目引用| 项目引用.是路径根(文本响应)),
                    声明关键字: 声明关键字表
                        .iter()
                        .find(|&&关键字值| 关键字值 == 文本响应)
                        .copied(),
                });
                let 别名命中 = 事实.别名值;
                let 是路径头候选 = !前一为路径分隔 && 后有效为路径分隔(词元序列, 序号);
                // 模块路径表只在路径根位查一次（命中判定与取值共用同一次查找）
                let 模块命中 = if 是路径头候选 {
                    模块路径映射.get(文本响应).map(String::as_str)
                } else {
                    None
                };
                // 项目路径链状态必须无条件推进（链内段的豁免判定依赖它，与当前
                // 标识符是否有替换候选无关）；根段确认依赖上一标识符留存的候选
                // 标记与当前 `::` 状态
                let 在项目链内 =
                    项目.is_some() && (在项目路径内 || (待定项目根 && 前一为路径分隔));
                if 在项目链内 {
                    在项目路径内 = true;
                }
                if 别名命中.is_some() || 模块命中.is_some() {
                    // `.方法()` 位：`.` 后的标识符且下一个有意义词元是 `(`
                    //（字段名不是方法名，豁免集合见下方使用处豁免）
                    let 于方法位 = 前一为圆点 && 后有效为左括号(词元序列, 序号);
                    // 路径根位置（首段）：后跟 `::` 且前不是 `::` 的标识符——
                    // `模块词::项` 的首段。字段/变量不可经 `::` 访问，根位豁免
                    // 不适用（office-zb #27）；模块词回退替换亦仅限根位
                    let 于路径头 = 是路径头候选;
                    // 声明位保护：紧随声明关键字的名字是用户自己的定义；
                    // 例外——库特征实现块内「函数」关键字后的方法名是库 API 名称
                    //（见「库特征实现方法收集」），照常参与替换
                    let 声明受保护 = 前一关键字.is_some()
                        && !(前一关键字 == Some("fn") && 已声明.库方法集.contains(文本响应));
                    // 各位置豁免集合：
                    // - 链内：仅项目声明名（项/模块）——`平台Linux::新建` 豁免，
                    //   未定义于项目的 `源码映射项::新建` 照常替换（与教程
                    //   `fn new` 定义侧一致）；
                    // - `::` 后非链（根非项目根）：无项目上下文时保留旧行为
                    //   （本文件项名豁免，`接口错误::错误请求`）；有上下文时
                    //   一律按库 API 替换（`盒子::新建` 的同名项目项不得误伤）；
                    // - `.方法()` 位：仅项目方法名（项集合）——`编辑表.长度()`
                    //   的 `长度` 是 `向量::长度` 调用，字段名豁免不适用于方法位；
                    // - 其他：本文件声明名 + 项目裸使用处豁免（含结构体字段）
                    let 使用处豁免 = if 在项目链内 {
                        已声明.条目集.contains(文本响应)
                            || 项目.is_some_and(|项目引用| {
                                项目引用.条目集.contains(文本响应)
                                    || 项目引用.模块集.contains(文本响应)
                            })
                    } else if 前一为路径分隔 {
                        项目.is_none() && 已声明.条目集.contains(文本响应)
                    } else if 于方法位 {
                        已声明.条目集.contains(文本响应)
                            || 项目.is_some_and(|项目引用| 项目引用.条目集.contains(文本响应))
                    } else if 于路径头 {
                        // 路径根位（后跟 `::`）：字段/变量/裸名豁免不适用——它们
                        // 不可经 `::` 访问。缺陷回归（office-zb #27 字段场景）：
                        // 字段名与词表词撞名（如「天数」词条）时，`天数::新建`
                        // 曾因字段豁免保留「天数」、只替换段位 → `天数::new`
                        // 报 E0433；字面量/字段访问位等非根位仍按字段豁免。
                        // 仅本文件项名与项目项名/模块名（路径链根）在根位豁免
                        已声明.条目集.contains(文本响应) || 事实.路径根
                    } else {
                        已声明.条目集.contains(文本响应)
                            || 已声明.变量集.contains(文本响应)
                            || 已声明.成员集.contains(文本响应)
                            // 项目声明名（项+字段，含其他文件声明）与项目根词
                            //（模块名；包根/父级/自身为英文，替换表不会命中，
                            // 在此仅作为路径链起点）
                            || 项目.is_some_and(|项目引用| 项目引用.裸使用豁免(文本响应))
                            || 事实.路径根
                    };
                    // 声明位标识符与用户声明名的使用处保留原样（随片段拷出）
                    if !声明受保护 && !使用处豁免 {
                        if let Some(英文名) = 别名命中 {
                            编辑表.push(源码映射条目::新建(
                                当前偏移,
                                词元长度,
                                文本响应,
                                英文名,
                            ));
                            输出文本.push_str(&原因[拷贝游标..当前偏移]);
                            输出文本.push_str(英文名);
                            拷贝游标 = 当前偏移 + 词元长度;
                        } else if let Some(英文名) = 模块命中 {
                            // 路径根位回退模块路径表：`异步运行时::睡眠` → `tokio::sleep`、
                            // `#[异步运行时::主函数]` → `#[tokio::main]`（office-zb #10/#18）。
                            // 导入语句内已在管线模块路径阶段替换，此处覆盖表达式/属性位置
                            let 规范化值 = crate::模块路径::规范化包名连字符(英文名);
                            let 替换值 = 规范化值.as_deref().unwrap_or(英文名);
                            编辑表.push(源码映射条目::新建(
                                当前偏移,
                                词元长度,
                                文本响应,
                                替换值,
                            ));
                            输出文本.push_str(&原因[拷贝游标..当前偏移]);
                            输出文本.push_str(替换值);
                            拷贝游标 = 当前偏移 + 词元长度;
                        }
                    }
                }
                // 根段候选判定（基于母语原文；`包` 等已在词法阶段转为英文）
                待定项目根 = 事实.路径根;
                // `让 可变 名称`：声明位内的可变透明传递声明状态；
                // `&可变 类型` 等非声明位的可变不传递，库类型引用仍被替换
                前一关键字 = if 文本响应 == "mut" {
                    前一关键字
                } else {
                    事实.声明关键字
                };
                前一为路径分隔 = false;
                前一为圆点 = false;
            }
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {
                // 空白与注释不打断声明状态、路径限定状态与成员访问状态；
                // 原文随片段拷出，无需单独输出
            }
            _ => {
                // 符号终结声明位；连续两个冒号构成 `::` 路径限定
                前一关键字 = None;
                let 是冒号 = matches!(词元.kind, TokenKind::Colon);
                // 非冒号符号终结项目路径链（`::` 的冒号保持链状态）
                if !是冒号 {
                    在项目路径内 = false;
                    待定项目根 = false;
                }
                前一为路径分隔 = if 是冒号 {
                    前一为路径分隔 || 上一为冒号
                } else {
                    false
                };
                上一为冒号 = 是冒号;
                前一为圆点 = matches!(词元.kind, TokenKind::Dot);
            }
        }
        当前偏移 += 词元长度;
    }
    输出文本.push_str(&原因[拷贝游标..]);
    替换结果 {
        输出文本, 编辑表
    }
}

/// 整份源码是否存在任何替换候选
///
/// 主循环只在两处替换：别名表命中，或路径根位（后跟 `::`、前不是 `::`）命中
/// 模块路径表。声明名收集与逐位置豁免判定都只服务于这些候选，因此候选数为零
/// 的文件整条阶段可以省掉——扫描本身只做一次标识符查表 + 路径根位前瞻，比
/// 「收集声明 + 判定豁免」两趟便宜得多。
///
/// 状态机与主循环逐字对齐（`::` 由两个冒号词元构成、空白/注释不打断），
/// 否则预扫可能漏判候选，把该替换的文件原样返回。
fn 有替换候选(
    词元序列: &[rustc_lexer::Token],
    原因: &str,
    别名映射: &HashMap<String, String>,
    模块路径映射: &HashMap<String, String>,
) -> bool {
    let mut 偏移 = 0usize;
    let mut 上一为冒号 = false;
    let mut 前一为路径分隔 = false;
    for (序号, 词元) in 词元序列.iter().enumerate() {
        let 文本响应 = &原因[偏移..偏移 + 词元.len];
        match 词元.kind {
            TokenKind::Ident => {
                if 别名映射.contains_key(文本响应) {
                    return true;
                }
                if !前一为路径分隔
                    && !模块路径映射.is_empty()
                    && 模块路径映射.contains_key(文本响应)
                    && 后有效为路径分隔(词元序列, 序号)
                {
                    return true;
                }
                前一为路径分隔 = false;
            }
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. } => {}
            _ => {
                let 是冒号 = matches!(词元.kind, TokenKind::Colon);
                前一为路径分隔 = if 是冒号 {
                    前一为路径分隔 || 上一为冒号
                } else {
                    false
                };
                上一为冒号 = 是冒号;
            }
        }
        偏移 += 词元.len;
    }
    false
}

/// 下一个有意义词元（跳过空白/注释）是否为 `(`
///
/// 判定标识符处于「方法调用位」（`实例.方法()`）而非「字段访问位」
///（`实例.字段`）——两者豁免集合不同（字段名不是方法名）。
/// 行选择上限：词法器的词法令牌仅含种类与长度，词元序列与源码
/// 对齐，下标序号即偏移序位。
fn 后有效为左括号(词元序列: &[rustc_lexer::Token], 序号: usize) -> bool {
    词元序列
        .get(序号 + 1..)
        .unwrap_or_default()
        .iter()
        .find(|词元| {
            !matches!(
                词元.kind,
                TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
            )
        })
        .is_some_and(|词元| matches!(词元.kind, TokenKind::OpenParen))
}

/// 下一个有意义词元（跳过空白/注释）是否为 `::`
///
/// 判定标识符处于「路径根位置」（`模块词::项` 的首段）。词法器将
/// `::` 拆分为两个连续冒号词元；空白/注释不打断（与主循环
/// `上一为冒号` 状态对空白的处理一致）。
fn 后有效为路径分隔(词元序列: &[rustc_lexer::Token], 序号: usize) -> bool {
    let mut 冒号计数 = 0;
    for 词元 in 词元序列.get(序号 + 1..).unwrap_or_default() {
        if matches!(
            词元.kind,
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
        ) {
            continue;
        }
        if matches!(词元.kind, TokenKind::Colon) {
            冒号计数 += 1;
            if 冒号计数 >= 2 {
                return true;
            }
            continue;
        }
        return false;
    }
    false
}
