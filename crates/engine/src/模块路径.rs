//! 模块路径替换模块
//! 1. 将源代码中使用语句的中文模块路径段替换为英文路径段
//!    （如 `使用 标准集合::哈希映射` → `使用 std::collections::HashMap`）；
//! 2. 为已知模块路径段添加 `crate::` 前缀（LSP 虚拟项目跨文件引用专用，
//!    原实现在 LSP 侧，迁入引擎统一维护转译规则）；
//! 3. 文件式模块声明的净化（虚拟项目聚合用）与非母语模块名的
//!    `#[path]` 注解（真实项目产物用，CLI 与 LSP 镜像共享同一实现）。
//!
//! 各阶段均以令牌级替换并产出编辑表，供全管线编辑地图组合。
//!
//! 包名规范化：Cargo 包名允许连字符（如 `tracing-subscriber`），但 Rust
//! 代码中引用包必须写下划线形式；使用路径中模块、类型、函数名不含连字符，
//! `-` 只会出现在包名段，故替换时对映射值做连字符到下划线的规范化安全。

use crate::缓存::源码映射条目;
use rustc_lexer::{TokenKind, tokenize};
use std::collections::{HashMap, HashSet};

/// 单阶段替换结果：输出文本与编辑表
///
/// 编辑表以**本阶段输入文本**的字节偏移记录（输入偏移升序、互不重叠），
/// 替换文字为本阶段输出文本。
#[derive(Debug, Clone)]
pub struct 替换结果 {
    /// 替换后的文本
    pub 输出文本: String,
    /// 编辑表
    pub 编辑表: Vec<源码映射条目>,
}

/// 将源代码中的中文模块路径段替换为英文
///
/// # 参数
/// - `源文本`: 待替换的源代码字符串
/// - `路径映射`: 中文路径段 → 英文路径段 的映射表
///
/// # 注意
/// 采用令牌级替换（与别名替换一致）：
/// - 仅替换**完整标识符令牌**，避免破坏组合词
///   （如 `读取全部字符串` 中的 `字符串` 不会被误替换）；
/// - 仅替换**使用语句内**的路径段（含末段与单段路径，如 `使用 文件系统;`），
///   使用语句内不可能出现用户变量，全量替换安全；
/// - 表达式中的 `类型::关联函数`（如 `引用计数::新建`）不替换，
///   留给别名映射处理成 `Rc::new`。
pub fn 替换模块路径(源文本: &str, 路径映射: &HashMap<String, String>) -> String {
    带映射替换模块路径(源文本, 路径映射).输出文本
}

/// 同 [`替换模块路径`]，同时产出编辑表（本阶段输入坐标）
pub fn 带映射替换模块路径(
    源文本: &str,
    路径映射: &HashMap<String, String>,
) -> 替换结果 {
    if 路径映射.is_empty() {
        return 替换结果 {
            输出文本: 源文本.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 使用语句是唯一的替换场合：整份源码里两种词形都不出现时无需分词
    // （直接调用本函数时母语与已转译的使用语句都可能出现）
    if !源文本.contains("use") && !源文本.contains("使用") {
        return 替换结果 {
            输出文本: 源文本.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 不收集令牌向量：主循环只顺序消费一次（每个使用行只命中少数段），
    // 收集一份全文件令牌表是纯分配开销
    替换模块路径迭代(
        源文本,
        路径映射,
        tokenize(源文本).map(|令牌| (令牌.kind, 令牌.len)),
    )
}

/// 同 [`带映射替换模块路径`]，但复用调用方已分好的令牌流
///
/// 引擎的延迟项目上下文入口在词法产物上已经分词一次（为了收集声明名
/// 建项目上下文），而本阶段恰好也是在这份文本上跑，可直接借用那份令牌流，
/// 省掉一次全文件分词。两条入口的输出与编辑表逐字相同（同一序列）。
pub(crate) fn 带令牌替换模块路径(
    源文本: &str,
    路径映射: &HashMap<String, String>,
    令牌切片: &[rustc_lexer::Token],
) -> 替换结果 {
    if 路径映射.is_empty() {
        return 替换结果 {
            输出文本: 源文本.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 与现分词入口同一道早退：本阶段与它逐字等价，只是令牌来源不同
    if !源文本.contains("use") && !源文本.contains("使用") {
        return 替换结果 {
            输出文本: 源文本.to_string(),
            编辑表: Vec::new(),
        };
    }
    替换模块路径迭代(
        源文本,
        路径映射,
        令牌切片.iter().map(|令牌| (令牌.kind, 令牌.len)),
    )
}

/// [`带映射替换模块路径`] 的实现：令牌流由调用方决定是现分词
/// （流式）还是复用已有向量
fn 替换模块路径迭代<迭代流>(
    源文本: &str,
    路径映射: &HashMap<String, String>,
    令牌迭代: 迭代流,
) -> 替换结果
where
    迭代流: Iterator<Item = (TokenKind, usize)>,
{
    let mut 输出文本 = String::with_capacity(源文本.len());
    let mut 编辑表 = Vec::new();
    let mut 当前偏移 = 0;
    // 已刷出的源偏移：未命中的令牌不逐个追加，命中时才把「上次刷出
    // 位置 → 本令牌起点」的原始片段整段拷过去。大文件里令牌数万而命中
    // 只在使用语句行，逐令牌复制是纯开销（2000 行样例本阶段 515.7 → 473.9 微秒）
    let mut 已复制 = 0usize;
    // 使用语句内的路径段才启用模块路径映射；
    // 表达式中的 `类型::关联函数`（如 `引用计数::新建`）应走别名映射，
    // 不能被模块路径映射误替换成 `rc::新建`
    let mut 处于使用语句 = false;

    for (本类别, 本长度) in 令牌迭代 {
        let 文本片段 = &源文本[当前偏移..当前偏移 + 本长度];
        if 本类别 == TokenKind::Ident {
            // 使用语句内所有路径段（含末段或单段）都查映射：
            // 使用中不可能出现用户变量，替换安全；
            // 末段若不在路径映射（如 `服务器` 属于标识符别名），
            // 保持原样交给别名替换处理
            if 处于使用语句 && let Some(英文路径) = 路径映射.get(文本片段) {
                // 包名规范化：映射值中的连字符改为下划线
                //（映射值中的连字符在 Rust 路径里非法）
                let 规范化后 = 规范化包名连字符(英文路径);
                let 替换文字 = 规范化后.as_deref().unwrap_or(英文路径);
                编辑表.push(源码映射条目::新建(
                    当前偏移,
                    本长度,
                    文本片段,
                    替换文字,
                ));
                输出文本.push_str(&源文本[已复制..当前偏移]);
                输出文本.push_str(替换文字);
                已复制 = 当前偏移 + 本长度;
            }
            // 检测使用语句起点（管线中 `使用` 已被词法转译为对应关键字；
            // 直接调用本函数时两种写法均支持）
            if 文本片段 == "use" || 文本片段 == "使用" {
                处于使用语句 = true;
            }
        } else if 本类别 == TokenKind::Semi {
            // 使用语句以分号结束
            处于使用语句 = false;
        }
        当前偏移 += 本长度;
    }
    输出文本.push_str(&源文本[已复制..]);
    替换结果 {
        输出文本, 编辑表
    }
}

/// 将使用路径段中的连字符规范化为下划线（包名规则）
///
/// Cargo 包名允许连字符（如 `tracing-subscriber`），但 Rust 路径中包段
/// 必须写下划线形式。使用路径中模块、类型、函数名均不含连字符，`-` 只会
/// 出现在包名段，故直接替换安全；无需替换时返回无（避免无谓分配）。
/// 别名阶段对使用语句之外的模块词回退替换时复用本函数。
pub(crate) fn 规范化包名连字符(段文本: &str) -> Option<String> {
    段文本.contains('-').then(|| 段文本.replace('-', "_"))
}

/// 可能被加 `crate::` 前缀的路径段：模块名之后（跳过空白）紧跟 `::`
///
/// 供 [`带映射限定模块路径`] 的快速通道使用：这是「该名字会被加
/// 前缀」的**必要条件**（[`路径分隔符在后`] 允许名与 `::` 之间
/// 夹空白或注释）。注释以 `/` 开头，遇到 `/` 时同样视为可能（否则
/// `甲 /*x*/ :: 乙` 会被误判为不可能）；其余后续字节（`(`、`;`、`_` 等）
/// 都足以否定该处出现。
fn 可能成为路径段(内容: &str, 名字: &str) -> bool {
    if 名字.is_empty() {
        return false;
    }
    // 名字可能自重叠（长名字里含更短的自我匹配），每次只前进一个字符
    let 步长 = 名字.chars().next().map_or(1, |字符值| 字符值.len_utf8());
    let mut 起点 = 0usize;
    while let Some(位置) = 内容[起点..].find(名字) {
        let 名字后 = 起点 + 位置 + 名字.len();
        let 剩余 = 内容[名字后..].trim_start_matches([' ', '\t', '\r', '\n']);
        if matches!(剩余.as_bytes().first(), Some(b':') | Some(b'/')) {
            return true;
        }
        起点 += 位置 + 步长;
    }
    false
}

/// 为已知模块路径段添加 `crate::` 前缀
///
/// Rust 2018+ 中，子模块内的裸路径 `模块::项` 无法解析到包的根模块，
/// 必须写成 `crate::模块::项` 或先使用。LSP 虚拟项目把每个方言文件聚合为
/// 同一包的兄弟模块，因此为引用其他模块的路径段自动补全前缀，
/// 使 rust-analyzer 能够解析跨文件引用（引用查找与重命名）。
///
/// 已带前缀的路径（`crate::辅助`、`其他::辅助`）不会被重复处理。
///
/// 遮蔽豁免：模块名与文件内名字（类型声明名、使用导入绑定名）重名时，
/// 裸路径首段按 Rust 作用域解析优先命中后者（如 `结构体 项目配置` 与
/// `模块 项目配置` 重名时，`项目配置::缺省()` 指向结构体关联函数），
/// 此时不得加前缀——前缀会把路径钉死为模块路径（E0425）。文件含通配
/// 导入（`use ...::*;`）时，项目项名集合（跨文件汇总）中的名字视为
/// 可能被通配引入作用域，一并豁免；项目项名集合传空集合时仅按文件内
/// 遮蔽判定（无项目上下文的调用方行为不变）。
pub fn 带映射限定模块路径(
    内容: &str,
    模块名集: &HashSet<String>,
    项目项名集: &HashSet<String>,
) -> 替换结果 {
    if 模块名集.is_empty() || 内容.is_empty() {
        return 替换结果 {
            输出文本: 内容.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 快速通道：本条只给「与模块名逐字节相同的标识符、且后面紧跟 `::`」
    // 加前缀，所以只要每个模块名的每处出现后面都不可能跟 `::`，就一定没有
    // 编辑（无编辑时逐令牌重建的输出恒等于原文）。比「全文包含模块名」更准：
    // 单文件项目的模块名就是文件名干，而 `主函数` 会被词法阶段译成
    // 入口函数名（`fn main()`）——只看子串会永远命中，等于没有早退。
    if !模块名集.iter().any(|名字| 可能成为路径段(内容, 名字)) {
        return 替换结果 {
            输出文本: 内容.to_string(),
            编辑表: Vec::new(),
        };
    }
    // 令牌序列与字节区间：预扫描（遮蔽名收集）与主循环共用
    let mut 令牌区间: Vec<(TokenKind, usize, usize)> = Vec::new();
    let mut 累计偏移 = 0usize;
    for 令牌 in tokenize(内容) {
        let 起点 = 累计偏移;
        累计偏移 += 令牌.len;
        令牌区间.push((令牌.kind, 起点, 累计偏移));
    }
    let (遮蔽名集, 存在通配导入) = 收集遮蔽名(内容, &令牌区间);

    let mut 输出文本 = String::with_capacity(内容.len() + 模块名集.len() * 8);
    let mut 编辑表 = Vec::new();

    for (序号, &(判别类别, 起点, 终点)) in 令牌区间.iter().enumerate() {
        let 文本片段 = &内容[起点..终点];

        if 为空白(判别类别) {
            输出文本.push_str(文本片段);
            continue;
        }

        // 模块路径段：标识符属于已知模块名、后跟 `::`、且不在既有路径段之后
        // （`crate::辅助`、`a::辅助` 中的 `辅助` 已处于路径内，跳过）；
        // 文件内遮蔽名与通配下命中的项目项名不加前缀（保持本地语义）
        let 需加前缀 = 为标识符(判别类别) && {
            let 原始名 = 文本片段.strip_prefix("r#").unwrap_or(文本片段);
            模块名集.contains(原始名)
                && 路径分隔符在后(&令牌区间, 序号)
                && !路径分隔符在前(&令牌区间, 序号)
                && !遮蔽名集.contains(原始名)
                && !(存在通配导入 && 项目项名集.contains(原始名))
        };
        if 需加前缀 {
            let 加前缀后 = format!("crate::{}", 文本片段);
            编辑表.push(源码映射条目::新建(
                起点,
                文本片段.len(),
                文本片段,
                &加前缀后,
            ));
            输出文本.push_str(&加前缀后);
        } else {
            输出文本.push_str(文本片段);
        }
    }
    替换结果 {
        输出文本, 编辑表
    }
}

/// 收集文件内遮蔽名与通配导入标记（`crate::` 前缀豁免判定用）
///
/// 遮蔽名 = 可能让裸路径首段优先解析为本地项的名字：
/// - 类型声明名：结构体、枚举、特征、类型、联合关键字后的名字
///   （类型命名空间，路径首段解析的优先候选）；
/// - 使用导入绑定名：使用语句中每条路径链的末段，别名子句取其别名
///   （容器段与中间段不引入作用域，不收集）。
///
/// 不收集模块声明名：LSP 虚拟项目会以 1:1 空格替换抹除文件式模块
/// 声明（[`剥离文件模块声明`]），声明消失后裸模块名仍须依赖
/// `crate::` 前缀解析，收集会令前缀缺失（回归 E0433 误报）。
///
/// 返回值第二项标记文件是否存在通配导入（`use ...::*;`）：通配引入
/// 的名字不可枚举，调用方回退查项目级项名集合做豁免。
fn 收集遮蔽名<'甲>(
    内容: &'甲 str,
    令牌区间: &[(TokenKind, usize, usize)],
) -> (HashSet<&'甲 str>, bool) {
    let mut 名字集: HashSet<&'甲 str> = HashSet::new();
    let mut 存在通配导入 = false;
    for (序号, &(判别类别, 起点, 终点)) in 令牌区间.iter().enumerate() {
        if !为标识符(判别类别) {
            continue;
        }
        let 文本片段 = &内容[起点..终点];
        if matches!(文本片段, "struct" | "enum" | "trait" | "type" | "union") {
            // 声明名：关键字后第一个非空白令牌为标识符时收集
            let mut 后续序号 = 序号 + 1;
            while 后续序号 < 令牌区间.len() && 为空白(令牌区间[后续序号].0) {
                后续序号 += 1;
            }
            if 后续序号 < 令牌区间.len() && 为标识符(令牌区间[后续序号].0) {
                let (_, 起始, 截止) = 令牌区间[后续序号];
                名字集.insert(&内容[起始..截止]);
            }
        } else if 文本片段 == "use" {
            收集使用绑定(内容, 令牌区间, 序号, &mut 名字集, &mut 存在通配导入);
        }
    }
    (名字集, 存在通配导入)
}

/// 扫描一条使用语句：收集绑定名（路径链末段或别名），标记通配
///
/// 使用关键字后的令牌流以分号结束（使用语句内不出现分号）；花括号容器段
/// （`path::{...}` 的容器路径末段）不引入作用域，遇 `{` 不提交末段；
/// 通配来源段（`路径::*` 的路径末段）同样不是绑定名。
fn 收集使用绑定<'甲>(
    内容: &'甲 str,
    令牌区间: &[(TokenKind, usize, usize)],
    使用序号: usize,
    名字集: &mut HashSet<&'甲 str>,
    存在通配导入: &mut bool,
) {
    let mut 末段: Option<&'甲 str> = None;
    let mut 期待别名 = false;
    for &(判别类别, 起点, 终点) in &令牌区间[(使用序号 + 1)..] {
        if 判别类别 == TokenKind::Semi {
            break;
        }
        let 文本片段 = &内容[起点..终点];
        if 判别类别 == TokenKind::Star {
            *存在通配导入 = true;
            末段 = None;
        } else if matches!(判别类别, TokenKind::Ident | TokenKind::RawIdent) {
            let 名字 = 文本片段.strip_prefix("r#").unwrap_or(文本片段);
            if 名字 == "as" {
                期待别名 = true;
            } else if !matches!(名字, "use" | "pub" | "crate" | "self" | "super") {
                if 期待别名 {
                    名字集.insert(名字);
                    期待别名 = false;
                    末段 = None;
                } else {
                    末段 = Some(名字);
                }
            }
        } else if matches!(判别类别, TokenKind::Comma | TokenKind::CloseBrace) {
            // 链结束（`a::b,` / `a::b}`）：末段为导入绑定名
            if let Some(段名) = 末段.take() {
                名字集.insert(段名);
            }
        } else if 判别类别 == TokenKind::OpenBrace {
            // 进入成员列表（`path::{...}`）：容器段不是绑定名
            末段 = None;
        }
    }
    if let Some(段名) = 末段 {
        名字集.insert(段名);
    }
}

/// 抹除文件式模块声明（`mod 名字;`），供 LSP 虚拟项目内容净化使用
///
/// LSP 虚拟项目将每个方言文件以哈希名托管，并在聚合 `main.rs` 中以
/// `#[path]` 声明为兄弟模块；用户原文中的文件式 `模块 名字;`（转译后为
/// `mod 名字;`）指向的模块文件在虚拟项目中不存在，会被 Cargo 检查报
/// E0583（找不到模块文件）与 E0754（非母语标识符名）。因此发送给
/// rust-analyzer 与写入磁盘前须抹除这类声明。
///
/// 抹除范围连带声明紧邻的修饰：属性（`#[cfg(...)]`、`#[path = ...]`）、
/// 文档注释与可见性（公开、`pub(crate)`）——修饰必须附着于某个项，
/// 声明被抹除后会变成悬空修饰触发新错误；修饰与声明之间允许空白与注释。
///
/// 抹除采用 1:1 字符替换（换行符保留、其余字符替换为等数 UTF-16 单位的
/// 空格），行号与列号同原文严格一致，列映射无需调整；内联模块
/// （`mod 名字 { ... }`）照常参与编译，不被处理。
pub fn 剥离文件模块声明(内容: &str) -> String {
    // 快速通道：判定一个令牌是否文件式声明，要求其文本恰为模块关键字，
    // 因此全文连子串都不含时不可能有声明。LSP 每次按键都会调用
    // 本函数，省掉整趟词法与令牌区间表的分配（绝大多数文件没有模块声明）。
    if !内容.contains("mod") {
        return 内容.to_string();
    }

    // 收集令牌的字节区间：词法器令牌流连续覆盖整个输入
    let mut 令牌区间: Vec<(TokenKind, usize, usize)> = Vec::new();
    let mut 累计偏移 = 0usize;
    for 令牌 in tokenize(内容) {
        let 起点 = 累计偏移;
        累计偏移 += 令牌.len;
        令牌区间.push((令牌.kind, 起点, 累计偏移));
    }

    // 定位所有文件式模块声明：模块关键字 + 名字（隔空白或注释）+ 分号
    let mut 待抹范围: Vec<(usize, usize)> = Vec::new();
    let mut 序号 = 0usize;
    while 序号 < 令牌区间.len() {
        let (判别类别, 起点, 终点) = 令牌区间[序号];
        if 为标识符(判别类别)
            && &内容[起点..终点] == "mod"
            && let Some(分号序号) = 文件模块分号(&令牌区间, 序号)
        {
            // 回溯扩展起点：连带声明前的属性、文档注释、可见性修饰
            let 起始 = 文件模块声明起点(&令牌区间, 内容, 序号);
            待抹范围.push((令牌区间[起始].1, 令牌区间[分号序号].2));
            序号 = 分号序号 + 1;
            continue;
        }
        序号 += 1;
    }
    if 待抹范围.is_empty() {
        return 内容.to_string();
    }

    // 1:1 字符替换：换行保留（行号不变），其余字符按等数 UTF-16 单位
    // 替换为空格（列号不变）
    let mut 输出文本 = String::with_capacity(内容.len());
    let mut 已复制 = 0usize;
    for (起点, 终点) in 待抹范围 {
        输出文本.push_str(&内容[已复制..起点]);
        for 字符值 in 内容[起点..终点].chars() {
            if 字符值 == '\n' || 字符值 == '\r' {
                输出文本.push(字符值);
            } else {
                for _ in 0..字符值.len_utf16() {
                    输出文本.push(' ');
                }
            }
        }
        已复制 = 终点;
    }
    输出文本.push_str(&内容[已复制..]);
    输出文本
}

/// 检查模块关键字令牌是否为文件式声明，是则返回其结束分号的令牌索引
///
/// 文件式：模块关键字后（允许空白或注释）为单个标识符，再后（允许空白或注释）
/// 为分号；内联模块（`mod X { ... }`）返回无。
fn 文件模块分号(
    令牌区间: &[(TokenKind, usize, usize)], 模块序号: usize
) -> Option<usize> {
    let mut 名字已见 = false;
    for (序号, &(判别类别, _, _)) in 令牌区间.iter().enumerate().skip(模块序号 + 1) {
        if 为空白(判别类别) {
            continue;
        }
        if !名字已见 {
            // 模块关键字后必须紧跟名字（含原始标识符）
            if !为标识符(判别类别) {
                return None;
            }
            名字已见 = true;
            continue;
        }
        return matches!(判别类别, TokenKind::Semi).then_some(序号);
    }
    None
}

/// 回溯文件式模块声明的起点：连带声明紧邻的注释、属性与可见性修饰
///
/// 从模块关键字令牌向前回溯：跳过空白（注释与声明之间的空行允许跨越）；
/// 遇到紧邻的注释（如文档注释）直接纳入——悬空文档注释会触发
/// E0585（缺少文档注释目标）；遇到属性结尾（`]`）时纳入配对的 `#[`；
/// 遇到可见性括号（`)`）时纳入配对的 `(` 并确认前置公开修饰；遇到裸
/// 公开修饰直接纳入。任何其他令牌（上一项的结尾等）终止回溯。
/// 返回最前的修饰令牌索引；无修饰时返回模块关键字自身索引。
fn 文件模块声明起点(
    令牌区间: &[(TokenKind, usize, usize)],
    内容: &str,
    模块序号: usize,
) -> usize {
    let mut 最早 = 模块序号;
    let mut 游标 = 模块序号; // 回溯游标：当前已纳入块的第一个令牌索引
    loop {
        // 向前跳过空白（仅空白；注释本身会被纳入或终止回溯）
        let mut 前序 = 游标;
        while 前序 > 0 && 令牌区间[前序 - 1].0 == TokenKind::Whitespace {
            前序 -= 1;
        }
        if 前序 == 0 {
            return 最早;
        }
        let (判别类别, 起点, 终点) = 令牌区间[前序 - 1];
        if matches!(
            判别类别,
            TokenKind::LineComment | TokenKind::BlockComment { .. }
        ) {
            // 紧邻注释（含文档注释）随声明一并抹除
            最早 = 前序 - 1;
            游标 = 前序 - 1;
        } else if 判别类别 == TokenKind::Ident && &内容[起点..终点] == "pub" {
            // 裸可见性修饰
            最早 = 前序 - 1;
            游标 = 前序 - 1;
        } else if 判别类别 == TokenKind::CloseParen {
            // 可见性括号形式的闭圆括号
            let Some(开启序号) = 配对开启(
                令牌区间,
                前序 - 1,
                TokenKind::OpenParen,
                TokenKind::CloseParen,
            ) else {
                return 最早;
            };
            // 开圆括号前须为非空白公开修饰
            let mut 定位 = 开启序号;
            while 定位 > 0 && 为空白(令牌区间[定位 - 1].0) {
                定位 -= 1;
            }
            if 定位 > 0
                && 为标识符(令牌区间[定位 - 1].0)
                && &内容[令牌区间[定位 - 1].1..令牌区间[定位 - 1].2] == "pub"
            {
                最早 = 定位 - 1;
                游标 = 定位 - 1;
            } else {
                return 最早;
            }
        } else if 判别类别 == TokenKind::CloseBracket {
            // 属性结尾
            let Some(开启序号) = 配对开启(
                令牌区间,
                前序 - 1,
                TokenKind::OpenBracket,
                TokenKind::CloseBracket,
            ) else {
                return 最早;
            };
            // 开方括号前须为非空白井号码
            let mut 定位 = 开启序号;
            while 定位 > 0 && 为空白(令牌区间[定位 - 1].0) {
                定位 -= 1;
            }
            if 定位 > 0 && 令牌区间[定位 - 1].0 == TokenKind::Pound {
                最早 = 定位 - 1;
                游标 = 定位 - 1;
            } else {
                return 最早;
            }
        } else {
            return 最早;
        }
    }
}

/// 向前查找与闭合序号处闭合令牌配对的开启令牌索引
fn 配对开启(
    令牌区间: &[(TokenKind, usize, usize)],
    闭合序号: usize,
    开启类别: TokenKind,
    闭合类别: TokenKind,
) -> Option<usize> {
    let mut 深度 = 0usize;
    for 序号 in (0..=闭合序号).rev() {
        let 本类别 = 令牌区间[序号].0;
        if 本类别 == 闭合类别 {
            深度 += 1;
        } else if 本类别 == 开启类别 {
            深度 -= 1;
            if 深度 == 0 {
                return Some(序号);
            }
        }
    }
    None
}

/// 是否为空白或注释令牌
fn 为空白(判别类别: TokenKind) -> bool {
    matches!(
        判别类别,
        TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
    )
}

/// 是否为标识符令牌（含原始标识符）
fn 为标识符(判别类别: TokenKind) -> bool {
    matches!(判别类别, TokenKind::Ident | TokenKind::RawIdent)
}

/// 检查指定令牌之后两个连续的非空白令牌是否为 `::`
///
/// rustc 将 `::` 拆分为两个冒号令牌。
fn 路径分隔符在后(令牌区间: &[(TokenKind, usize, usize)], 当前序号: usize) -> bool {
    let mut 冒号计数 = 0;
    for &(判别类别, _, _) in &令牌区间[(当前序号 + 1)..] {
        if 为空白(判别类别) {
            continue;
        }
        if matches!(判别类别, TokenKind::Colon) {
            冒号计数 += 1;
            if 冒号计数 >= 2 {
                return true;
            }
            continue;
        }
        return false;
    }
    false
}

/// 检查指定令牌之前两个连续的非空白令牌是否为 `::`
fn 路径分隔符在前(令牌区间: &[(TokenKind, usize, usize)], 当前序号: usize) -> bool {
    let mut 冒号计数 = 0;
    for &(判别类别, _, _) in 令牌区间[..当前序号].iter().rev() {
        if 为空白(判别类别) {
            continue;
        }
        if matches!(判别类别, TokenKind::Colon) {
            冒号计数 += 1;
            if 冒号计数 >= 2 {
                return true;
            }
        } else {
            return false;
        }
    }
    false
}

/// 为非母语模块名的文件式声明 `mod 名称;` 补充 `#[path = "名称.rs"]` 注解。
///
/// rustc 拒绝加载非母语标识符对应的模块文件（E0754），而方言项目
/// 的模块文件常以母语命名（如 `src/数学.zh` → `src/数学.rs`）；
/// 显式指定路径后 rustc 可正常加载。仅处理以分号结尾的文件式声明，
/// 内联模块块（`mod 名称 { ... }`）与英文名不受影响。
///
/// 适用于包的根文件（`main.rs`/`lib.rs`）：子模块与根文件同处源码目录。
/// 非根文件的多层目录布局请用 [`注解嵌套模块并返回行映射`]，
/// 虚拟托管布局（平铺哈希产物）请用 [`注解模块路径并返回行映射`]。
pub fn 注解非母语模块(源文本: &str) -> String {
    注解非母语模块并返回行映射(源文本).0
}

/// 非根模块文件（多层目录）的 `#[path]` 注解，并返回行映射。
///
/// 自身词干为当前文件自身词干（如 `src/领域.rs` 传 `"领域"`）：
/// 其中 `mod 工具;` 的子文件实际位于 `src/领域/工具.rs`，而 `#[path]`
/// 相对当前文件所在源码目录解析，故注入 `#[path = "领域/工具.rs"]`。
/// 更深层同理（`src/领域/工具.rs` 传 `"工具"` → `#[path = "工具/内部.rs"]`，
/// 相对 `src/领域/`）。仅注解非母语名；英文名遵循 rustc 默认查找。
pub fn 注解嵌套模块并返回行映射(
    源文本: &str, 自身词干: &str
) -> (String, Vec<usize>) {
    注解模块路径并返回行映射(源文本, |名字| {
        (!名字.is_ascii()).then(|| format!("{自身词干}/{名字}.rs"))
    })
}

/// 通用文件式模块声明 `#[path]` 注解器，并返回磁盘行 → 引擎直行映射。
///
/// 解析器给出相对路径时在声明前插入 `#[path = "<相对路径>"]`；
/// 返回无时不注解（如子文件不存在，保留 rustc 原生 E0583）。
/// 仅处理分号结尾的文件式声明与尚无 `#[path]` 的声明；
/// 内联模块块（`mod 名 { ... }`）不受影响。
///
/// 供三类布局复用：根文件（`名.rs`）、多层真实布局（`自词干/名.rs`）、
/// 虚拟托管布局（平铺哈希产物，`<hash>.rs`）。
pub fn 注解模块路径并返回行映射(
    源文本: &str,
    解析器: impl Fn(&str) -> Option<String>,
) -> (String, Vec<usize>) {
    注解模块路径实现(源文本, &解析器)
}

/// 同 [`注解非母语模块`]，并额外返回磁盘产物行 → 引擎直出行映射
///
/// 每处注解在模块声明所在行前插入一整行 `#[path = ...]`，其后所有磁盘
/// 行号相对引擎直出产物整体偏移（偏移量 = 该行之前的注解数）。诊断回译时
/// 必须先用本映射把 rustc 报告的磁盘行号换算回引擎直出行号，再走以引擎
/// 直出产物为基准的列映射；否则多模块入口文件（如 `main.zh` 声明 3 个
/// `模块 xxx;`）的诊断行号会系统性偏移 3 行。映射从 0 起计数：
/// `行映射[磁盘行] = 引擎直出行`（注解行归属其所在模块声明行）。
pub fn 注解非母语模块并返回行映射(源文本: &str) -> (String, Vec<usize>) {
    注解模块路径实现(源文本, &|名字| {
        (!名字.is_ascii()).then(|| format!("{名字}.rs"))
    })
}

/// [`注解模块路径并返回行映射`] 的实现体
fn 注解模块路径实现(
    源文本: &str,
    解析器: &dyn Fn(&str) -> Option<String>,
) -> (String, Vec<usize>) {
    // 文件首部字节序标记：rustc 仅接受文件第一个字符位置的字节序标记。首行恰好是
    // 模块声明时，注解行插在声明前会把字节序标记挤到行内（
    // `unknown start of token: \u{feff}`，编译失败）。剥离后统一前置，
    // 字节序标记不占行，行映射不受影响。
    let (字节序标记, 正文) = if let Some(剩余文本) = 源文本.strip_prefix("\u{FEFF}") {
        ("\u{FEFF}", 剩余文本)
    } else {
        ("", 源文本)
    };
    let 令牌们: Vec<_> = tokenize(正文).collect();
    // 逐令牌的字节偏移（词法器令牌流覆盖全源，偏移连续）
    let mut 偏移们: Vec<usize> = Vec::with_capacity(令牌们.len());
    let mut 累计 = 0usize;
    for 令牌 in &令牌们 {
        偏移们.push(累计);
        累计 += 令牌.len;
    }
    let 跳过杂项 = |起点序号: usize| {
        let mut 序号 = 起点序号;
        while 序号 < 令牌们.len()
            && matches!(
                令牌们[序号].kind,
                TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
            )
        {
            序号 += 1;
        }
        序号
    };
    let mut 插入点集: Vec<(usize, String)> = Vec::new();
    for (序号, 令牌) in 令牌们.iter().enumerate() {
        if 令牌.kind != TokenKind::Ident {
            continue;
        }
        let 文本片段 = &正文[偏移们[序号]..偏移们[序号] + 令牌.len];
        if 文本片段 != "mod" {
            continue;
        }
        let 名字序号 = 跳过杂项(序号 + 1);
        let Some(名字令牌) = 令牌们.get(名字序号) else {
            continue;
        };
        if 名字令牌.kind != TokenKind::Ident {
            continue;
        }
        let 分号序号 = 跳过杂项(名字序号 + 1);
        // 仅文件式声明（分号结尾）需要注解；内联模块块以开大括号开头
        if !matches!(
            令牌们.get(分号序号).map(|令牌| 令牌.kind),
            Some(TokenKind::Semi)
        ) {
            continue;
        }
        let 名字 = &正文[偏移们[名字序号]..偏移们[名字序号] + 名字令牌.len];
        let Some(模块路径) = 解析器(名字) else {
            continue;
        };
        // 插入点：若有可见性修饰（公开），注解必须在公开修饰之前
        let mut 插入位置 = 偏移们[序号];
        let mut 回退序号 = 序号;
        while 回退序号 > 0
            && matches!(
                令牌们[回退序号 - 1].kind,
                TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
            )
        {
            回退序号 -= 1;
        }
        if 回退序号 > 0
            && 令牌们[回退序号 - 1].kind == TokenKind::Ident
            && &正文[偏移们[回退序号 - 1]..偏移们[回退序号 - 1] + 令牌们[回退序号 - 1].len] == "pub"
        {
            插入位置 = 偏移们[回退序号 - 1];
        }
        // 已有路径注解时不重复添加：注解可独占多行，需向上逐行扫描属性链
        let 行首 = 正文[..插入位置]
            .rfind('\n')
            .map(|索引| 索引 + 1)
            .unwrap_or(0);
        let mut 扫描起点 = 行首;
        let mut 已有路径属性 = false;
        loop {
            let 当前行 = 正文[扫描起点..插入位置].lines().next().unwrap_or("");
            // 首行可能是模块声明所在行的缩进前缀；上移后的行应为属性行
            if 扫描起点 != 行首 || 当前行.trim_start().starts_with("#[") {
                if 当前行.contains("#[path") {
                    已有路径属性 = true;
                    break;
                }
                if !当前行.trim_start().starts_with("#[") {
                    break; // 属性链被普通行或空行打断
                }
            }
            if 扫描起点 == 0 {
                break;
            }
            let 前行首 = 正文[..扫描起点 - 1]
                .rfind('\n')
                .map(|索引| 索引 + 1)
                .unwrap_or(0);
            if 前行首 == 扫描起点 {
                break;
            }
            扫描起点 = 前行首;
        }
        if 已有路径属性 {
            continue;
        }
        let 缩进 = &正文[行首..插入位置];
        插入点集.push((插入位置, format!("#[path = \"{模块路径}\"]\n{缩进}")));
    }
    // 按插入点升序回放：引擎直出文本的换行推进引擎行号；注解插入文本
    // 的换行不推进（插入行仍归属其所在模块声明行）
    let mut 结果文本 = String::with_capacity(
        正文.len() + 插入点集.iter().map(|(_, 片段)| 片段.len()).sum::<usize>(),
    );
    结果文本.push_str(字节序标记);
    let mut 行映射: Vec<usize> = vec![0];
    let mut 引擎行 = 0usize;
    let mut 上次位置 = 0usize;
    for (插入位置, 片段) in &插入点集 {
        追加并维护行映射(
            &mut 结果文本,
            &mut 行映射,
            &mut 引擎行,
            &正文[上次位置..*插入位置],
            true,
        );
        追加并维护行映射(&mut 结果文本, &mut 行映射, &mut 引擎行, 片段, false);
        上次位置 = *插入位置;
    }
    追加并维护行映射(
        &mut 结果文本,
        &mut 行映射,
        &mut 引擎行,
        &正文[上次位置..],
        true,
    );
    (结果文本, 行映射)
}

/// 追加文本并同步维护行映射：来自引擎为假（注解插入文本）的换行
/// 不推进引擎行号，其余同普通文本
fn 追加并维护行映射(
    输出文本: &mut String,
    行映射: &mut Vec<usize>,
    引擎行: &mut usize,
    文本片段: &str,
    来自引擎: bool,
) {
    for 字符值 in 文本片段.chars() {
        输出文本.push(字符值);
        if 字符值 == '\n' {
            if 来自引擎 {
                *引擎行 += 1;
            }
            行映射.push(*引擎行);
        }
    }
}

