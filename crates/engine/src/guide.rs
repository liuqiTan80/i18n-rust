//! 母语编程指南渲染（`rzc cheat` / `rzc guide` / `rzc init --ai` 共用）
//!
//! 把「词条表渲染」从 CLI 下沉到引擎后，`guide` 与 `init --ai` 复用同一
//! 数据源与表格版式：语言包词条一旦更新，三条出口同步生效，不会出现
//! 指南与 `rzc cheat` 输出漂移。
//!
//! 文本模板取自各语言包 `ui.toml` 的 `["界面消息"]` 节（`guide_*` 键），
//! 调用方须先 [`crate::语言::set_language`]，与错误/诊断输出同一约定。
//! 词条表本体（分类/表头/危险等级标签/内容）与 `rzc cheat` 一致——
//! 附录A、README 与既有测试均以该版式为基准；同一分类内行的先后顺序沿用
//! 原实现（来自 HashMap 迭代序，不保证稳定，历史行为同样如此）。

use crate::mapping_manager::MappingManager;

/// 词条表分类标题（双语固定，与历史 `rzc cheat` 输出一致）
const TITLE_KEYWORDS: &str = "Keywords / 关键字";
const TITLE_MODULE_PATHS: &str = "Module paths / 模块路径";
const TITLE_ALIASES: &str = "Aliases / 别名";
const TITLE_DERIVES: &str = "Derives / 派生特征";

/// 词条表行元组：`(母语词条, 英文名, 危险等级标签, 备注)`
type CheatRow = (String, String, String, String);
/// 词条表分类：`(标题, 行集合)`
type CheatSection = (&'static str, Vec<CheatRow>);

/// 取全量词条表：过滤恒等条目（native == rust）后按分类返回行
///
/// 行元组为 [`CheatRow`]，顺序与原 `rzc cheat` 渲染一致
/// （HashMap 迭代序不保证，历史行为同样如此）。
fn cheat_rows(manager: &MappingManager) -> Vec<CheatSection> {
    let maps: [(&str, &std::collections::HashMap<String, String>); 4] = [
        (TITLE_KEYWORDS, manager.get_keyword_map()),
        (TITLE_MODULE_PATHS, manager.get_module_path_map()),
        (TITLE_ALIASES, manager.get_alias_map()),
        (TITLE_DERIVES, manager.get_derive_map()),
    ];
    maps.into_iter()
        .map(|(title, map)| {
            let rows = map
                .iter()
                .filter(|(native, en)| native != en)
                .map(|(native, en)| {
                    let danger = manager.danger_of(native);
                    (
                        native.clone(),
                        en.clone(),
                        danger.level.label().to_string(),
                        danger.note,
                    )
                })
                .collect();
            (title, rows)
        })
        .collect()
}

/// Markdown 表格单元转义：竖线与换行会破坏表格结构
fn markdown_cell(text: &str) -> String {
    text.replace('|', "\\|").replace(['\n', '\r'], " ")
}

/// 危险等级图例（markdown 版式，逐字节对齐原 `rzc cheat --markdown` 输出）
fn danger_legend_markdown() -> String {
    let mut s = String::new();
    s.push_str("> **危险等级图例**：\n");
    s.push_str(
        "> - `纯安全`：只在受保护位置（声明位/方法调用位/use 路径段）替换，不改写自定义标识符；\n",
    );
    s.push_str("> - `会改写标识符`：词法层任意位置替换，同名自定义标识符也会被改写；\n");
    s.push_str(
        "> - `会 panic`：运行时可能 panic，默认请选安全同义条目，仅调用处显式选择时使用；\n",
    );
    s.push_str("> - 同一词条同时涉及多种风险时以 `+` 连接，并在「备注」列说明。\n\n");
    s
}

/// 渲染 `rzc cheat` 完整输出（markdown 与终端两种版式）
///
/// 与下沉前的 CLI 实现内容一致（分类/版式/条目相同，同一分类内行序为 HashMap 迭代序）；
/// `lang_code` 仅用于标题与表头列名。
pub fn render_cheat(manager: &MappingManager, lang_code: &str, markdown: bool) -> String {
    let sections = cheat_rows(manager);
    let total: usize = sections.iter().map(|(_, rows)| rows.len()).sum();
    let mut out = String::new();
    if total == 0 {
        out.push_str(&format!("rzc cheat — {lang_code} ↔ Rust\n\n"));
        out.push_str("This language pack maps every identifier to itself (identity mapping).\n");
        out.push_str("No cheat sheet is needed — write Rust as usual.\n");
        return out;
    }
    if markdown {
        out.push_str(&format!("# rzc cheat — {lang_code} ↔ Rust ({total})\n\n"));
        out.push_str(&danger_legend_markdown());
        for (title, rows) in &sections {
            if rows.is_empty() {
                continue;
            }
            out.push_str(&format!("## {title}\n\n"));
            out.push_str(&format!(
                "| {lang_code} | Rust | 危险等级 | 备注 |\n|---|---|---|---|\n"
            ));
            for (native, en, level, note) in rows {
                out.push_str(&format!(
                    "| {native} | `{en}` | {level} | {} |\n",
                    markdown_cell(note)
                ));
            }
            out.push('\n');
        }
        out.push_str(&format!(
            "> Generated by `rzc cheat {lang_code} --markdown`.\n"
        ));
    } else {
        out.push_str(&format!(
            "rzc cheat — {lang_code} ↔ Rust（共 {total} 条）\n\n"
        ));
        out.push_str(
            "危险等级：纯安全 = 受保护位置替换｜会改写标识符 = 任意位置替换（同名标识符会被改写）｜会 panic = 运行时可能 panic（仅显式选择）\n\n",
        );
        for (title, rows) in &sections {
            if rows.is_empty() {
                continue;
            }
            let width = rows
                .iter()
                .map(|(n, ..)| n.chars().count())
                .max()
                .unwrap_or(0);
            out.push_str(&format!("── {title} ──\n"));
            for (native, en, level, note) in rows {
                let pad = width - native.chars().count();
                let note = if note.is_empty() {
                    String::new()
                } else {
                    format!("  // {note}")
                };
                out.push_str(&format!(
                    "  {native}{}  {en}  [{level}]{note}\n",
                    " ".repeat(pad)
                ));
            }
            out.push('\n');
        }
    }
    out
}

/// 渲染 markdown 词条表本体（危险等级图例 + 全部分类表，不含标题行）
///
/// 供 [`render_agent_guide`] 组装：指南自身有一级标题，此处只出图例与表格，
/// 版式与 `rzc cheat --markdown` 完全一致。
pub fn render_cheat_tables_markdown(manager: &MappingManager, lang_code: &str) -> String {
    let mut out = danger_legend_markdown();
    for (title, rows) in cheat_rows(manager) {
        if rows.is_empty() {
            continue;
        }
        out.push_str(&format!("### {title}\n\n"));
        out.push_str(&format!(
            "| {lang_code} | Rust | 危险等级 | 备注 |\n|---|---|---|---|\n"
        ));
        for (native, en, level, note) in &rows {
            out.push_str(&format!(
                "| {native} | `{en}` | {level} | {} |\n",
                markdown_cell(note)
            ));
        }
        out.push('\n');
    }
    out
}

/// 渲染面向学习者与 AI 助手的母语编程指南（markdown）
///
/// 结构：标题 → 引言语 → 书写规则（标识符/标点/危险等级/工作流/实测坑/待译清单）
/// → 入口示例（语言包 `template_main`）→ 全量词条表 → 尾注。
/// 全部文案来自 `ui.toml` 的 `guide_*` 键，随 `set_language` 切换。
pub fn render_agent_guide(manager: &MappingManager, lang_code: &str) -> String {
    use crate::语言::{f, t};
    let sections = cheat_rows(manager);
    let total: usize = sections.iter().map(|(_, rows)| rows.len()).sum();
    let mut out = String::new();
    out.push_str(&format!("{}\n\n", f("guide_title", &[lang_code])));
    out.push_str(&format!("{}\n\n", f("guide_intro", &[lang_code])));
    out.push_str(&format!("{}\n", t("guide_rules_head")));
    for key in [
        "guide_rule_keywords",
        "guide_rule_ident",
        "guide_rule_punct",
        "guide_rule_danger",
    ] {
        out.push_str(&format!("{}\n", t(key)));
    }
    // 工作流规则含 `{}` 占位（入口文件扩展名 = 语言码），须带参渲染
    out.push_str(&format!("{}\n", f("guide_rule_workflow", &[lang_code])));
    // 实测坑（三引号多行字符串 / parent() 返回借用）：来自真实项目踩坑，
    // 写进指南让 AI 助手少绕弯路；词条补齐母语支持后可删除本条规则
    out.push_str(&format!("{}\n", t("guide_rule_pitfalls")));
    out.push_str(&format!("{}\n", t("guide_rule_gaps")));
    out.push('\n');
    out.push_str(&format!("{}\n\n", t("guide_example_head")));
    out.push_str("```rust\n");
    out.push_str(t("template_main").trim_end());
    out.push_str("\n```\n\n");
    out.push_str(&format!(
        "{}\n\n",
        f("guide_table_head", &[&total.to_string()])
    ));
    out.push_str(&render_cheat_tables_markdown(manager, lang_code));
    out.push_str(&format!("{}\n", t("guide_footer")));
    out
}
