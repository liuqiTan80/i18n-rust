//! 转译产物坐标 → 母语源码坐标的列映射
//!
//! 转译是逐令牌的原地替换，不增删换行，因此**行号恒等**；但中英文令牌
//! 长度不同（「让」换出的英文写法是三个字母，「可变」也是三个字母），同一行
//! 内的列号会发生偏移，必须回放替换过程才能还原到母语源码的列。
//!
//! 本模块供命令行使用。**不可与 LSP 侧的列映射混用**：LSP 协议要求 UTF-16
//! 代码单元列（`lsp/src/translation_cache.rs`），而命令行输出面向终端，
//! 采用**字符数**列——与 rustc 的 JSON 诊断里报告起始列的那个字段口径一致。
//! 算法同源，但列口径不同，混用会在非基本多文种平面字符（表情符号等）上产生偏移。
//!
//! 设计（中文原生重构，非英文版的逐句对译）：
//! - **行首分段点不再入库**。英文版每行都要塞一个 `(0, 0)` 哨兵，构建函数的
//!   初始化、跨行时的新建行、回译坐标的循环初值三处重复同一个字面量；
//!   改成"每行只存真正发生长度变化的点"，行首零点由 `回译坐标` 侧的常量给出。
//!   附带收益：`列位点` 不再需要「可复制」「可克隆」「部分相等」「全等」四个
//!   派生特征——原版派生是为了 `point = *p` 这种写法，重构后全程持引用。
//! - **直出判定不用谓词宏**。词形「匹配」是一词多译（分支匹配关键字与
//!   布尔谓词宏各占一支），而语言包没有谓词宏的唯一中文词形；这里改用文本自身
//!   的判据（注释前缀 + 全白，见 `是否直出`），既不碰「匹配」，也不引入「令牌
//!   种类」的变体路径。
//! - **偏移索引改为升序游标归并**。英文版先把编辑表倒进 `哈希映射` 再逐令牌查，
//!   而管线保证「编辑表按母语源偏移升序」（转译产物里那条全管线映射表），
//!   令牌起点又单调递增，因此一个只前进的游标就够了：省掉一次哈希建表与
//!   全部堆分配。代价是把那条**顺序不变量从隐含变成正确性依赖**（见台账）。

use crate::缓存::源码映射条目;

/// 行内列映射分段点：一次长度变化的替换发生后记录的 (产物列, 母语列)
///
/// 两个分段点之间产物与母语同步增长（未替换文本原样输出），
/// 故段内可直接用 `产物列位 - 母语列位` 的恒定差值换算。
pub struct 列位点 {
    /// 转译产物的行内列（从零起算，字符数）
    pub 产物列位: u32,
    /// 母语源码的行内列（从零起算，字符数）
    pub 母语列位: u32,
}

/// 行首（零偏移）分段点：查询侧的起点，不参与建表
const 行首点: 列位点 = 列位点 {
    产物列位: 0,
    母语列位: 0,
};

/// 逐行列映射表：回放转译过程得到，供诊断列号回译使用
pub struct 列位映射表 {
    /// `全部行[i]` 为第 i 行（从零起算）的分段点，按 `产物列位` 升序；
    /// 行首零点不入库（由 `行首点` 常量表达）
    全部行: Vec<Vec<列位点>>,
}

/// 空白与注释是否不经替换直出：产物与母语在这段文本上逐字符等长
///
/// 判据取自文本本身而非令牌种类枚举：谓词宏与「令牌种类」变体路径
/// 都没有唯一中文词形。分词器产出的令牌里，仅空白段会裁剪为空，
/// 仅注释段会以 `//`、`/*` 开头，故三个前缀/空白判定与原来的三个变体一一对应。
fn 是否直出(片段: &str) -> bool {
    片段.starts_with("//") || 片段.starts_with("/*") || 片段.trim().is_empty()
}

impl 列位映射表 {
    /// 回放转译过程，构建逐行的列映射
    ///
    /// `母语源` 为母语源码，`管线编辑` 为转译管线的全量编辑表
    /// （转译产物的全管线映射表，**必须按 `源偏移` 升序**——
    /// 游标归并把这条顺序当成前提）。未命中编辑表的令牌视为原样输出。
    pub fn 回放生成(母语源: &str, 管线编辑: &[源码映射条目]) -> Self {
        let mut 全部行: Vec<Vec<列位点>> = Vec::new();
        let mut 当前行: Vec<列位点> = Vec::new();
        let mut 母语列: u32 = 0;
        let mut 产物列: u32 = 0;
        let mut 偏移: usize = 0;
        let mut 游标: usize = 0;

        for 词元 in rustc_lexer::tokenize(母语源) {
            let 起点 = 偏移;
            let 片段 = &母语源[起点..][..词元.len];
            偏移 += 词元.len;

            // 空白与注释原样输出，但可能跨行（块注释、连续换行）：按换行切段，
            // 段与段之间收尾上一行、把行内列归零
            if 是否直出(片段) {
                let mut 非首段 = false;
                for 段 in 片段.split('\n') {
                    if 非首段 {
                        全部行.push(当前行);
                        当前行 = Vec::new();
                        母语列 = 0;
                        产物列 = 0;
                    }
                    非首段 = true;
                    let 段宽 = 段.chars().count() as u32;
                    母语列 += 段宽;
                    产物列 += 段宽;
                }
                continue;
            }

            // 游标只前进：跳过起点已落在本令牌之前的编辑条目
            while 游标 < 管线编辑.len() && 管线编辑[游标].源偏移 < 起点 {
                游标 += 1;
            }
            let 母语宽 = 片段.chars().count() as u32;
            let 产物宽 = if 游标 < 管线编辑.len() && 管线编辑[游标].源偏移 == 起点
            {
                管线编辑[游标].替换文字.chars().count() as u32
            } else {
                母语宽
            };

            母语列 += 母语宽;
            产物列 += 产物宽;

            // 仅长度变化时记录分段点：长度未变则该令牌前后列关系不变
            if 产物宽 != 母语宽 {
                当前行.push(列位点 {
                    产物列位: 产物列,
                    母语列位: 母语列,
                });
            }
        }

        全部行.push(当前行);
        Self { 全部行 }
    }

    /// 把转译产物坐标（行、列均从一起算）映射回母语源码坐标
    ///
    /// 转译不增删换行，行号恒等返回。
    /// 落在替换区间内的位置按差值近似到最近的中文令牌起点——
    /// 这与 LSP 侧一致，诊断只需指向正确的令牌，无需精确到字符内部。
    ///
    /// 行号越界（映射表行数不足）时原样返回，不臆造坐标。
    pub fn 回译坐标(&self, 行号: u32, 列位: u32) -> (u32, u32) {
        let Some(行点们) = self.全部行.get(行号.saturating_sub(1) as usize) else {
            return (行号, 列位);
        };
        let 目标 = 列位.saturating_sub(1);
        // 分段点按产物列位升序，因此「产物列位 <= 目标」的点恰好构成一个前缀：
        // 前缀长度减一即所求；一个都不满足时退回行首零点
        let 前缀长 = 行点们.iter().filter(|候选| 候选.产物列位 <= 目标).count();
        let 点 = if 前缀长 > 0 {
            &行点们[前缀长 - 1]
        } else {
            &行首点
        };
        let 差值 = 点.产物列位 as i32 - 点.母语列位 as i32;
        (行号, (目标 as i32 - 差值).max(0) as u32 + 1)
    }

    /// 映射表覆盖的行数（供测试与诊断用）
    pub fn 覆盖行数(&self) -> usize {
        self.全部行.len()
    }
}

#[cfg(test)]
mod 母语测试 {
    use super::*;

    /// 产物 `    let mut 数量 = 10;`，母语 `    让 可变 数量 = 10;`
    ///
    /// 字节偏移：4 个前导空格后「让」占 3 字节（偏移 4），
    /// 再 1 空格后「可变」占 6 字节（偏移 8）。
    fn 示例<'甲>() -> (&'甲 str, Vec<源码映射条目>) {
        let 编辑 = vec![
            源码映射条目::new(4, 3, "让", "let"),
            源码映射条目::new(8, 6, "可变", "mut"),
        ];
        ("    让 可变 数量 = 10;", 编辑)
    }

    #[test]
    fn 关键字处列位回译() {
        let (源, 编辑) = 示例();
        let 映射表 = 列位映射表::回放生成(源, &编辑);
        // 产物列 5（从一起算）= 英文「让」写法的首字符 → 母语列 5 = 「让」
        assert_eq!(映射表.回译坐标(1, 5), (1, 5));
        // 产物列 9 = 英文「可变」写法的首字符 → 母语列 7 = 「可」
        assert_eq!(映射表.回译坐标(1, 9), (1, 7));
        // 产物列 13 = 「数」 → 母语列 10 = 「数」（未被替换，但受前面两个替换影响）
        assert_eq!(映射表.回译坐标(1, 13), (1, 10));
        // 产物列 16 = `=` → 母语列 13 = `=`
        assert_eq!(映射表.回译坐标(1, 16), (1, 13));
    }

    /// 前导空格未被替换，列号应恒等
    #[test]
    fn 首个替换之前的列位恒等() {
        let (源, 编辑) = 示例();
        let 映射表 = 列位映射表::回放生成(源, &编辑);
        assert_eq!(映射表.回译坐标(1, 1), (1, 1));
        assert_eq!(映射表.回译坐标(1, 4), (1, 4));
    }

    /// 空编辑表 → 恒等映射（转译未改动任何令牌时不应漂移）
    #[test]
    fn 无编辑时全列恒等() {
        let 映射表 = 列位映射表::回放生成("    让 数量 = 1;", &[]);
        for 列号 in 1..=15 {
            assert_eq!(映射表.回译坐标(1, 列号 as u32), (1, 列号 as u32));
        }
    }

    /// 多行：行号恒等，且每行的列差独立累积（不跨行污染）
    #[test]
    fn 多行各自独立() {
        // 字节偏移：第 1 行「让 x = 1;」占 0..9（「让」3 字节 + 7 个 ASCII），
        // `\n` 在偏移 10，故第 2 行「让」在 11、「可变」在 15
        let 编辑 = vec![
            源码映射条目::new(0, 3, "让", "let"),
            源码映射条目::new(11, 3, "让", "let"),
            源码映射条目::new(15, 6, "可变", "mut"),
        ];
        let 映射表 = 列位映射表::回放生成("让 x = 1;\n让 可变 y = 2;", &编辑);
        assert_eq!(映射表.覆盖行数(), 2);

        // 第 1 行：`let x = 1;` 列 5 = `x` → 母语列 3 = `x`
        assert_eq!(映射表.回译坐标(1, 5), (1, 3));
        // 第 2 行：`let mut y = 2;` 列 9 = `y` → 母语列 6 = `y`
        assert_eq!(映射表.回译坐标(2, 9), (2, 6));
    }

    /// 行号越界时原样返回，不臆造坐标
    #[test]
    fn 行号越界原样透传() {
        let (源, 编辑) = 示例();
        let 映射表 = 列位映射表::回放生成(源, &编辑);
        assert_eq!(映射表.回译坐标(99, 7), (99, 7));
    }

    /// 列号为 0（防御：上游给出非法坐标）不应下溢恐慌
    #[test]
    fn 列位为零不下溢() {
        let (源, 编辑) = 示例();
        let 映射表 = 列位映射表::回放生成(源, &编辑);
        assert_eq!(映射表.回译坐标(1, 0), (1, 1));
    }

    /// 跨行注释：换行后的行内列必须从零重算（重构改走按换行切段的路径）
    ///
    /// 英文版逐字符推进这段列号，却没有一条测试覆盖"注释跨行"；
    /// 这里把行边界当成显式契约钉住。
    #[test]
    fn 块注释跨行后列位归零() {
        // 字节布局：`/* 说明 */` 占 0..12（斜杠 2 + 空格 1 +「说明」6 + 空格 1 + 星斜 2），
        // `\n` 在偏移 12，故第 2 行的「让」在偏移 13
        let 编辑 = vec![源码映射条目::new(13, 3, "让", "let")];
        let 映射表 = 列位映射表::回放生成("/* 说明 */\n让 x = 1;", &编辑);
        assert_eq!(映射表.覆盖行数(), 2);
        // 产物第 2 行 `let x = 1;` 列 5 = `x` → 母语列 3
        assert_eq!(映射表.回译坐标(2, 5), (2, 3));
    }

    /// 同一偏移上的多条编辑：取第一条（游标语义，固定下来防行为漂移）
    ///
    /// 英文版的 `哈希映射` 倒表会让**后写覆盖前写**，与这里的取首条不同；
    /// 管线本不该在同偏移放两条编辑，此测试只为把可预期行为钉死。
    #[test]
    fn 同偏移多条编辑取第一条() {
        let 编辑 = vec![
            源码映射条目::new(0, 3, "让", "let"),
            源码映射条目::new(0, 3, "让", "lethan"),
        ];
        let 映射表 = 列位映射表::回放生成("让 x = 1;", &编辑);
        // 取首条即按三字母的英文写法推进：产物列 5 回译到母语列 3
        // （若按哈希映射的后写覆盖取那条六字母的替换文字，产物列推进 6，列 5 落在点前 → 恒等返回 (1, 5)）
        assert_eq!(映射表.回译坐标(1, 5), (1, 3));
    }

    /// 等长替换不产生分段点：列关系在该令牌前后不变
    #[test]
    fn 等长替换不留分段点() {
        // 「让」占一个字符：换成三字母的英文写法会留点，换成单字母的写法则等长
        let 编辑 = vec![源码映射条目::new(0, 3, "让", "y")];
        let 映射表 = 列位映射表::回放生成("让 x = 1;", &编辑);
        assert_eq!(映射表.全部行[0].len(), 0);
        assert_eq!(映射表.回译坐标(1, 5), (1, 5));
    }
}
